#!/usr/bin/env bash
# SessionStart hook: печатает в контекст карту возможностей ЭТОЙ сессии — что
# из инфраструктуры доступно, что нет. Ответ на требование «агент всегда
# понимает, что он может, а что нет»: недоступное не предлагается и не
# имитируется, а называется недоступным с указанием, где задача выполнима.
#
# Детект дешёвый и честный: только то, что проверяемо из шелла (платформа,
# CLI, env). Наличие MCP-серверов из хука не видно — по ним карта даёт
# ожидание по окружению, а истина — список инструментов сессии.
#
# Fail quiet: любая ошибка не должна ломать старт сессии.
set -u

# Project-уровень уступает user-уровню (install.sh), иначе карта печатается
# дважды в craft-сессиях на локальной машине.
if [[ -n "${CLAUDE_PROJECT_DIR:-}" && "$0" == "$CLAUDE_PROJECT_DIR"/* \
      && -e "$HOME/.claude/hooks/$(basename "$0")" ]]; then
  exit 0
fi

self="$(realpath "$0" 2>/dev/null || echo "$0")"
# shellcheck disable=SC1091
. "$(dirname "$self")/_load-env.sh" 2>/dev/null || true

if [[ "$(uname -s 2>/dev/null)" == "Darwin" ]]; then
  platform="локальный мак"
else
  platform="облачный контейнер (Linux)"
fi

if command -v arc >/dev/null 2>&1 && [[ -d "$HOME/arcadia" || -d "$HOME/arc-mounts" ]]; then
  arc_line="доступен — задачи Аркадии выполнимы (изолированный маунт, скилл arc-temp-branch-pr)"
  tracker_line="ожидается подключённым (истина — список инструментов сессии: mcp__startrek…)"
else
  arc_line="НЕДОСТУПЕН — работа с кодом Аркадии в этой сессии невозможна, только с локальной машины"
  tracker_line="НЕДОСТУПЕН — Яндекс-трекер только с локальной машины"
fi

if [[ -n "${CRAFT_API_BASE:-}" ]]; then
  craft_line="connect-API доступен; MCP — смотри список инструментов (craft_read/craft_write)"
else
  craft_line="connect-API не сконфигурирован в этой сессии; при наличии Craft MCP работай через него"
fi

cat <<CARD
=== Карта окружения сессии ===
- Платформа: $platform
- arc / Аркадия: $arc_line
- Яндекс-трекер MCP: $tracker_line
- Craft: $craft_line
Директива: недоступное здесь — не предлагать, не имитировать и не заменять
выдумкой; если задача требует недоступного, скажи явно и назови, где она
выполнима (локальная машина / облачная craft-сессия).
=== конец карты ===
CARD
exit 0
