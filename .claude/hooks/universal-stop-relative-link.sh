#!/usr/bin/env bash
# Stop-хук (БЛОКИРУЮЩИЙ): гейт ссылок на файлы в тексте хода.
#
# Приложение резолвит путь ссылки от ЕДИНСТВЕННОГО корня сессии — её рабочей
# директории. Дополнительные рабочие директории (--add-dir) корнями не являются,
# поэтому относительный путь, отсчитанный от чужого маунта, не открывается
# никогда. Абсолютный путь работает и внутри корня, и снаружи.
#
# Механика: из stdin-JSON события Stop берутся transcript_path и cwd. Из JSONL
# берётся ВЕСЬ текст хода — все текстовые блоки агента после последней реплики
# Влада, — а не только последнее сообщение: отчёт, после которого агент ещё
# работал, иначе не проверяется вовсе, а Владу он уже показан. Сообщения
# подагентов (isSidechain) пропускаются: их Влад не видит.
#
# Границу хода задаёт последняя настоящая реплика Влада — запись last-prompt или
# user-запись с текстом и без tool_result. Просто «последняя user-запись» не
# годится: в живом транскрипте их сотни, и почти все — результаты инструментов.
#
# Что считается дефектом:
#   * относительный путь, не существующий ОТ КОРНЯ СЕССИИ (другие базы не
#     пробуются — приложение их не пробует тоже);
#   * абсолютный путь, которого нет на диске;
#   * адрес, который приложение не соберёт в принципе: с пробелом внутри или
#     завёрнутый в угловые скобки — markdown-экранирование пробела уезжает в
#     адрес вместе со скобками;
#   * подпись, дословно повторяющая свой же абсолютный адрес: адресу положено
#     быть абсолютным, а показывается пусть обрезанный путь — иначе строка
#     превращается в полотно из слешей. Гейт смотрит два предмета: резолвится ли
#     адрес и читается ли подпись.
#
# Схема опознаётся строго: правило «любой токен + двоеточие» принимало за схему
# имя файла с суффиксом строки, и битые `tsconfig.json:12` проходили молча.
# Срезать суффикс раньше проверки нельзя — тогда у `tel:1800…` срежется весь
# хвост и телефонная ссылка уедет в блок как битый путь.
#
# Анти-зацикливание — дедупом, а не глушением: один и тот же набор битых ссылок
# блокируется один раз, и не больше трёх блокировок на сессию. Глушение по
# stop_hook_active выключало проверку целиком, стоило любому другому стоп-хуку
# сработать раньше. Fail open на всём неожиданном.
set -u

# Project-уровень уступает user-уровню (install.sh) — не гейтим дважды.
if [[ -n "${CLAUDE_PROJECT_DIR:-}" && "$0" == "$CLAUDE_PROJECT_DIR"/* \
      && -e "$HOME/.claude/hooks/$(basename "$0")" ]]; then
  exit 0
fi

# Служебный вложенный вызов (классификатор план-гейта) исключён: Владу его ответ не
# показывается, ссылок в нём нет, а лишний ход от блокировки роняет сам вызов.
[[ -n "${CRAFT_NESTED_CALL:-}" ]] && exit 0

input="$(cat)"

tp="$(jq -r '.transcript_path // ""' <<<"$input" 2>/dev/null)" || exit 0
[[ -n "$tp" && -f "$tp" ]] || exit 0

# Корень ровно один и тот же, что у приложения: рабочая директория сессии.
root="$(jq -r '.cwd // ""' <<<"$input" 2>/dev/null)" || root=""
[[ -n "$root" ]] || root="$PWD"

# Граница хода: номер строки последней настоящей реплики Влада. Флаг печатается
# на КАЖДУЮ строку файла (fromjson? // {}), иначе битая строка сдвинет нумерацию.
flags="$(jq -Rr '
  (fromjson? // {}) as $r
  | if ($r.type == "last-prompt") then "B"
    elif ($r.type == "user")
         and (($r.isSidechain // false) | not)
         and ((($r.message.content | type) == "string")
              or ((($r.message.content // []) | type) == "array"
                  and (($r.message.content // []) | any(.type == "text"))
                  and (($r.message.content // []) | all(.type != "tool_result"))))
    then "B"
    else "-" end' "$tp" 2>/dev/null)" || exit 0

start="$(grep -n '^B$' <<<"$flags" | tail -n 1 | cut -d: -f1)"
[[ -n "$start" ]] || start=0

text="$(tail -n +$((start + 1)) "$tp" 2>/dev/null | jq -Rr '
  (fromjson? // empty)
  | select(.type == "assistant" and ((.isSidechain // false) | not))
  | (.message.content // [])[]
  | select(.type == "text")
  | .text' 2>/dev/null)"
[[ -n "$text" ]] || exit 0

bad=""
add_bad() { case "$bad" in *"  $1"$'\n'*) ;; *) bad+="  $1"$'\n' ;; esac; }

while IFS= read -r raw; do
  [[ -z "${raw//[[:space:]]/}" ]] && continue
  # Угловые скобки и пробел: приложение берёт адрес как есть, вместе со скобками,
  # и такой ссылки не существует ни при каком пути.
  if [[ "$raw" == \<*\> || "$raw" == *" "* ]]; then
    add_bad "$raw"
    continue
  fi
  # Якорь и настоящая схема — не файловый путь. Схемой считаем только адрес с
  # двойной косой (http://, block://, craftdocs://) плюс короткий список тех, что
  # ей не пользуются. Просто «токен:» схемой не считаем: под неё маскируется имя
  # файла с суффиксом строки — `tsconfig.json:12` или `CRM-52256:15`.
  [[ "$raw" == \#* ]] && continue
  [[ "$raw" =~ ^[a-zA-Z][a-zA-Z0-9+.-]*:// ]] && continue
  [[ "$raw" =~ ^(mailto|tel|sms): ]] && continue
  p="${raw%%#*}"                                   # якорь на конце
  p="$(sed -E 's/:[0-9]+(-[0-9]+)?$//' <<<"$p")"   # суффикс строки path:42
  p="${p/#\~\//$HOME/}"                            # ~/ — тоже абсолютный
  [[ -z "$p" ]] && continue
  if [[ "$p" == /* ]]; then
    [[ -e "$p" ]] && continue
  else
    [[ -e "$root/$p" ]] && continue
  fi
  add_bad "$raw"
done < <(grep -oE '\]\([^)]*\)' <<<"$text" | sed -E 's/^\]\(//; s/\)$//')

# Подпись ссылки: адрес обязан быть абсолютным, а показывается пусть обрезанный
# путь — от узнаваемого корня. Признак дефекта машинный и без порогов на длину:
# подпись, дословно повторяющая свой же абсолютный адрес, и есть неукороченная.
dup=""
while IFS= read -r pair; do
  [[ -z "${pair//[[:space:]]/}" ]] && continue
  label="${pair%%\](*}"; label="${label#[}"
  addr="${pair#*\](}"; addr="${addr%)}"
  [[ "$addr" == /* || "$addr" == \~/* ]] || continue
  [[ "$label" == "$addr" ]] || continue
  case "$dup" in *"  $label"$'\n'*) ;; *) dup+="  $label"$'\n' ;; esac
done < <(grep -oE '\[[^]]*\]\([^)]*\)' <<<"$text")

[[ -z "$bad" && -z "$dup" ]] && exit 0

# Дедуп блокировок: один и тот же набор битых ссылок предъявляется один раз,
# и не больше трёх раз за сессию — иначе ход не закончится никогда.
state="${RELATIVE_LINK_STATE:-${TMPDIR:-/tmp}/relative-link.${CLAUDE_CODE_SESSION_ID:-default}.blocked}"
sig="$(printf '%s%s' "$bad" "$dup" | cksum 2>/dev/null | tr -d ' ')"
if [[ -n "$sig" ]]; then
  if [[ -f "$state" ]]; then
    grep -qxF "$sig" "$state" 2>/dev/null && exit 0
    (( $(wc -l < "$state" 2>/dev/null || echo 0) >= 3 )) && exit 0
  fi
  printf '%s\n' "$sig" >> "$state" 2>/dev/null || true
fi

reason=""
[[ -n "$bad" ]] && reason="Ссылки на файлы в этом ходе у Влада не откроются:
$bad
Приложение резолвит относительный путь только от корня сессии ($root) — дополнительные рабочие директории корнями не являются. Дай абсолютный путь; путь с пробелами ссылкой не оформляется вовсе (угловые скобки уезжают в адрес) — такой путь дай простым текстом. Битый путь — исправь."
if [[ -n "$dup" ]]; then
  [[ -n "$reason" ]] && reason+=$'\n\n'
  reason+="Подписью ссылки показан абсолютный путь целиком:
$dup
Адрес оставь абсолютным, а подпись обрежь до узнаваемого корня — репозитория, маунта или пакета: полотно из слешей Влад читает с телефона."
fi
reason+=$'\n'"Повтори список ссылок в финальном сообщении: показанный текст Влад уже увидел."
jq -cn --arg r "$reason" '{"decision":"block","reason":$r}'
exit 0
