#!/usr/bin/env bash
# Stop-хук (БЛОКИРУЮЩИЙ): гейт ссылок на файлы в финальном ответе агента.
#
# Относительный путь в markdown-ссылке резолвится от рабочей директории сессии,
# а работа часто идёт вне её — в отдельном arc-маунте, чужом репозитории,
# домашней папке. Такая ссылка у пользователя просто не открывается, и агент
# узнаёт об этом только от него. Хук ловит это в момент завершения хода.
#
# Проверяются два канала, и правило в них разное.
#
# 1. Текст последнего ответа агента — адресат Влад в чате. Отбрасываются адреса с
#    настоящей схемой (`схема://` плюс mailto/tel/sms), якоря на `#` и пустые; у
#    остальных срезается суффикс строки (`path:42`) и якорь. Абсолютный путь
#    проверяется как есть, относительный — по очереди от cwd события, от
#    CLAUDE_PROJECT_DIR и от рабочей директории процесса.
# 2. Описания тикетов, ушедших за ход в трекер (CreateIssue/UpdateIssue) — адресат
#    браузер. Локальный путь там не откроется ни у кого, поэтому проверяется не
#    существование по диску, а форма: адрес без схемы дефектен. Границей хода
#    служит последняя настоящая запись Влада; tool-result приходит записью того же
#    типа в двух формах — с полем результата на верхнем уровне либо блоком
#    `tool_result` внутри содержимого, и обе началом хода не считаются.
#
# Схема опознаётся строго не из педантизма: правило `любой токен + двоеточие`
# принимало за схему имя файла с суффиксом строки, и битые `tsconfig.json:12`
# проходили молча. Срезать суффикс раньше проверки нельзя — тогда у `tel:1800…`
# срежется весь хвост и телефонная ссылка уедет в блок как битый путь.
#
# Не нашёлся ни один вариант → {"decision":"block","reason":…} со списком
# ссылок: агент чинит и завершает снова. Анти-зацикливание: повторный Stop
# (stop_hook_active или CLAUDE_STOP_HOOK_ACTIVE) → тихий exit 0. Fail open на
# всём неожиданном.
set -u

# Project-уровень уступает user-уровню (install.sh) — не гейтим дважды.
if [[ -n "${CLAUDE_PROJECT_DIR:-}" && "$0" == "$CLAUDE_PROJECT_DIR"/* \
      && -e "$HOME/.claude/hooks/$(basename "$0")" ]]; then
  exit 0
fi

# Анти-зацикливание: этот Stop уже вызван из-под стоп-хука → пропуск.
[[ "${CLAUDE_STOP_HOOK_ACTIVE:-}" == "true" ]] && exit 0
input="$(cat)"
[[ "$(jq -r '.stop_hook_active // false' <<<"$input" 2>/dev/null)" == "true" ]] && exit 0

tp="$(jq -r '.transcript_path // ""' <<<"$input" 2>/dev/null)" || exit 0
[[ -n "$tp" && -f "$tp" ]] || exit 0

evt_cwd="$(jq -r '.cwd // ""' <<<"$input" 2>/dev/null)" || evt_cwd=""

# Последний ответ агента целиком: сначала его запись, потом её текстовые блоки.
last="$(jq -c 'select(.type=="assistant")' "$tp" 2>/dev/null | tail -n 1)"
text=""
if [[ -n "$last" ]]; then
  text="$(jq -r '(.message.content[]? | select(.type=="text") | .text) // empty' <<<"$last" 2>/dev/null)"
fi

# Тело тикета уходит в трекер вызовом инструмента, а не текстом ответа — гейт по
# тексту его не видит. Границей хода служит последняя НАСТОЯЩАЯ запись Влада.
# Tool-result приходит записью того же типа и в двух формах: с полем результата на
# верхнем уровне либо блоком `tool_result` внутри содержимого. Обе — не начало хода.
turn_start="$(jq -r 'if (.type=="user"
                        and (has("toolUseResult")|not)
                        and (any(.message.content[]?; (type=="object") and .type=="tool_result") | not))
                     then input_line_number else empty end' \
  "$tp" 2>/dev/null | tail -n 1)"
[[ -n "$turn_start" ]] || turn_start=0
tracker_text="$(tail -n +"$((turn_start + 1))" "$tp" 2>/dev/null \
  | jq -r 'try (select(.type=="assistant")
                | .message.content[]?
                | select(.type=="tool_use")
                | select(.name=="mcp__tracker_mcp__CreateIssue"
                         or .name=="mcp__tracker_mcp__UpdateIssue")
                | (.input.description // .input.fields.description // empty))' 2>/dev/null)"

[[ -n "$text" || -n "$tracker_text" ]] || exit 0

exists_somewhere() {
  local p="$1" base
  [[ "$p" == /* ]] && { [[ -e "$p" ]]; return; }
  for base in "$evt_cwd" "${CLAUDE_PROJECT_DIR:-}" "$PWD"; do
    [[ -n "$base" && -e "$base/$p" ]] && return 0
  done
  return 1
}

bad=""
while IFS= read -r raw; do
  [[ -z "$raw" ]] && continue
  # Якорь и настоящая схема — не файловый путь. Схемой считаем только адрес с
  # двойной косой (http://, block://, craftdocs://) плюс короткий список тех, что
  # ей не пользуются. Просто «токен:» схемой не считаем: под неё маскируется имя
  # файла с суффиксом строки — `tsconfig.json:12` или `CRM-52256:15`.
  [[ "$raw" == \#* ]] && continue
  [[ "$raw" =~ ^[a-zA-Z][a-zA-Z0-9+.-]*:// ]] && continue
  [[ "$raw" =~ ^(mailto|tel|sms): ]] && continue
  p="${raw%%#*}"                       # якорь на конце
  p="$(sed -E 's/:[0-9]+(-[0-9]+)?$//' <<<"$p")"   # суффикс строки path:42
  p="${p/#\~\//$HOME/}"                # ~/ — тоже абсолютный
  [[ -z "$p" ]] && continue
  exists_somewhere "$p" && continue
  bad+="  $raw"$'\n'
done < <(grep -oE '\]\([^)[:space:]]+\)' <<<"$text" | sed -E 's/^\]\(//; s/\)$//')

# В тикете правило другое: его читают в браузере, локальный путь там не откроется
# ни у кого. Поэтому проверяется не существование по диску, а форма — любой адрес
# без схемы дефектен.
bad_web=""
while IFS= read -r raw; do
  [[ -z "$raw" ]] && continue
  [[ "$raw" == \#* ]] && continue
  [[ "$raw" =~ ^[a-zA-Z][a-zA-Z0-9+.-]*:// ]] && continue
  [[ "$raw" =~ ^(mailto|tel|sms): ]] && continue
  bad_web+="  $raw"$'\n'
done < <(grep -oE '\]\([^)[:space:]]+\)' <<<"$tracker_text" | sed -E 's/^\]\(//; s/\)$//')

[[ -z "$bad" && -z "$bad_web" ]] && exit 0

reason=""
[[ -n "$bad" ]] && reason+="Ссылки на файлы в ответе не открываются — путь не резолвится ни от рабочей директории, ни от корня проекта:
$bad
Файл лежит вне рабочей директории (отдельный маунт, чужой репозиторий, домашняя папка) — дай абсолютный путь. Битый путь — исправь.
"
[[ -n "$bad_web" ]] && reason+="Локальные пути в описании тикета — его читают в браузере, там такая ссылка не откроется ни у кого:
$bad_web
Файл адресуй веб-ссылкой на просмотрщик своего репозитория — какой именно, знает скилл окружения."
jq -cn --arg r "$reason" '{"decision":"block","reason":$r}'
exit 0
