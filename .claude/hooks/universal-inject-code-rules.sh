#!/usr/bin/env bash
# SessionStart hook (устанавливается в ~/.claude): живой инжект ЯДРА «Правил
# кода» из Craft. Канон — Craft; никакого коммитнутого кэша.
#
# Инжектится ТОЛЬКО корень дока (maxDepth=1): ядро + диспетчер доменных
# страниц. Полные доменные страницы (TypeScript, React, …) агент читает
# целиком по триггеру домена — так велит сам диспетчер. Сжимать их в инжект
# нельзя (урок в «Обслуживании памяти»).
#
# ПОЧЕМУ ФАЙЛ, А НЕ СТДАУТ. Стдаут хука режется площадкой на 10 000 СИМВОЛОВ,
# а ядро больше. Поэтому ядро складывается в файл, а в стдаут уходят только
# оба диспетчера (маршрутизация, без неё агент не знает, что доменные
# страницы и код-скиллы есть) плюс директива прочитать файл. В craft-репо
# файл ещё и импортируется из CLAUDE.md — импорт не режется вовсе, и там это
# настоящая доставка; вне репо остаётся директива.
#
# Счёт только в символах. Прежняя редакция сравнивала ${#out} и резала
# ${out:0:BUDGET}: в POSIX-локали это БАЙТЫ, кириллический символ весит два,
# и до сессии доходила половина ядра.
#
# Fail quiet: нет env/сети → короткая директива-фолбек.
set -u

self="$(realpath "$0" 2>/dev/null || echo "$0")"
# shellcheck disable=SC1091
. "$(dirname "$self")/_load-env.sh" 2>/dev/null || true

CODE_RULES_ID="${CRAFT_CODE_RULES_ID:-d3f184fb-2c70-6058-0797-d9851f4b16a7}"
STDOUT_BUDGET=9500

ROOT="${CLAUDE_PROJECT_DIR:-$PWD}"
OUT="$ROOT/.claude/craft-code-rules-context.md"
# В craft-репо файл импортируется из CLAUDE.md; в остальных репозиториях
# импорта нет, и агенту нужна явная директива прочитать файл.
IMPORTED=0
[[ -e "$ROOT/.claude/hooks/craft-inject-router.sh" ]] && IMPORTED=1

# Счёт в СИМВОЛАХ, а не в байтах: wc -m в POSIX-локали считает байты — ровно
# та ошибка, из-за которой ядро резалось вдвое, и повторить её здесь легко.
# Ищем локаль, где один кириллический символ считается за один; не нашлась —
# счёт остаётся байтовым, то есть завышенным, и бюджет от этого только строже.
CHAR_LC=""
for l in C.UTF-8 C.utf8 en_US.UTF-8 en_US.utf8; do
  [[ "$(printf 'ы' | LC_ALL="$l" wc -m 2>/dev/null | tr -d ' ')" == "1" ]] && { CHAR_LC="$l"; break; }
done

chars() {  # <файл|->
  if [[ -n "$CHAR_LC" ]]; then LC_ALL="$CHAR_LC" wc -m < "$1" | tr -d ' '
  else wc -m < "$1" | tr -d ' '; fi
}

fallback() {
  echo "⚠️ Ядро «Правил кода» не загружено из Craft ($1). Перед правками кода прочитай его живьём: Craft MCP blocks get $CODE_RULES_ID --depth 1 (ядро + диспетчер доменных страниц; страницу своего домена читай целиком)."
  exit 0
}

# Улика доставки. Печатается ТОЛЬКО при непустом файле: иначе она доказывала бы
# запуск хука, а не доставку правил, и евал-прогон был бы зелёным на пустом
# контексте.
evidence() {
  [[ -s "$OUT" ]] || return 1
  if (( IMPORTED )); then
    echo "Ядро правил кода обновлено: $(chars "$OUT") символов записано в .claude/craft-code-rules-context.md; полный текст уже в контексте через импорт в CLAUDE.md.${1:-}"
  else
    echo "Ядро правил кода обновлено: $(chars "$OUT") символов записано в $OUT. ПРОЧИТАЙ этот файл целиком до первых правок кода — в стдаут влезает только диспетчер.${1:-}"
  fi
}

# Диспетчеры печатаются всегда: это маршрутизация к доменным страницам и
# код-скиллам. Пропали маркеры — говорим об этом строкой, а не молчим.
dispatchers() {
  local d
  d="$(awk '/^ *# Диспетчер доменных страниц/{f=1} /^ *# Связка со специфичными/{f=0} f' "$OUT")"
  if [[ -z "$d" ]]; then
    echo "⚠️ В ядре не нашлись диспетчеры доменных страниц и код-скиллов — структура дока изменилась. Прочитай ядро целиком: $OUT"
    return
  fi
  printf '%s\n' "$d"
}

# То же, что у хуков роутера и инцидента: внутри евал-пачки файл
# переиспользуется. Параллельные сессии делят один путь, и перезапись сносит
# контекст соседу на старте; свежесть даёт прогрев до пачки — он идёт без
# CRAFT_EVAL.
if [[ -n "${CRAFT_EVAL:-}" && -s "$OUT" ]]; then
  evidence " (переиспользован кэш евал-прогона)"
  dispatchers
  exit 0
fi

base="${CRAFT_API_BASE:-}"
[[ -z "$base" ]] && fallback "CRAFT_API_BASE не задан"
base="${base%/}"

md="$(curl -sS --fail --max-time 30 --retry 2 --retry-all-errors \
  -H 'Accept: text/markdown' \
  "$base/blocks?id=$CODE_RULES_ID&maxDepth=1" 2>/dev/null)" || fallback "сеть/API недоступны"
[[ -z "$md" ]] && fallback "пустой ответ API"

mkdir -p "$(dirname "$OUT")"
# Запись атомарная: хук может отработать дважды за старт — из домашнего слоя и
# из проектного, — и оба захода пишут один путь.
tmp="$OUT.$$.tmp"
{
  echo "=== Craft: «⚙️ Правила кода» — ядро, живой инжект ($(date -u +%FT%TZ)) ==="
  printf '%s\n' "$md"
  echo "=== конец ядра. Работаешь с доменом — прочитай его страницу ЦЕЛИКОМ (Craft MCP, blocks get по ссылке из диспетчера, --depth -1) до первых правок кода ==="
} > "$tmp" || fallback "не удалось записать файл ядра"
mv -f "$tmp" "$OUT" || fallback "не удалось положить файл ядра на место"

msg="$(evidence)" || fallback "файл ядра пуст"

out="$(printf '%s\n%s\n' "$msg" "$(dispatchers)")"

# Обрезка не молчит и не рвёт текст: если диспетчеры вдруг перестали влезать,
# стдаут отдаёт только улику и говорит, что маршрутизация осталась в файле.
if (( $(printf '%s' "$out" | wc -m | tr -d ' ') > STDOUT_BUDGET )); then
  out="$msg
⚠️ Диспетчеры не влезли в стдаут хука (предел $STDOUT_BUDGET символов) — они целиком в файле ядра, прочитай его."
fi

printf '%s\n' "$out"
exit 0
