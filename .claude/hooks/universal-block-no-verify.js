#!/usr/bin/env node
// PreToolUse(Bash) guard: блокирует обход git-хуков репозитория. Они ловят
// ровно то, что сломает сборку: падает хук — чини причину, а не выключай
// проверку. Обход действительно нужен (сломанный хук, осознанное решение) — это
// решение Влада, и проходит он явным разрешением на конкретный вызов.
//
// Две формы обхода. Подмена каталога хуков проверяется по СЫРОЙ команде, потому
// что значение бывает в кавычках, и без учёта регистра — имена git-конфига
// регистронезависимы.
//
// Флаг пропуска проверок при коммите и отправке ищется иначе: сперва
// вычёркиваются кавычные строки (сообщение коммита, упоминающее флаг, обходом не
// является), затем команда режется на сегменты, и отказ выносится только
// сегменту, где встретились и git, и коммит с отправкой, и сам флаг.
//
// Fail open на всём неожиданном.
import { readEvent } from './lib/event.js';
import { deny } from './lib/decide.js';
import { hookOnce } from './lib/once.js';

const HAS_GIT = /(^|[^\w-])git(\s|$)/m;

const { raw, event, input } = readEvent();
if (!hookOnce(raw, event, import.meta.url)) process.exit(0);

const command = input.command || '';
if (!command) process.exit(0);

// Быстрый пропуск: git как отдельного слова в команде нет вовсе.
if (!HAS_GIT.test(command)) process.exit(0);

if (/(^|\s)-c\s+["']?core\.hookspath=/im.test(command)) {
  deny('Заблокировано: git -c core.hooksPath=… — подмена каталога git-хуков, то есть их обход. Хуки репо (pre-commit, pre-push) ловят то, что сломает CI: падает хук → чини причину, а не выключай проверку. Обход действительно нужен (сломанный хук, осознанное решение) — это решение Влада: скажи об этом в ответе и попроси его нажать allow.');
}

const stripped = command.replace(/'[^']*'/g, "''").replace(/"[^"]*"/g, '""');
for (const segment of stripped.split(/[;|&]/)) {
  if (!segment.trim()) continue;
  if (!HAS_GIT.test(segment)) continue;
  if (!/(^|\s)(commit|push)(\s|$)/m.test(segment)) continue;
  if (/(^|\s)--no-verify(\s|$)/m.test(segment)) {
    deny('Заблокировано: git commit/push с --no-verify — обход git-хуков репо. Хуки (pre-commit, pre-push) ловят то, что сломает CI: падает хук → чини причину, а не пропускай проверку. Обход действительно нужен (сломанный хук, осознанное решение) — это решение Влада: скажи об этом в ответе и попроси его нажать allow.');
  }
}
process.exit(0);
