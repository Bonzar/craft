#!/usr/bin/env node
// PreToolUse(Bash) guard: блокирует ОДИНОЧНУЮ длинную паузу — анти-паттерн
// «подождать наугад и потом проверить». Будиться надо на СОБЫТИИ: фоновый
// запуск будит на выходе процесса, блокирующий сторож выходит ровно на условии,
// а состояние фоновой задачи читается своим инструментом без всякой паузы.
//
// Ловит две формы: одиночную паузу и цепочку, НАЧИНАЮЩУЮСЯ с неё («подождать и
// сразу проверить»). Вторая добавлена после того, как ровно так шесть раз прошло
// мимо гварда в одной сессии — причём при уже запущенной фоновой задаче, которая
// будит на событии сама.
//
// Пропускается (НЕ блок): пауза не первым звеном цепочки или внутри цикла — это
// законный сторож; короткая пауза меньше трёх секунд; осознанный таймер с
// маркером в комментарии, когда надо дать поработать и снять метрику.
import { readEvent } from './lib/event.js';
import { deny } from './lib/decide.js';
import { hookOnce } from './lib/once.js';

const { raw, event, input } = readEvent();
if (!hookOnce(raw, event, import.meta.url)) process.exit(0);

const command = input.command || '';

// Осознанный таймер — пропускаем.
if (/# *timed-wait/.test(command)) process.exit(0);

const trimmed = command.replace(/^\s+/, '').replace(/\s+$/, '');

// Пауза первым звеном: сама по себе либо в начале цепочки. Аргумент берём у
// ПЕРВОЙ паузы, а не по концу строки: у цепочки конца нет, и «две минуты, потом
// показать лог» иначе читалось бы как две секунды.
const head = /^sleep\s+(\d+(?:\.\d+)?)([smhd]?)(?:\s*(?:$|[;&|]))/.exec(trimmed);
if (!head) process.exit(0);

const [, number, unit] = head;
// Любая единица кроме секунд — заведомо долго; иначе решает целая часть.
const long = (unit && unit !== 's') || Math.floor(Number(number)) >= 3;

if (long) {
  // Развёрнутая форма ответа — та же, что печатала bash-версия.
  deny('Одиночный sleep — произвольная задержка ожидания. Будись на событии, а не по таймеру: (1) запусти процесс с run_in_background:true — харнесс разбудит на exit; (2) для условия (строка в логе / порт / файл) повесь в фоне блокирующий сторож, который выходит на событии: tail -n +1 -F log | grep -q -m1 PATTERN | npx wait-on tcp:PORT|http://host/health | curl --retry N --retry-connrefused -sf URL | fswatch -1 path; (3) текущее состояние фоновой задачи читай через TaskOutput. Если это ОСОЗНАННЫЙ таймер (дать поработать N секунд и снять метрику) — добавь маркер: sleep N # timed-wait.', { compact: false });
}
process.exit(0);
