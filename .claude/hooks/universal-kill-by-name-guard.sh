#!/usr/bin/env bash
# PreToolUse(Bash) guard: блокирует гашение процесса, адресованное ИМЕНЕМ или маской, —
# `pkill`, `killall`, `kill $(pgrep …)`. На машине, где экземпляр не один (браузер под
# несколькими сессиями, демон, сервер), такое гашение бьёт по чужим.
#
# Инцидент, ради которого гвард заведён: `pkill -x "Google Chrome"` на общем маке снёс
# рабочие браузеры двух чужих сессий вместе со своим замерочным. Текстовое правило про
# это существовало и не удержало — отсюда машинная ступень.
#
# Точное имя от маски здесь ничем не отличается: `-x` бьёт по всем экземплярам ровно так
# же, как `-f` по подстроке. Разница только в том, что именем целятся увереннее.
#
# Пропускается (НЕ блок):
#   - гашение по номеру процесса: `kill 123`, `kill -9 "$(cat pidfile)"`, `kill $PID`;
#   - всё, что не про гашение.
#
# Ловит и команды, уходящие на другую машину (`ssh host 'pkill …'`), потому что видит
# текст вызова целиком.
set -u

# Project-уровень уступает user-уровню (install.sh) — не гейтим дважды.
if [[ -n "${CLAUDE_PROJECT_DIR:-}" && "$0" == "$CLAUDE_PROJECT_DIR"/* \
      && -e "$HOME/.claude/hooks/$(basename "$0")" ]]; then
  exit 0
fi

cmd=$(cat | jq -r '.tool_input.command // ""')

# pkill/killall в любом месте строки — они по определению адресуют именем.
# kill сам по себе законен, поэтому ловим только связку с поиском по имени: kill $(pgrep …).
if printf '%s' "$cmd" | grep -Eq '(^|[[:space:];&|(]|["'"'"'])(pkill|killall)([[:space:]]|$)' \
   || printf '%s' "$cmd" | grep -Eq 'kill[^|;&]*\$\([[:space:]]*(pgrep|pidof)' \
   || printf '%s' "$cmd" | grep -Eq '(pgrep|pidof)[^|;&]*\|[[:space:]]*xargs[^|;&]*kill'; then
  jq -n '{
    hookSpecificOutput: {
      hookEventName: "PreToolUse",
      permissionDecision: "deny",
      permissionDecisionReason: "Гашение по имени процесса бьёт по чужим экземплярам: на общей машине браузер, демон или сервер подняты несколькими сессиями, и точное имя (-x) от маски (-f) тут ничем не отличается. Адресуй СВОЙ экземпляр: номер процесса из своего pid-файла (kill \"$(cat mypid)\") либо порт, на котором он слушает (lsof -ti tcp:PORT -sTCP:LISTEN). Своего идентификатора нет — сначала заведи его, а не гаси по имени."
    }
  }'
fi

exit 0
