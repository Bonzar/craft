#!/usr/bin/env node
// PreToolUse guard на записи файла плана. Правила 3, 5 и 6 идут первыми и
// действуют на КАЖДЫЙ план; правила 0–2 и 4 полицуют только Craft-планы,
// опознанные по структуре, а планы про КОД пропускают: те законно называют
// файлы, команды и идентификаторы.
//
// Что держится:
//   0. Забор длиннее трёх бэктиков — вложенный блок кода читается хуже цитаты.
//   1. Механика выполнения в плане: секции проверки и порядка, команды.
//   2. Голый идентификатор блока вне кликабельной ссылки.
//   3. Жёсткий перенос абзаца — Влад читает с телефона, где каждая перенесённая
//      строка рисуется отдельным абзацем и фраза рвётся посреди себя.
//   4. Сущность без строки адреса — план без адреса неисполним.
//   5. Относительный путь: внутри файла плана он резолвится от папки планов, а
//      не от корня сессии, и не открывается.
//   6. Подпись ссылки, дословно повторяющая свой абсолютный адрес.
//
// Узкие признаки вместо широких — цена ложного отказа выше цены пропуска.
// Fail quiet на всём неожиданном.
//
// Счёт длины и складывание регистра здесь делаются средствами языка: bash-версии
// нужна была UTF-8-локаль (в POSIX кириллица весит вдвое, и порог переноса падал
// вдвое), а разбор заборов приходилось писать на awk с обходом бага в его
// реализации, где длина ряда знаков считалась неверно.
import fs from 'node:fs';
import path from 'node:path';
import { readEvent } from './lib/event.js';
import { deny } from './lib/decide.js';

const { event, tool, input } = readEvent();
if (!['Write', 'Edit', 'MultiEdit'].includes(tool)) process.exit(0);

const file = input.file_path || '';
if (!/\/plans\/.*\.md$/.test(file)) process.exit(0);

// Записываемый текст лежит в разных полях у разных инструментов: целиком, одним
// фрагментом и ПАЧКОЙ фрагментов. Читать только первые два — значит пропускать
// пакетную правку насквозь. Фрагменты склеиваются ЧЕРЕЗ ПУСТУЮ СТРОКУ: встык
// хвост одного и начало другого прочитались бы соседями и дали ложный перенос.
const parts = [];
if (input.content) parts.push(input.content);
if (input.new_string) parts.push(input.new_string);
for (const edit of input.edits || []) {
  if (edit && edit.new_string) parts.push(edit.new_string);
}
const content = parts.join('\n\n');
if (content.trim() === '') process.exit(0);

// Забор — ряд бэктиков или тильд от трёх знаков с любым отступом; у открывающего
// запоминаются знак и длина, и закрыть блок может лишь ряд того же знака не
// короче. Без длины забор из четырёх бэктиков рвётся вложенным примером из трёх.
// Режим blank гасит строки блока ПУСТЫМИ (плюс цитаты, таблицы и заголовки):
// удаление придвинуло бы друг к другу несоседние строки и родило ложный перенос.
// Режим drop выбрасывает их совсем, оставляя только прозу плана.
function stripFenced(text, mode) {
  const out = [];
  let inside = false;
  let char = '';
  let len = 0;
  for (const line of text.split('\n')) {
    const trimmed = line.replace(/^\s*/, '');
    const first = trimmed[0];
    let run = 0;
    if (first === '`' || first === '~') {
      while (trimmed[run] === first) run += 1;
    }
    let fence = false;
    if (run >= 3) {
      if (!inside) {
        inside = true; char = first; len = run; fence = true;
      } else if (first === char && run >= len) {
        inside = false; fence = true;
      }
    }
    if (fence || inside) {
      if (mode === 'blank') out.push('');
      continue;
    }
    if (mode === 'blank' && /^\s*[>|#]/.test(line)) {
      out.push('');
      continue;
    }
    out.push(line);
  }
  return out.join('\n');
}

// --- 3. Жёсткий перенос абзаца ---------------------------------------------
const wrapBody = stripFenced(content, 'blank');
let previous = '';
for (const line of wrapBody.split('\n')) {
  if (previous.trim() !== '') {
    // Длина — по тексту строки: без ведущих пробелов и без маркера списка.
    // Отступ на продолжении — самый частый стиль переноса, и он не должен
    // прятать дефект. Маркер нумерованного пункта — любой длины и в обеих
    // формах: одноцифровой шаблон принимал десятый пункт за продолжение девятого.
    let head = previous.replace(/^\s*/, '').replace(/^[-*+] /, '');
    head = head.replace(/^[0-9]+[.)]\s/, '');
    const next = line.replace(/^\s*/, '');
    const nextIsItem = /^[-*+] /.test(next) || /^[0-9]+[.)]\s/.test(next);
    // Локатор адреса и строка со ссылкой исключены: их длину задаёт адрес, а не
    // вёрстка.
    if (head.length >= 60 && !head.startsWith('где:') && !previous.includes('http')
        && next !== '' && !nextIsItem && !next.startsWith('---') && !next.startsWith('![')) {
      deny('План свёрстан жёсткими переносами: абзац разбит на строки под ширину терминала. Влад читает с телефона, где каждая такая строка рисуется отдельным абзацем и фраза рвётся посреди себя. Набери абзац одной строкой; перенос оставь только внутри цитат, кода и таблиц — в цитате знак «>» ставится на КАЖДОЙ строке, иначе продолжение читается как проза.');
    }
  }
  previous = line;
}

// --- 5. Относительный путь ---------------------------------------------------
// Дефектом считается только путь, который РЕЗОЛВИТСЯ в живой ФАЙЛ от корня
// сессии: значит автор имел в виду реальный файл и записал его относительно.
// Неразрешимый путь и имя без косой черты не трогаются — это прозаическое
// упоминание. Каталог тоже не адрес: хлебная крошка называет место, а не файл.
const planRoot = event.cwd || process.env.CLAUDE_PROJECT_DIR || process.cwd();
const pathBody = stripFenced(content, 'drop').split('\n').filter((l) => !/^\s*>/.test(l)).join('\n');

// Адрес ссылки и голый текст разбираются порознь: подпись в квадратных скобках —
// не адрес, и ловить в ней относительность нельзя.
const candidates = new Set();
for (const m of pathBody.matchAll(/\]\(([^)]*)\)/g)) {
  candidates.add(m[1].replace(/^</, '').replace(/>$/, ''));
}
// Из остатка убираются адреса, у которых относительной части быть не может: URL
// со схемой и абсолютные пути. Иначе хвост URL и середина абсолютного пути
// читаются как относительный.
const rest = pathBody
  .replace(/\[[^\]]*\]\([^)]*\)/g, '')
  .replace(/[a-zA-Z][a-zA-Z0-9+.-]*:\/\/[^ )]*/g, '')
  .replace(/(^|[\s([])[~/][^ )]*/g, '$1');
for (const m of rest.matchAll(/(?:^|[^A-Za-z0-9_./-])([A-Za-z0-9_@.-]+(?:\/[A-Za-z0-9_@.+-]+)+)/g)) {
  candidates.add(m[1]);
}

const relative = [];
for (const raw of [...candidates].sort()) {
  let candidate = raw.trim();
  if (!candidate) continue;
  candidate = candidate.split('#')[0].replace(/:[0-9]+(-[0-9]+)?$/, '');
  if (!candidate || candidate.startsWith('/') || candidate.startsWith('~')) continue;
  if (/^[a-zA-Z][a-zA-Z0-9+.-]*:\/\//.test(candidate)) continue;
  try {
    if (fs.statSync(path.join(planRoot, candidate)).isFile()) relative.push(candidate);
  } catch { /* не резолвится — прозаическое упоминание, не адрес */ }
}
if (relative.length > 0) {
  deny(`В плане относительные пути к файлам: ${relative.join(', ')} — у Влада они не откроются. Внутри файла плана путь резолвится от папки планов, а не от корня сессии, и кликается даже голое упоминание в тексте. Дай абсолютный путь от корня диска.`);
}

// --- 6. Подпись, дословно повторяющая свой абсолютный адрес ------------------
// Признак без порогов на длину: адресу положено быть абсолютным, подписи —
// обрезанной до узнаваемого корня, поэтому их равенство и есть неукороченная
// подпись.
const duplicated = new Set();
for (const m of pathBody.matchAll(/\[([^\]]*)\]\(([^)]*)\)/g)) {
  const [, label, address] = m;
  if (!(address.startsWith('/') || address.startsWith('~/'))) continue;
  if (label === address) duplicated.add(label);
}
if (duplicated.size > 0) {
  deny(`В плане подписью ссылки показан абсолютный путь целиком: ${[...duplicated].sort().join(', ')} — Влад читает план с телефона, и строка превращается в полотно из слешей. Адрес оставь абсолютным, подпись обрежь до узнаваемого корня — репозитория, маунта или пакета.`);
}

// --- дальше только Craft-планы ----------------------------------------------
// Опознаются по структурным сигналам: строка адреса, ссылка на блок или
// сущностный заголовок. Заголовок в списке обязателен: без него план, где адрес
// забыт у ВСЕХ сущностей разом, не опознавался бы Craft-планом и проезжал мимо
// правила адреса — то есть мимо ровно того случая, ради которого оно заведено.
if (!/docs\.craft\.do|block:\/\/|(^|\s)где:|^\s*#+\s*\[/m.test(content)) process.exit(0);

// Дословный текст живёт в цитатном блоке, примеры — в заборах; и там, и там
// законны команды, идентификаторы и даже заголовок проверки: это записываемое
// содержимое, а не механика плана.
const body = stripFenced(content, 'drop').split('\n').filter((l) => !/^\s*>/.test(l)).join('\n');
const problems = [];

// 0. Забор длиннее трёх бэктиков. Только на записи ЦЕЛОГО файла: на правке
// фрагмента длинный забор бывает законной половиной пары, целого текста хук не
// видит и судить не может.
const wholeFile = Boolean(input.content);
if (wholeFile && /^\s*````/m.test(content)) {
  problems.push('забор длиннее трёх бэктиков — вложенный блок кода в плане запрещён, показывай вложенный пример цитатой');
}

// 1a. Секции проверки, порядка и тестов.
if (/^#+\s*(Порядок|Проверка|Verification|Verify|Тесты|Testing|Проверка результата|Порядок выполнения)/im.test(body)) {
  problems.push('секция механики/проверки/порядка — механика в план не выносится');
}
// 1b. Команды и структурные флаги.
if (/(blocks (get|update|add|move|delete|learn)|tasks (update|add|delete)|(^|\s)--(json|id|markdown|siblingId|depth)(\s|=)|git (commit|push|add)|curl )/m.test(body)) {
  problems.push('команды/механика выполнения в тексте плана');
}

// 4. Сущность без адреса. Сущностный блок — заголовок ЛЮБОГО уровня, открытый
// скобкой типа и операции, и строки до следующего заголовка; такой блок обязан
// нести строку адреса. Только на записи ЦЕЛОГО файла: на правке фрагмента
// сущность без адреса законна — адрес остался в неправленой части.
if (wholeFile) {
  let entity = false;
  let found = false;
  let bad = false;
  for (const line of body.split('\n')) {
    if (/^\s*#+\s*\[/.test(line)) {
      if (entity && !found) { bad = true; break; }
      entity = true; found = false; continue;
    }
    if (/^\s*#/.test(line)) {
      if (entity && !found) { bad = true; break; }
      entity = false; continue;
    }
    if (entity && /^\s*[-*+]?\s*где:/.test(line)) found = true;
  }
  if (!bad && entity && !found) bad = true;
  if (bad) {
    problems.push('сущность без строки «где:» — у каждой сущности плана есть адрес правки, путь крошками от контейнера до позиции');
  }
}

// 2. Голый идентификатор блока вне кликабельной ссылки: адреса Craft снимаются
// первыми, и оставшийся в остатке идентификатор — голый.
const stripped = body.replace(/https?:\/\/docs\.craft\.do[^ )]*/g, '');
if (/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i.test(stripped)) {
  problems.push('голый block-ID вне ссылки — отсылка к блоку должна быть кликабельной ссылкой docs.craft.do');
}

if (problems.length === 0) process.exit(0);

deny(`План нарушает правила: ${problems.map((p) => `${p}; `).join('')}План отвечает ЧТО меняется и КУДА ложится — механика, команды, проверка и порядок в него не выносятся; отсылки к блокам даются кликабельными ссылками docs.craft.do, не голым ID. Перепиши план и запиши снова.`);
