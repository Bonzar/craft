#!/usr/bin/env bash
# PreToolUse на ExitPlanMode: не ПОВТОРЯТЬ показ плана в ходе, начатом СЛУЖЕБНЫМ
# сообщением.
#
# План-режим при отсутствии Влада закрывается сам, следом приходит техническое
# продолжение хода — и показ соблазняет повторить. Повтор ничего не даёт: Влад не
# отвечал, закроется снова. Рычаг инцидента «четыре показа подряд после служебного
# продолжения»; правило — «Влад не в сети — не его отказ» в «Общении с Владом».
#
# Запрещён именно ПОВТОР, а не показ вообще: правило про повтор, и первая версия гейта,
# судившая по одному признаку «ход служебный», блокировала первый показ исправленного
# плана. Различитель — ИЗМЕНИЛСЯ ЛИ ПЛАН: при пропуске гейт запоминает хеш файла плана,
# отклоняет только совпадение. План правился после замечания Влада — это новый показ.
#
# Метку служебного хода ставит и снимает universal-plan-gate-reset.sh: он уже разбирает
# словарь якорей (service-anchors.txt). Он же снимает хеш показа — реплика Влада
# начинает разговор заново.
#
# На событие отклонения показа гейт не опирается: доходит ли оно до хуков, не проверено.
#
# Fail open на всём неожиданном: сломанный гейт не должен клинить работу.
set -u

# Хеш файла. Запасная команда обязательна: на маке из README основной нет, хеш вышел бы
# пустым, и гейт молча выключился бы. Формат первого токена у обеих команд одинаков.
hash_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" 2>/dev/null | cut -d' ' -f1
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" 2>/dev/null | cut -d' ' -f1
  fi
}

# Уступаем user-level копии — иначе двойной прогон на локальной машине.
if [[ -n "${CLAUDE_PROJECT_DIR:-}" && "$0" == "$CLAUDE_PROJECT_DIR"/* \
      && -e "$HOME/.claude/hooks/$(basename "$0")" ]]; then
  exit 0
fi

input="$(cat)"
tool="$(jq -r '.tool_name // ""' <<<"$input" 2>/dev/null)" || exit 0
[[ "$tool" == "ExitPlanMode" ]] || exit 0

sid="${CLAUDE_CODE_SESSION_ID:-default}"
marker="${CRAFT_SERVICE_TURN_MARKER:-/tmp/plan-service-turn.${sid}}"
shown="${CRAFT_PLAN_SHOWN_MARKER:-/tmp/plan-shown.${sid}}"
plan="${CRAFT_PLAN_FILE:-$(cat "${CRAFT_PLAN_FILE_MARKER:-/tmp/plan-file.${sid}.path}" 2>/dev/null)}"

# Хеш плана — признак «тот же самый показ». Файла плана нет — судить не по чему, гейт
# молчит: пропущенный повтор дешевле заблокированного показа.
now=""
[[ -n "$plan" && -r "$plan" ]] && now="$(hash_of "$plan")"

if [[ -e "$marker" && -n "$now" && "$now" == "$(cat "$shown" 2>/dev/null)" ]]; then
  jq -cn '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:"Ход начат служебным сообщением, а план с прошлого показа не менялся — это повтор. План уже показан и закрылся сам: Влада не было. Дождись его реплики, ничего не выполняй и план текстом не пересказывай. Правил план по замечанию — показывай, повтором это не считается."}}'
  exit 0
fi

# Показ проходит — запоминаем, ЧТО именно показано.
[[ -n "$now" ]] && { printf '%s\n' "$now" > "$shown" 2>/dev/null || true; }
exit 0
