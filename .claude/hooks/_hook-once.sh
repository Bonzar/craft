#!/usr/bin/env bash
# Sourced (не исполняется) хуками, зарегистрированными сразу в двух местах:
# в project-level `.claude/settings.json` этого репо и в пользовательском
# `~/.claude/settings.json` (install.sh). Оба вызова приходят на одно событие, и
# без дедупликации хук отрабатывает дважды: двойная директива в контексте,
# двойной deny, двойной инкремент счётчиков.
#
# Уступка идёт в два шага, потому что двойная регистрация бывает двух разных
# видов.
#
# ШАГ 1 — по чекауту. Локально Claude Desktop режет сессии отдельный worktree:
# project-регистрация исполняет файл хука ИЗ него, а пользовательская — файл
# основного чекаута. Это разные файлы разных версий, и работать должен тот, чей
# файл лежит в чекауте сессии: его код и есть код этой сессии, а для синка ещё и
# его чекаут — правильная цель. Посторонний уступает.
#
# Чекаут сессии опознаётся по каталогу, который событие приносит с собой (cwd), а
# не по переменной окружения с корнем проекта: в окружении инструментов её нет, и
# правило, стоящее на ней, молча выключилось бы там, где её не задают. Файла
# этого хука в чекауте сессии нет вовсе (сессия чужого проекта, где система
# приходит только пользовательской регистрацией) — уступать некому, работаем.
#
# ШАГ 2 — по факту. Когда обе регистрации ведут в ОДИН файл (сессия запущена в
# самом чекауте), пути совпадают буквально и признака «кто из двух» не остаётся.
# Тогда решает занятие события: первый вызов ставит метку, второй видит занятое и
# выходит.
#
# Ключ метки — сессия, имя события и само содержимое события. Содержимое
# обязательно: без него метка первого сообщения дожила бы до второго и погасила
# бы хук навсегда. Срок жизни метки — единицы секунд: два вызова одной
# регистрации приходят одновременно, а следующее сообщение с дословно тем же
# текстом («да», «continue») приходит позже этого срока.
#
# Тесты глушат механизм HOOK_ONCE=off: раннер зовёт кейсы одного хука одним
# процессом и повторяет один и тот же вход (repeat), там дедупликация мешает.
#
# Использование, после чтения stdin:
#   . "$(dirname "$0")/_hook-once.sh"
#   hook_once "$input" || exit 0

# 1, если в чекауте сессии лежит файл ЭТОГО же хука, а исполняется другой, —
# значит вызов посторонний и уступает. 0 во всех остальных случаях.
hook_yields_to_session_checkout() {
  local payload="${1:-}" cwd base probe candidate self_real cand_real
  cwd="$(jq -r '.cwd // ""' <<<"$payload" 2>/dev/null)" || return 1
  [[ -n "$cwd" && -d "$cwd" ]] || return 1

  base="$(basename "$0")"
  # Чекаут — ближайший каталог вверх от cwd, у которого есть свой .claude/hooks
  # с файлом этого имени. Именно файл, а не сам факт репы: воркри может быть
  # старее main и нужного хука ещё не содержать.
  probe="$(cd "$cwd" 2>/dev/null && pwd)" || return 1
  while [[ -n "$probe" && "$probe" != "/" ]]; do
    candidate="$probe/.claude/hooks/$base"
    if [[ -e "$candidate" ]]; then
      self_real="$(realpath "$0" 2>/dev/null || echo "$0")"
      cand_real="$(realpath "$candidate" 2>/dev/null || echo "$candidate")"
      [[ "$self_real" != "$cand_real" ]] && return 0
      return 1
    fi
    probe="$(dirname "$probe")"
  done
  return 1
}

# 0 — работай; 1 — уступи (посторонний экземпляр либо уже занятое событие).
hook_once() {
  # Выключатель гасит ОБА шага разом: иначе исход кейсов зависел бы от того, из
  # какого каталога запущен прогон тестов.
  [[ "${HOOK_ONCE:-}" == "off" ]] && return 0

  hook_yields_to_session_checkout "${1:-}" && return 1

  local payload="${1:-}" dir key mark ttl now mtime
  dir="${HOOK_ONCE_DIR:-${TMPDIR:-/tmp}}"
  ttl="${HOOK_ONCE_TTL:-5}"

  key="$(printf '%s' "$payload" | { sha256sum 2>/dev/null || shasum -a 256 2>/dev/null; } | cut -d' ' -f1)"
  # Хеша нет (обеих команд нет на машине) — дедупликации нет, но работу хука это
  # не отменяет: лучше двойное срабатывание, чем молчание обоих вызовов.
  [[ -z "$key" ]] && return 0

  mark="$dir/hook-once.$(basename "${0%.sh}").$key"

  # mkdir атомарен: из двух одновременных вызовов ровно один создаёт каталог.
  if mkdir "$mark" 2>/dev/null; then
    return 0
  fi

  now="$(date +%s 2>/dev/null || echo 0)"
  mtime="$(stat -c %Y "$mark" 2>/dev/null || stat -f %m "$mark" 2>/dev/null || echo 0)"
  if [[ "$now" =~ ^[0-9]+$ && "$mtime" =~ ^[0-9]+$ ]] && (( now - mtime <= ttl )); then
    return 1
  fi

  # Метка протухла (то же сообщение повторили позже) — занимаем событие заново.
  touch "$mark" 2>/dev/null || true
  return 0
}
