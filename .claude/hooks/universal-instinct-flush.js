#!/usr/bin/env node
// Stop hook: детектор неразобранных сигналов. Сам НИЧЕГО не дистиллирует и не
// пишет в Craft (хук этого не может) — при наличии неразобранных сигналов
// блокирует завершение хода директивой агенту: дистиллируй кандидатов и сбрось
// их в «Наблюдения» дока «Инстинкты агента», затем отметь разбор.
//
// Сигналы он берёт из ЖУРНАЛА СОБЫТИЙ СЕССИИ (строки `op: error` и
// `op: incident`), а не из отдельного буфера: буфера больше нет, ошибка
// инструмента и сигнал инцидента стали обычными фактами журнала. Журнал —
// объявленный ФАКТ события: нет его — ответ `unsupported` с именем, а не
// молчаливый проход.
//
// Отметка разбора. Прежде разбор подтверждался УДАЛЕНИЕМ буфера: буфер был
// расходником. Журнал расходником не является — его читают гвард «не правь то,
// чего не читал» и сборка набора изменений, — поэтому удалять его нельзя.
// Вместо удаления агент кладёт в свою метку ЧИСЛО: размер журнала на момент
// выдачи директивы, который хук печатает прямо в ней. Следующий конец хода
// смотрит сигналы ПОСЛЕ этого числа. Семантика прежняя: не разобрал — блокирует
// снова; разобрал — молчит; пришёл новый сигнал — блокирует опять и только по
// новому.
//
// Запись кандидатов проходит план-гейт без плана: док в предодобренных зонах
// (gate-exempt-pages.txt), исключение закреплено в «Обслуживании памяти».
// Анти-цикл: stop_hook_active в событии → молчим (не блокируем собственный
// повторный Stop). Fail quiet.
//
// Уступки второму вызову здесь нет намеренно, как и у прежней версии: блок и так
// одноразовый по признаку сигналов, а повторный Stop проходит.
import fs from 'node:fs';
import { readEvent } from './lib/event-claude.js';
import { missingFact, unsupported } from './lib/event.js';
import { block } from './lib/decide-claude.js';
import { readSignals } from './lib/journal.js';
import { instinctFlushMarker } from './lib/paths.js';

// Headless-евалы исключены признаком CRAFT_EVAL=1, как и у stop-routine-facts:
// в прогоне пишущих инструментов нет, требование «отметь разбор» невыполнимо, и
// агент тратит ходы на обходные пути вместо измеряемой задачи.
// Служебный вложенный вызов (классификатор план-гейта) исключён по той же причине,
// что и евал: у него нет ни рутины, ни диалога с Владом, он живёт один ход и
// возвращает одну строку — лишний ход от блокировки роняет сам вызов.
if (process.env.CRAFT_EVAL || process.env.CRAFT_NESTED_CALL) process.exit(0);

const ev = readEvent();
if (ev.stop_active || process.env.CLAUDE_STOP_HOOK_ACTIVE === 'true') {
  process.exit(0);
}

// Объявленный факт: журнал. Его отсутствие — не «сигналов не было», и разница
// между этими двумя вещами называется вслух (решение 8).
const REQUIRES = ['journal'];
const missing = missingFact(ev, REQUIRES);
if (missing) {
  process.stderr.write(`[instinct-flush] unsupported: ${unsupported(missing).capability}\n`);
  process.exit(0);
}
const log = ev.journal;
const mark = instinctFlushMarker();

// Прочитанная отметка: число или ноль. Нечитаемая метка означает «не разбирали»,
// а не «разобрали всё»: ошибка в свою пользу тут молча гасила бы контур.
let from = 0;
try {
  const parsed = Number.parseInt(fs.readFileSync(mark, 'utf8').trim(), 10);
  if (Number.isFinite(parsed) && parsed > 0) from = parsed;
} catch { /* отметки нет — разбираем с начала журнала */ }

const { records, size } = readSignals(log, from);
if (records.length === 0) process.exit(0);

const observations = process.env.CRAFT_OBSERVATIONS_PAGE_ID || '11126344-32e1-8c47-81d2-9079eac43f1f';

block(`[stop-hook] В журнале сессии есть неразобранные сигналы: ${records.length} (журнал ${log}, строки с "op":"error" и "op":"incident" после байта ${from}). Перед завершением хода: 1) прочитай эти строки; 2) выдели из них ПОВТОРЯЕМЫЕ паттерны и дистиллируй кандидатов формата «[скоуп] при [сигнале] → [действии]» (скоуп — слаг проекта или global; только дистиллят, без сырых логов; разовые нерепрезентативные ошибки — пропусти); 3) добавь каждого кандидата отдельным блоком в КОНЕЦ страницы «Наблюдения» дока «Инстинкты агента» (Craft, block-ID ${observations}, position end — только append, чужие блоки не трогать); Craft недоступен — просто пропусти шаг записи; 4) отметь разбор: printf '%s' ${size} > ${mark} — журнал НЕ удаляй, его читают гварды. Ничего достойного кандидата нет — тоже просто отметь разбор.`);
