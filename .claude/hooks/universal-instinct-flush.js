#!/usr/bin/env node
// Stop hook: детектор неразобранных сигналов. Сам НИЧЕГО не дистиллирует и не
// пишет в Craft (хук этого не может) — при наличии неразобранных сигналов
// блокирует завершение хода директивой агенту: дистиллируй кандидатов и сбрось
// их в «Наблюдения» дока «Инстинкты агента», затем отметь разбор.
//
// Сигналы он берёт из ЖУРНАЛА СОБЫТИЙ СЕССИИ (строки `op: error` и
// `op: incident`), а не из отдельного буфера: буфера больше нет, ошибка
// инструмента и сигнал инцидента стали обычными фактами журнала. Журнал —
// объявленный ФАКТ события: нет его — ответ `unsupported` с именем, а не
// молчаливый проход.
//
// Отметка разбора. Прежде разбор подтверждался УДАЛЕНИЕМ буфера: буфер был
// расходником. Журнал расходником не является — его читают гвард «не правь то,
// чего не читал» и сборка набора изменений, — поэтому удалять его нельзя.
//
// Вместо удаления разведены ДВА РАЗНЫХ ФАКТА, и разведены они принципиально:
//   — «разбор сделан» — акт АГЕНТА. Он ставит метку, у неё нет содержимого, и
//     хук её содержимого не читает: значим только сам факт существования;
//   — «докуда разобрано» — знание ХУКА. Хук записывает его в СВОЁ состояние в тот
//     момент, когда выдаёт директиву, и в самой директиве этого числа НЕТ.
// Слить их в один файл нельзя. Тогда горизонт двигал бы гейтимый: агент,
// упёршийся в блокировку конца хода, положил бы в метку заведомо большое число и
// заглушил бы контур до конца сессии — не злым умыслом, а «помогая». Гейтимый не
// пишет собственное предусловие; он может только сказать «сделал».
//
// Семантика прежняя: не разобрал — блокирует снова; разобрал — молчит; пришёл
// новый сигнал — блокирует опять и только по новому.
//
// Запись кандидатов проходит план-гейт без плана: док в предодобренных зонах
// (gate-exempt-pages.txt), исключение закреплено в «Обслуживании памяти».
// Анти-цикл: stop_hook_active в событии → молчим (не блокируем собственный
// повторный Stop). Fail quiet.

import fs from 'node:fs';
import { readEvent } from './lib/event-claude.js';
import { hookOnce } from './lib/once.js';
import { missingFact, unsupported } from './lib/event.js';
import { block } from './lib/decide-claude.js';
import { readSignals } from './lib/journal.js';
import { instinctFlushMarker, instinctFlushState } from './lib/paths.js';

// Headless-евалы исключены признаком CRAFT_EVAL=1, как и у stop-routine-facts:
// в прогоне пишущих инструментов нет, требование «отметь разбор» невыполнимо, и
// агент тратит ходы на обходные пути вместо измеряемой задачи.
// Служебный вложенный вызов (классификатор план-гейта) исключён по той же причине,
// что и евал: у него нет ни рутины, ни диалога с Владом, он живёт один ход и
// возвращает одну строку — лишний ход от блокировки роняет сам вызов.
if (process.env.CRAFT_EVAL || process.env.CRAFT_NESTED_CALL) process.exit(0);

const ev = readEvent();
if (ev.stop_active || process.env.CLAUDE_STOP_HOOK_ACTIVE === 'true') {
  process.exit(0);
}

// Уступка второму вызову. Прежней версии она была не нужна — та ничего не писала,
// и признак одноразовости жил в самом буфере. Теперь хук ПИШЕТ состояние, и два
// процесса одного события (проектная и пользовательская регистрации) гонятся за
// него: первый подтверждает разбор и сносит метку, второй метки уже не видит,
// откатывает горизонт назад и блокирует ход по только что разобранному — плюс две
// директивы в один ответ харнесу. У конца хода идентификатора вызова нет, поэтому
// ключом служит хеш события со сроком в секунды — как у шести соседей по цепочке.
if (!hookOnce(ev.raw, ev.core, import.meta.url)) process.exit(0);

// Объявленный факт: журнал. Его отсутствие — не «сигналов не было», и разница
// между этими двумя вещами называется вслух (решение 8).
const REQUIRES = ['journal'];
const missing = missingFact(ev, REQUIRES);
if (missing) {
  process.stderr.write(`[instinct-flush] unsupported: ${unsupported(missing).capability}\n`);
  process.exit(0);
}
const log = ev.journal;
const mark = instinctFlushMarker();
const stateFile = instinctFlushState();

// Состояние хука: `horizon` — досюда сигналы уже разобраны; `offered` — досюда
// хук выдал их в последней директиве. Нечитаемое состояние означает «не
// разбирали», а не «разобрали всё»: ошибка в свою пользу тут молча гасила бы
// контур.
function readState() {
  try {
    const parsed = JSON.parse(fs.readFileSync(stateFile, 'utf8'));
    const num = (v) => (Number.isFinite(v) && v > 0 ? v : 0);
    return { horizon: num(parsed.horizon), offered: num(parsed.offered) };
  } catch {
    return { horizon: 0, offered: 0 };
  }
}
function writeState(next) {
  try {
    fs.writeFileSync(stateFile, JSON.stringify(next));
  } catch { /* состояние не легло — в худшем случае разбор попросят повторно */ }
}

const state = readState();
let { horizon } = state;

// Метка агента: «разобрал». Читается ТОЛЬКО её существование — содержимое не
// смотрится вовсе, поэтому подделать горизонт ею нечем. Двигается он на то, что
// в прошлой директиве выдал САМ ХУК.
let acknowledged = false;
try {
  fs.statSync(mark);
  acknowledged = true;
} catch { /* агент разбора не подтверждал */ }
if (acknowledged) {
  if (state.offered > horizon) horizon = state.offered;
  writeState({ horizon, offered: 0 });
  try {
    fs.rmSync(mark, { force: true });
  } catch { /* метка не снялась — следующий ход просто увидит тот же горизонт */ }
}

const scan = readSignals(log, horizon);
// Журнал ЕСТЬ, но не читается — это не «сигналов не было». Разницу между этими
// двумя вещами называет имя, а не молчание: молчание тут выдало бы отказ чтения
// за спокойную сессию.
if (scan.status !== 'ok') {
  process.stderr.write(`[instinct-flush] unsupported: ${scan.capability}\n`);
  process.exit(0);
}
const { records, end } = scan;

// Журнал начался заново (его снесли, подменили, он усох), и отметка осталась из
// прошлой его жизни. Разбор читает с начала — значит и горизонт обязан вернуться
// туда же. Двигая его ТОЛЬКО вперёд, хук заклинило бы навсегда: каждый ход он
// блокировал бы тем же сигналом, а агент дописывал бы дубль кандидата.
if (scan.from !== horizon) horizon = scan.from;

if (records.length === 0) {
  // Сигналов в просмотренном куске нет — двигаем горизонт на его конец. Журнал
  // растёт на КАЖДОМ чтении и записи, и без этого каждый следующий конец хода
  // перечитывал бы его с того же старого места: на длинной сессии это
  // квадратично. Потерять при этом нечего — строки за концом последней полной
  // строки в этот скан не попали и найдутся следующим.
  if (end !== horizon) writeState({ horizon: end, offered: 0 });
  process.exit(0);
}

const observations = process.env.CRAFT_OBSERVATIONS_PAGE_ID || '11126344-32e1-8c47-81d2-9079eac43f1f';

// Хук ЗАПОМИНАЕТ, докуда выдал разбор. В директиве этого числа нет: агенту
// сообщать его незачем, а дать ему им распорядиться — значит отдать горизонт.
writeState({ horizon, offered: end });

block(`[stop-hook] В журнале сессии есть неразобранные сигналы: ${records.length} (журнал ${log}, строки с "op":"error" и "op":"incident"). Перед завершением хода: 1) прочитай эти строки; 2) выдели из них ПОВТОРЯЕМЫЕ паттерны и дистиллируй кандидатов формата «[скоуп] при [сигнале] → [действии]» (скоуп — слаг проекта или global; только дистиллят, без сырых логов; разовые нерепрезентативные ошибки — пропусти); 3) добавь каждого кандидата отдельным блоком в КОНЕЦ страницы «Наблюдения» дока «Инстинкты агента» (Craft, block-ID ${observations}, position end — только append, чужие блоки не трогать); Craft недоступен — просто пропусти шаг записи; 4) отметь разбор пустой меткой: : > ${mark} — журнал НЕ удаляй, его читают гварды. Ничего достойного кандидата нет — тоже просто отметь разбор.`);
