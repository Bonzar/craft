#!/usr/bin/env node
// PreToolUse(Bash) guard: блокирует гашение процесса, адресованное ИМЕНЕМ или
// маской. На машине, где экземпляр не один (браузер под несколькими сессиями,
// демон, сервер), такое гашение бьёт по чужим.
//
// Инцидент, ради которого гвард заведён: гашение по точному имени на общем маке
// снесло рабочие браузеры двух чужих сессий вместе со своим замерочным.
// Текстовое правило про это существовало и не удержало — отсюда машинная ступень.
//
// Точное имя от маски здесь ничем не отличается: обе формы бьют по всем
// экземплярам разом, разница только в уверенности прицела.
//
// Пропускается (НЕ блок):
//   - гашение по номеру процесса: `kill 123`, `kill -9 "$(cat pidfile)"`;
//   - всё, что не про гашение.
//
// Ловит и команды, уходящие на другую машину (`ssh host '…'`), потому что видит
// текст вызова целиком.
//
// Регулярки построчные (флаг m): bash-версия звала grep, а он смотрит каждую
// строку отдельно — без этого флага многострочная команда читалась бы иначе.
import { readEvent } from './lib/event-claude.js';
import { deny } from './lib/decide-claude.js';
import { hookOnce } from './lib/once.js';

const REASON = 'Гашение по имени процесса бьёт по чужим экземплярам: на общей машине браузер, демон или сервер подняты несколькими сессиями, и точное имя (-x) от маски (-f) тут ничем не отличается. Адресуй СВОЙ экземпляр: номер процесса из своего pid-файла (kill "$(cat mypid)") либо порт, на котором он слушает (lsof -ti tcp:PORT -sTCP:LISTEN). Своего идентификатора нет — сначала заведи его, а не гаси по имени.';

// Команды, адресующие процесс именем: сами по себе (первая), через подстановку
// поиска по имени (вторая) и через конвейер в xargs (третья).
const BY_NAME = [
  /(^|[\s;&|(]|["'])(pkill|killall)(\s|$)/m,
  /kill[^|;&]*\$\(\s*(pgrep|pidof)/m,
  /(pgrep|pidof)[^|;&]*\|\s*xargs[^|;&]*kill/m,
];

const { raw, core, input } = readEvent();
if (!hookOnce(raw, core, import.meta.url)) process.exit(0);

const command = input.command || '';
if (BY_NAME.some((re) => re.test(command))) {
  // Развёрнутая форма ответа — та же, что печатала bash-версия.
  deny(REASON, { compact: false });
}
process.exit(0);
