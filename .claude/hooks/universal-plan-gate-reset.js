#!/usr/bin/env node
// UserPromptSubmit: обычная реплика Влада ПЕРИМЕТР ГЕЙТА НЕ ГАСИТ — маркер
// одобрения хранит список целей и живёт до смены сессии (файл в /tmp с id);
// отзыв разрешений — обычная просьба Влада, не магическая фраза. Хук чистит
// пометки хода (служебный ход, показ плана, ожидания критика), никогда не
// блокирует сообщение (нет вывода, тихий выход) — и отправляет реплику Влада в
// реестр одобренного фоновым приёмом: прямое указание («сделай короче») видно
// сверке и открывает работу без нового плана.
//
// СЛУЖЕБНОЕ СОБЫТИЕ ходом не считается: сброс по нему обнулял одобрение посреди
// исполнения. Якоря и правила их пополнения — в service-anchors.txt рядом.
// Пустой текст (нет поля, битый вход, нет разборщика — так же подаёт вход тестовый
// раннер) считаем настоящим ходом: лишний сброс дешевле пропущенного.
//
// Отметку критика (plan-critic.*.done) reset НЕ трогает: гейт сверяет её СОДЕРЖИМОЕ
// с хешем файла плана, поэтому правка плана обесценивает отметку сама, а гасить её
// репликой значило бы гонять критика по неизменившемуся тексту.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readEvent } from './lib/event.js';
import {
  serviceTurnMarker, planShownMarker, planCriticPending, approvalRegistry,
} from './lib/paths.js';
import { ingestInBackground } from './lib/registry.js';

const { prompt } = readEvent();

const selfPath = fileURLToPath(import.meta.url);
let dir = path.dirname(selfPath);
try {
  dir = path.dirname(fs.realpathSync(selfPath));
} catch { /* нечего резолвить — берём каталог как есть */ }
const anchorsFile = process.env.CRAFT_SERVICE_ANCHORS || path.join(dir, 'service-anchors.txt');

// Метка «ход начат служебным сообщением» — её читает guard-plan-service-turn, чтобы
// не показывать план повторно, пока Влад не ответил. Ставится здесь, а не в самом гейте:
// словарь якорей уже разобран, а гейт видит только событие показа.
const serviceTurn = serviceTurnMarker();

let anchors = [];
try {
  anchors = fs.readFileSync(anchorsFile, 'utf8').split('\n')
    .filter((line) => line !== '' && !line.startsWith('#'));
} catch { /* словаря нет — всё считаем настоящим ходом */ }

if (anchors.some((anchor) => prompt.startsWith(anchor))) {
  try {
    fs.writeFileSync(serviceTurn, '');
  } catch { /* метка не встала — в худшем случае план покажется повторно */ }
  process.exit(0);
}

// Реплика Влада: ход снова его, показ плана разрешён — снимаем метку служебного хода,
// хеш показанного, счётчик прогонов критика и его ожидания, разговор начинается заново.
// Ожидания снимаются вместе со счётчиком: критик, запущенный до реплики, дозавершился бы
// уже в новом разговоре и накрутил чужой счётчик — плато набралось бы прогонами, которых
// в этом разговоре не было. Цена — такой критик отметки не поставит, нужен новый прогон.
//
// Счётчик прогонов критика реплика НЕ снимает: обкатка привязана к плану, а не к ходу —
// «покажи» или замечание к плану её не завершают. Обнуление по реплике делало плато
// недостижимым в живом диалоге. Снимает его одобрение плана (plan-gate-approve).
for (const file of [serviceTurn, planShownMarker(), planCriticPending()]) {
  try {
    fs.rmSync(file, { force: true });
  } catch { /* нечего снимать */ }
}

// Автономный прогон реестр НАПОЛНЯЕТ: его задание — это и есть то, что рутине
// разрешено, и правки рутины сверяются с ним наравне со всеми. Выхода по
// автономности у гейта больше нет, и обходить приём было бы нечем.
//
// Пустая реплика в реестр не идёт. Длинная — идёт ЦЕЛИКОМ: срез по длине
// отрезал согласие на середине, и разбор получал полтребования вместо
// требования. Хвостовые переводы строки снимаются, на этом обработка кончается.
if (!/\S/.test(prompt)) process.exit(0);

const said = String(prompt).replace(/\n+$/, '');

// Реплика уходит в реестр ФОНОВЫМ приёмом: разбор решает, что тут цель, что
// задача и относится ли материал к уже одобренному, — а ход Влада при этом не
// ждёт модель. Пока приём идёт, у реестра стоит метка, и сверка правки её
// дожидается: сверять по недособранному реестру значит отклонять только что
// разрешённое.
ingestInBackground(approvalRegistry(), 'reply', said);
