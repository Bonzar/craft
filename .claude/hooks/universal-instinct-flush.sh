#!/usr/bin/env bash
# Stop hook: детектор несброшенных наблюдений. Сам НИЧЕГО не дистиллирует и не
# пишет в Craft (шелл этого не может) — при непустом сигнальном буфере блокирует
# завершение хода директивой агенту: дистиллируй кандидатов и сбрось их в
# «Наблюдения» дока «Инстинкты агента», затем очисти буфер.
#
# Запись кандидатов проходит план-гейт без плана: док в предодобренных зонах
# (gate-exempt-pages.txt), исключение закреплено в «Обслуживании памяти».
# Анти-цикл: stop_hook_active в событии → молчим (не блокируем собственный
# повторный Stop). Fail quiet.
set -u

# Headless-евалы исключены признаком CRAFT_EVAL=1, как и у stop-routine-facts:
# в прогоне пишущих инструментов нет, требование «очисти буфер» невыполнимо, и
# агент тратит ходы на обходные пути вместо измеряемой задачи.
[[ -n "${CRAFT_EVAL:-}" ]] && exit 0

input="$(cat)"
active="$(jq -r '.stop_hook_active // false' <<<"$input" 2>/dev/null)" || exit 0
[[ "$active" == "true" || "${CLAUDE_STOP_HOOK_ACTIVE:-}" == "true" ]] && exit 0

buf="${OBSERVE_BUFFER:-/tmp/agent-observe.${CLAUDE_CODE_SESSION_ID:-default}.log}"
[[ -s "$buf" ]] || exit 0

INSTINCTS_OBS_ID="${CRAFT_OBSERVATIONS_PAGE_ID:-11126344-32e1-8c47-81d2-9079eac43f1f}"

reason="[stop-hook] В сигнальном буфере сессии есть неразобранные наблюдения ($buf). Перед завершением хода: 1) прочитай буфер; 2) выдели из него ПОВТОРЯЕМЫЕ паттерны и дистиллируй кандидатов формата «[скоуп] при [сигнале] → [действии]» (скоуп — слаг проекта или global; только дистиллят, без сырых логов; разовые нерепрезентативные ошибки — пропусти); 3) добавь каждого кандидата отдельным блоком в КОНЕЦ страницы «Наблюдения» дока «Инстинкты агента» (Craft, block-ID $INSTINCTS_OBS_ID, position end — только append, чужие блоки не трогать); Craft недоступен — просто пропусти шаг записи; 4) очисти буфер (rm файла). Ничего достойного кандидата нет — тоже просто очисти буфер."

jq -cn --arg r "$reason" '{"decision":"block","reason":$r}'
exit 0
