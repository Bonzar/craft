#!/usr/bin/env bash
# PreToolUse на ExitPlanMode: не показывать Владу план, трогающий системную
# зону, пока эту его версию не обкатал plan-critic. Рычаг инцидента «показал
# системный план без критика» — правило про обкатку живёт в Craft-доке «План
# правок», хук лишь не даёт его пропустить молча.
#
# Перехват именно на ПОКАЗЕ, а не на записи файла плана: критик читает план
# из файла, поэтому гейт на записи заблокировал бы само планирование.
#
# Судит гейт по файлу плана, записанному в этой сессии
# (universal-mark-plan-file.sh); файла нет — гейт молчит. Показ несёт и сам текст
# плана, поэтому расхождение показанного с файлом отклоняется отдельно и до
# проверки зоны — иначе подменой одного из двух проезжает любой план.
#
# Обхода по CRAFT_AUTONOMOUS здесь нет намеренно: автономный прогон планов не
# показывает, а флаг-лазейка в гейте — приглашение ею воспользоваться.
#
# Fail open на всём неожиданном: сломанный гейт не должен клинить работу.
set -u

# Хеш файла. Запасная команда обязательна: на маке из README основной нет, хеш вышел бы
# пустым, и гейт молча выключился бы. Формат первого токена у обеих команд одинаков.
hash_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" 2>/dev/null | cut -d' ' -f1
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" 2>/dev/null | cut -d' ' -f1
  fi
}

# Уступаем user-level копии — иначе двойной прогон на локальной машине.
if [[ -n "${CLAUDE_PROJECT_DIR:-}" && "$0" == "$CLAUDE_PROJECT_DIR"/* \
      && -e "$HOME/.claude/hooks/$(basename "$0")" ]]; then
  exit 0
fi

input="$(cat)"
tool="$(jq -r '.tool_name // ""' <<<"$input" 2>/dev/null)" || exit 0
[[ "$tool" == "ExitPlanMode" ]] || exit 0

sid="${CLAUDE_CODE_SESSION_ID:-default}"
plan="${CRAFT_PLAN_FILE:-$(cat "${CRAFT_PLAN_FILE_MARKER:-/tmp/plan-file.${sid}.path}" 2>/dev/null)}"
[[ -n "$plan" && -r "$plan" ]] || exit 0

# Гейт судит по ФАЙЛУ плана, а показать можно другой текст — так системный план
# проезжает поверх безобидного файла. Сверка стоит ВЫШЕ триггера зоны намеренно:
# ниже она закрыла бы один обход и открыла зеркальный (несистемный показ поверх
# системного файла). Хвостовые переводы строки съедает подстановка, поэтому обычный
# показ проходит.
shown="$(jq -r '.tool_input.plan // ""' <<<"$input" 2>/dev/null)"
if [[ -n "$shown" && "$shown" != "$(cat "$plan" 2>/dev/null)" ]]; then
  jq -cn '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:"Показываемый план не совпадает с файлом плана. Гейт судит по файлу: запиши в него нынешний текст и прогони критика по нему, либо покажи то, что записано."}}'
  exit 0
fi

# Системная зона: правило (юнит [система] в плане), скилл, хук, настройки,
# CLAUDE.md. Триггер намеренно шире источника — «План правок» пускает без
# критика точечную правку системной зоны по дословной формулировке Влада, а
# машинного различителя «дословно от Влада» против «сочинил агент» нет.
#
# Читаются ПОЛЯ плана — строки, не начатые знаком цитаты: заголовок юнита и строка
# адреса. Дословный текст живёт в цитатном блоке, поэтому его двойники полей сюда не
# попадают. Вырезателя код-блоков нет намеренно: любой разбор заборов обманывается
# вложенностью и глушит гейт молча, а лишний вызов критика дёшев. Остаточные способы
# проехать — иной тип юнита, жирный заголовок, адрес на второй строке или без
# литерального пути, звёздочка вместо дефиса, неразрывный пробел в отступе.
export LC_ALL=C.UTF-8   # без UTF-8-локали grep -i не складывает регистр кириллицы
fields="$(grep -v '^[[:space:]]*>' "$plan")"
grep -qiE '^[[:space:]]*#+[[:space:]]*\[система' <<<"$fields" \
  || grep -qiE '^[[:space:]]*-[[:space:]]*где:.*(\.claude/|CLAUDE\.md)' <<<"$fields" || exit 0

markfile="${CRAFT_PLAN_CRITIC_MARKER:-/tmp/plan-critic.${sid}.done}"
want="$(hash_of "$plan")"
line="$(cat "$markfile" 2>/dev/null)"
have="$(cut -f1 <<<"$line")"          # голая отметка старого вида читается тем же полем
verdict="$(cut -f2 -s <<<"$line")"
[[ -n "$want" && "$want" == "$have" ]] && exit 0

# Вердикт «блокеров нет» разрывает самоинвалидацию: критик сказал, что держащих показ
# замечаний нет, значит правка шероховатостей после него круга не стоит — показ проходит,
# хотя хеш разошёлся. Поблажка ОДНОРАЗОВАЯ: вердикт тут же снимается, остаётся голый хеш.
# Иначе один вердикт открывал бы любой последующий текст в этом файле — план переписан
# целиком, а показан под чужой обкаткой.
if [[ "$verdict" == "noblockers" ]]; then
  printf '%s\n' "$have" > "$markfile" 2>/dev/null || true
  exit 0
fi

# Машинное «Плато». Одобрение критика самоинвалидирующееся по устройству: отметка стоит на
# хеше файла, а работа критика — выдать замечания, выполнение которых этот хеш меняет.
# Без условия завершения контур уходит в круг «критик → правка → отказ». Три завершённых
# прогона — потолок: правило велит показать план как есть, и гейт перестаёт этому мешать.
# Счётчик ведёт universal-mark-plan-critic.sh, обнуляет ОДОБРЕНИЕ плана
# (universal-plan-gate-approve.sh): обкатка кончается показом, а не репликой Влада —
# обнуление по реплике делало плато недостижимым в живом диалоге, где петля и случается.
runs="$(cat "${CRAFT_PLAN_CRITIC_RUNS:-/tmp/plan-critic.${sid}.runs}" 2>/dev/null)"
[[ "$runs" =~ ^[0-9]+$ ]] && (( runs >= 3 )) && exit 0

jq -cn '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:"План трогает системную зону (правило, скилл, хук, CLAUDE.md), а plan-critic эту его версию не обкатывал. Два законных пути: либо отработай замечания и прогони критика ЗАНОВО по новому тексту, либо, если правок не делал, просто прогони критика по нынешнему файлу. Показ идёт сразу после прогона: любая правка плана после него снова обесценивает обкатку. Три прогона по одному разговору — плато: гейт пропустит показ, и план показывается как есть с открытым вопросом о застрявших местах."}}'
exit 0
