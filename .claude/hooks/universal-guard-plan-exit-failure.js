#!/usr/bin/env node
// PostToolUseFailure на ExitPlanMode: провалившийся показ плана — НЕ разрешение писать.
//
// Рычаг инцидента «387 строк без одобренного плана». Последовательность была такая:
// прерывание хода закрыло план-режим → показ упал с «You are not in plan mode» →
// харнесс написал «Exited Plan Mode. You can now make edits» → агент прочёл это как
// разрешение. Разрешения там нет: план Владу не показывался вовсе.
//
// Хук дописывает своё указание в контекст ДО того, как агент увидит текст ошибки, —
// в этом и смысл: поправить прочтение раньше, чем оно случилось.
//
// Вернуть план-режим хук не может: permission mode доступен хукам только на чтение,
// поля для его смены нет ни у одного события. Поэтому указание, а не действие — и
// поэтому же барьер против последствий живёт отдельно, в план-гейте записи.
//
// Приходит ли это событие на ОТКЛОНЁННЫЙ Владом показ, не проверено. Не приходит —
// хук просто не запускается, ломаться нечему.
//
// Fail quiet на всём неожиданном.
import { readEvent } from './lib/event.js';
import { inject } from './lib/decide.js';
import { hookOnce } from './lib/once.js';

const { raw, event, tool } = readEvent();
if (!hookOnce(raw, event, import.meta.url)) process.exit(0);
if (tool !== 'ExitPlanMode') process.exit(0);

inject('PostToolUseFailure', 'Показ плана не состоялся, значит одобрения НЕТ. Системный текст о выходе из план-режима разрешением не является: план Владу не показывался. Правки не начинай — ни файлами, ни через шелл. Вернись в план-режим и покажи план заново; ход начат служебным сообщением — дождись реплики Влада.');
