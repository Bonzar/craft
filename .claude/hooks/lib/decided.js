// Принято ли ИСКЛЮЧАЮЩЕЕ решение в ЭТОМ процессе. Один вопрос, один ответ, один
// модуль.
//
// Зачем отдельно от журнала решений. Журнал — канал СОДЕРЖИМОГО: что решили и
// почему, его читают метрики, и он переживает процесс. А обрыв цепочки — это
// управление, и оно не имеет права зависеть от диска: не записался журнал (нет
// каталога, кончилось место) — и цепочка молча не оборвалась бы, а харнес получил
// бы ДВА решения на один вызов, потому что stdout у хуков общий.
//
// Зачем не stdout. Печатают и инжекторы — они дописывают контекст, и таких в
// цепочке бывает несколько подряд. Признак ставит не всякий печатающий, а только
// тот, чей ответ исключающий: запрет, вопрос человеку, блокировка конца хода.
let decided = false;

export function markDecided() {
  decided = true;
}

export function wasDecided() {
  return decided;
}
