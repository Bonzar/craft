// Состав и порядок правил гейта. Это ЕДИНСТВЕННОЕ место, где они заданы: раньше
// четыре разных решения (якорь, предодобренная зона, рубильник, сверка с
// реестром) были размазаны по одному файлу, и порядок хранился порядком строк в
// коде — добавить пятое значило вписать его в середину и надеяться.
//
// Порядок значим и идёт сверху вниз. Первое решение обрывает цепочку — так же,
// как у хуков в диспетчере.
//
// ПОЧЕМУ ИМЕННО ТАКОЙ:
//   anchor       — раньше всех: без якоря работа ещё не начата, и сверять не с
//                  чем. Предодобренная зона открывает гейт, а не отменяет якорь;
//                  рубильник снимает сверку правки с одобренным, а якорь говорит
//                  не про правку, а про то, куда ляжет след сессии;
//   exempt-scope — зона прямого редактирования (напр. «Продукты») идёт без плана;
//   switch       — рубильник Влада: проверки сняты тапом, след остаётся в логе;
//   registry     — сверка с реестром одобренного, последнее слово.
import * as anchor from './gate-rules/anchor.js';
import * as exemptScope from './gate-rules/exempt-scope.js';
import * as gateSwitch from './gate-rules/switch.js';
import * as registry from './gate-rules/registry.js';

