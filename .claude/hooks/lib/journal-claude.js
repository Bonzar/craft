// Форма вызова для журнала под харнес Claude Code: адаптер. Здесь и только здесь
// слой знает, какой инструмент ЧИТАЕТ файл и каким полем входа этот файл назван;
// общая часть журнала (journal.js) получает форму данными и решает по ней сама.
//
// journalShape(инструмент, вход) → форма вызова:
//   {kind: 'read', paths}   — чтение НАЗВАННЫХ файлов;
//   {kind: 'edit', path}    — правка содержимого;
//   {kind: 'command', text} — команда интерпретатора;
//   {}                      — всё прочее.
//
// Правку и команду опознаёт callShape адаптера имён (tool-flags-claude.js): своя
// копия этого списка разъехалась бы с ним, и один и тот же вызов у метрик
// считался бы правкой, а у журнала — нет. Здесь дописывается только то, чего у
// него нет: ЧТЕНИЕ. Гвардам чтение до сих пор было не нужно, поэтому формы у
// него и не было.
import { callShape } from './tool-flags-claude.js';

// Инструменты, которые называют ПРОЧИТАННЫЙ ФАЙЛ, и поле, которым он назван.
// Поиск и перечисления сюда не входят намеренно: их `path` — каталог обхода, а
// не прочитанный файл, и записать его целью значило бы разрешить правку по
// чтению, которого не было. У таких вызовов цель остаётся неназванной, и это
// честный ответ, а не пропуск.
const READ_TOOL_PATH = { Read: 'file_path' };

export function journalShape(tool, input = {}) {
  const field = READ_TOOL_PATH[tool];
  if (field) {
    const target = input && typeof input === 'object' ? input[field] : '';
    return { kind: 'read', paths: target ? [String(target)] : [] };
  }
  return callShape(tool, input);
}
