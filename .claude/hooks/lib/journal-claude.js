// Форма вызова для журнала под харнес Claude Code: адаптер. Здесь и только здесь
// слой знает, какой инструмент ЧИТАЕТ файл, каким полем входа этот файл назван и
// про какие читающие вызовы известно, что назвать прочитанное нечем. Общая часть
// журнала (journal.js) получает форму данными и решает по ней сама.
//
// journalShape(инструмент, вход) → форма вызова:
//   {kind: 'read', paths}    — чтение НАЗВАННЫХ файлов;
//   {kind: 'read-nothing'}   — читающий вызов, у которого читать нечего по природе;
//   {kind: 'note', ref}      — запись в базу заметок по её адресу;
//   {kind: 'edit', path}     — правка содержимого;
//   {kind: 'command', text}  — команда интерпретатора;
//   {}                       — всё прочее.
//
// Правку и команду опознаёт callShape адаптера имён (tool-flags-claude.js): своя
// копия его списка разъехалась бы с ним, и один и тот же вызов у метрик считался
// бы правкой, а у журнала нет. Здесь дописано только то, чего у него нет:
// ЧТЕНИЕ и АДРЕС записи в базу заметок.
//
// Почему адрес базы отдельно от callShape: там у него есть запасной вариант «имя
// инструмента вместо адреса», и он законен — метрики спрашивают лишь «менял ли
// вызов мир», и им довольно НЕПУСТОЙ строки. Журнал повышает ту же строку до
// утверждения о том, ЧТО изменено, и запасной вариант превращается в подделку:
// сборка изменений прочитала бы имя инструмента как адрес блока. Здесь запасного
// варианта нет — нет адреса, и общая часть назовёт это словом.
import { callShape } from './tool-flags-claude.js';
import { isNoteWrite, noteRef } from './note-write-craft.js';

// Инструменты, которые называют ПРОЧИТАННЫЙ ФАЙЛ, и поле, которым он назван.
const READ_TOOL_PATH = { Read: 'file_path' };

// Читающие вызовы, у которых прочитанного файла нет ПО ПРИРОДЕ вызова: список
// работы, перечисление агентов и скиллов, поиск в сети, чтение фонового вывода.
// У них пустой список целей — это факт «называть нечего», а не пропуск, и путать
// эти два случая нельзя: на них по-разному отвечает гвард чтения.
const READS_NOTHING_NAMED = new Set([
  'TaskList', 'TaskGet', 'TaskOutput', 'ListAgents', 'ListSkills', 'ListPlugins',
  'ListMcpResourcesTool', 'ReadNotifications', 'BashOutput', 'ToolSearch', 'WebSearch',
]);

export function journalShape(tool, input = {}) {
  const src = input && typeof input === 'object' ? input : {};
  const field = READ_TOOL_PATH[tool];
  if (field) {
    const target = src[field];
    // Поля нет — форма пустая: «читал, назвать нечем» скажет общая часть. Пустой
    // список целей тут был бы неотличим от «читать нечего по природе».
    if (target) return { kind: 'read', paths: [String(target)] };
    return {};
  }
  if (isNoteWrite(tool)) return { kind: 'note', ref: noteRef(src) };
  const shape = callShape(tool, src);
  if (shape.kind) return shape;
  if (READS_NOTHING_NAMED.has(tool)) return { kind: 'read-nothing' };
  // Формы у вызова нет. Что это значит, решает ОБЛАСТЬ вызова, а её здесь не
  // спрашивают: у читающего вызова пустая форма означает «прочитан названный
  // объект, а назвать его нечем» (обход каталогов, выборка по образцу, сеть,
  // чтение сторонним сервером — в том числе заметки базы), у прочих — «неизвестно,
  // чем был вызов». Оба ответа даёт общая часть, и оба она называет словом.
  return {};
}
