// Ключ следа события: им строка журнала решений сшивается с записью метрик.
//
// ФОРМУЛА, одна на все языки (второй экземпляр — runtime/pylib/key.py):
//
//   key = call_id,                                   если он непустой;
//         sha256(сырые байты события).hex[:16],      иначе.
//
// Байты — ровно то, что харнес подал процессу на stdin, без переразбора и
// перекодировки: два процесса, получившие одно событие, обязаны сойтись на одном
// ключе, а любой промежуточный JSON.stringify зависит от порядка ключей и от
// того, кто его собирал.
//
// Поэтому сюда приходит БУФЕР, а не строка. Строка — это уже результат разбора
// как UTF-8, и на байтах, которые в UTF-8 не разбираются, Node подставляет U+FFFD:
// ключ разошёлся бы с питоновским, который хеширует сами байты.
//
// Почему не номер процесса. Прежде ключом был uuid, выданный обёрткой на запуск.
// Под диспетчером метрики и решатель живут в ОДНОМ процессе, и он их сшивал; у
// пакета процесс свой, и его решение не сошлось бы с записью вызова никогда —
// отказ пакета молча исчезал бы из сводки.
//
// Ключ не уникален сам по себе, и на это опираться нельзя: событие до вызова и
// событие после него несут ОДИН идентификатор вызова, а два байт-в-байт
// одинаковых события без него дают один хеш. Поэтому сшивают по ПАРЕ «ключ и имя
// события» (lib/metrics-summary.js), а не по одному ключу.
import { sha256 } from './hash.js';

export function eventKey(callId, raw) {
  const id = typeof callId === 'string' ? callId.trim() : '';
  if (id) return id;
  const bytes = Buffer.isBuffer(raw) ? raw : Buffer.from(String(raw ?? ''), 'utf8');
  return sha256(bytes).slice(0, 16);
}
