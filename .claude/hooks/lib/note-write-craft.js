// Запись в базу заметок Craft: адаптер под рабочую систему. Здесь и только
// здесь слой знает, каким инструментом Влад пишет в базу и чем в его входе
// назван адрес записи; общая часть и адаптер харнеса получают ВОЗМОЖНОСТЬ
// «запись в базу заметок», а не имя инструмента.
//
// isNoteWrite(инструмент) → пишет ли этот вызов в базу заметок.
// noteRef(вход) → адрес записи для формы вызова: блок базы, иначе пусто.

// MCP-инструмент Craft: имя сервера у каждого чекаута своё, поэтому смотрим на
// хвост имени, а не на строку целиком.
export const isNoteWrite = (tool) => /__craft_write$/.test(String(tool || ''));

export const noteRef = (input = {}) => String(input.block_id || input.id || '');
