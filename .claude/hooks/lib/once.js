// Уступка второму вызову того же события.
//
// Хук зарегистрирован сразу в двух местах — в проектных настройках репозитория и
// в пользовательских, которые ставит install.sh. Оба вызова приходят на одно
// событие, и без дедупликации хук отрабатывает дважды: двойная директива в
// контексте, двойной отказ, двойной инкремент счётчиков.
//
// Уступка идёт в два шага, потому что двойная регистрация бывает двух видов.
//
// ШАГ 1 — по чекауту. Локально сессии режется отдельный воркри: проектная
// регистрация исполняет файл хука ИЗ него, а пользовательская — файл основного
// чекаута. Это разные файлы разных версий, и работать должен тот, чей файл лежит
// в чекауте сессии: его код и есть код этой сессии. Посторонний уступает.
// Чекаут сессии опознаётся по каталогу, который событие приносит с собой, а не
// по переменной окружения с корнем проекта: в окружении инструментов её нет, и
// правило, стоящее на ней, молча выключилось бы там, где её не задают.
//
// ШАГ 2 — по факту. Когда обе регистрации ведут в ОДИН файл, пути совпадают
// буквально и признака «кто из двух» не остаётся. Тогда решает занятие события:
// первый вызов ставит метку, второй видит занятое и выходит.
//
// Ключ метки — имя файла хука, ИМЯ СОБЫТИЯ и ИДЕНТИФИКАТОР ВЫЗОВА (`call_id`
// ядра), который несёт каждое инструментальное событие.
//
// Имя события в ключе обязательно: у одного вызова инструмента идентификатор
// общий на событии до вызова и после него, и хук, стоящий на обоих, по ключу из
// одного идентификатора гасил бы своё же событие после вызова меткой,
// оставленной до, — то есть молча терял бы половину событий.
//
// Идентификатор вызова точнее хеша содержимого: он не зависит от того, byte-in-
// byte ли совпали два вызова одной регистрации, и не требует срока — другого
// вызова с этим идентификатором и этим событием не будет. Метки поэтому
// убираются по возрасту, а не протухают (см. sweep ниже).
//
// У событий без идентификатора (реплика, старт, конец хода, компакция) ключ —
// содержимое события, а срок жизни метки — единицы секунд: два вызова одной
// регистрации приходят одновременно, а следующее такое же событие — позже.
//
// Имя в ключе берётся БЕЗ ЛЮБОГО расширения, а не только без `.sh`, как в
// bash-версии: пока слой переезжает, рядом лежат две версии одного хука, и по
// разным ключам они обе отработали бы на одно событие — ровно то, от чего этот
// механизм и написан.
import fs from 'node:fs';
import path from 'node:path';
import { sha256 } from './hash.js';
import { hookOnceDir } from './paths.js';

// true — в чекауте сессии лежит файл ЭТОГО же хука, а исполняется другой:
// значит вызов посторонний и уступает.
function yieldsToSessionCheckout(event, selfPath) {
  const cwd = event && typeof event.cwd === 'string' ? event.cwd : '';
  if (!cwd) return false;
  let probe;
  try {
    if (!fs.statSync(cwd).isDirectory()) return false;
    probe = fs.realpathSync(cwd);
  } catch {
    return false;
  }

  // Имя без расширения — по той же причине, что и ключ метки ниже: пока слой
  // переезжает, чекаут сессии может нести .sh там, где исполняется .js. Файл
  // чекаута и есть код этой сессии независимо от того, чем он написан.
  const base = path.basename(selfPath).replace(/\.[^.]+$/, '');
  const selfDir = path.dirname(selfPath);
  // Раскладка каталога хуков берётся ИЗ ПУТИ САМОГО ХУКА, а не зашивается: где
  // харнес держит хуки — его дело, а искать надо ту же раскладку в соседнем
  // чекауте. Два последних сегмента и есть она (у Claude Code это `.claude/hooks`).
  const layout = selfDir.split(path.sep).slice(-2);
  // Чекаут — ближайший каталог вверх от рабочего, у которого есть свой каталог
  // хуков с файлом этого имени. Именно файл, а не сам факт репозитория: воркри
  // может быть старее основного чекаута и нужного хука ещё не содержать.
  // Сравниваются КАТАЛОГИ, а не пути файлов: у одноимённых файлов это одно и то
  // же, а при разных расширениях сравнение путей объявило бы посторонним свой же
  // экземпляр из того же каталога.
  while (probe && probe !== '/') {
    const hooks = path.join(probe, ...layout);
    let names = [];
    try {
      names = fs.readdirSync(hooks);
    } catch { /* каталога хуков здесь нет — идём выше */ }
    if (names.some((n) => n.replace(/\.[^.]+$/, '') === base)) {
      const selfReal = fs.existsSync(selfDir) ? fs.realpathSync(selfDir) : selfDir;
      return selfReal !== fs.realpathSync(hooks);
    }
    probe = path.dirname(probe);
  }
  return false;
}

// Метка по идентификатору вызова не протухает, поэтому её убирает уборщик:
// вызов с этим идентификатором больше не повторится, и метка старше часа не
// нужна никому. Каталог сканируется не чаще раза в десять минут — право на
// уборку забирает тот, кто обновил файл-отметку; без этого метки копились бы
// в /tmp по каталогу на каждый вызов каждого хука до конца жизни машины.
const SWEEP_EVERY_MS = 10 * 60 * 1000;
const MARK_TTL_MS = 60 * 60 * 1000;
const SWEEP_STAMP = 'hook-once.sweep';

// Протухла ли метка. Метки нет вовсе — считаем протухшей: событие свободно.
function markExpired(mark) {
  try {
    return Date.now() - fs.statSync(mark).mtimeMs > MARK_TTL_MS;
  } catch {
    return true;
  }
}

function sweep(dir) {
  const stamp = path.join(dir, SWEEP_STAMP);
  try {
    if (Date.now() - fs.statSync(stamp).mtimeMs < SWEEP_EVERY_MS) return;
  } catch { /* отметки ещё нет — убираем и заводим её */ }
  try {
    fs.writeFileSync(stamp, '');
  } catch {
    return; // каталог не пишется — уборка не наше дело
  }
  let names = [];
  try {
    names = fs.readdirSync(dir);
  } catch {
    return;
  }
  const now = Date.now();
  for (const name of names) {
    if (!name.startsWith('hook-once.') || name === SWEEP_STAMP) continue;
    const mark = path.join(dir, name);
    try {
      if (now - fs.statSync(mark).mtimeMs > MARK_TTL_MS) fs.rmSync(mark, { recursive: true, force: true });
    } catch { /* метка пропала сама */ }
  }
}

// true — работай; false — уступи (посторонний экземпляр либо занятое событие).
export function hookOnce(raw, event, moduleUrl) {
  // Выключатель гасит ОБА шага разом: иначе исход кейсов зависел бы от того, из
  // какого каталога запущен прогон тестов.
  if (process.env.HOOK_ONCE === 'off') return true;

  const selfPath = new URL(moduleUrl).pathname;
  if (yieldsToSessionCheckout(event, selfPath)) return false;

  const name = path.basename(selfPath).replace(/\.[^.]+$/, '');
  const dir = hookOnceDir();

  // Инструментальное событие: ключ — событие и идентификатор вызова, срока нет.
  const id = event && typeof event.call_id === 'string' ? event.call_id.trim() : '';
  if (id) {
    const safe = (text) => String(text).replace(/[^A-Za-z0-9_-]/g, '_').slice(0, 64);
    const idMark = path.join(dir, `hook-once.${name}.id.${safe(event.event || 'event')}.${safe(id)}`);
    try {
      fs.mkdirSync(idMark);
      sweep(dir);
      return true;
    } catch {
      // Метка есть — событие занято, но только пока она не протухла: уборка
      // сносит метки старше MARK_TTL_MS, и метка того же возраста, до которой
      // уборка ещё не дошла, обязана значить то же самое. Иначе исход зависел
      // бы от того, успел ли кто-то прибраться.
      return markExpired(idMark);
    }
  }

  // Событие без идентификатора: ключ — содержимое, срок — секунды.
  const key = sha256(raw ?? '');
  const mark = path.join(dir, `hook-once.${name}.${key}`);
  const ttl = Number(process.env.HOOK_ONCE_TTL || 5);

  // Создание каталога атомарно: из двух одновременных вызовов ровно один его
  // создаёт, второй получает отказ и уступает.
  try {
    fs.mkdirSync(mark);
    return true;
  } catch {
    // Метка уже есть — решает её возраст.
  }

  let age = Infinity;
  try {
    age = (Date.now() - fs.statSync(mark).mtimeMs) / 1000;
  } catch {
    return true;
  }
  if (age <= ttl) return false;

  // Метка протухла (то же сообщение повторили позже) — занимаем событие заново.
  try {
    const now = new Date();
    fs.utimesSync(mark, now, now);
  } catch { /* не вышло обновить метку — работаем всё равно */ }
  return true;
}
