// Журнал событий сессии: строка на каждое ЧТЕНИЕ и каждую ЗАПИСЬ, плюс строка
// на сигнал хода (ошибка инструмента, сигнал инцидента).
//
// Зачем он есть. Читатели слоя — гвард «не правь то, чего не читал» и сборка
// набора изменений в базе заметок — берут факты ОТСЮДА, а не из транскрипта
// харнеса. Транскрипт есть не у всякого харнеса и у каждого свой; журнал
// строится из КАНОНИЧЕСКОГО события и потому одинаков для всех.
//
// Формат — JSONL, строка на факт. Четыре поля стоят у КАЖДОЙ строки, какой бы ни
// была операция: читателю не приходится знать, у какого `op` какая форма.
//   ts      — когда (ISO-8601 UTC);
//   op      — что за операция (OPS ниже);
//   tool    — чем сделана; строку приносит обёртка, здесь её не разбирают;
//   call_id — идентификатор вызова ИЗ ЯДРА события; пусто там, где харнес его не
//             даёт (реплика).
// Сверх них по смыслу операции: `targets` — над чем (СПИСКОМ: у команды целей
// бывает несколько), `text` — тело сигнала, `unsupported` — имя того, чего не
// хватило.
//
// Имён инструментов здесь нет: область вызова и его форму приносит адаптер
// харнеса (journal-claude.js), разбор команды — адаптер интерпретатора
// (write-targets-bash.js). Общая часть получает их результат данными.
//
// Содержимое правок, команд и ответов инструментов в журнал НЕ идёт: у сигнала
// пишется голова текста, и только у него — по ней инстинкт-контур и различает
// повторяющиеся неудачи.
//
// ЖУРНАЛ НЕ ПОКИДАЕТ МАШИНУ. Он живёт в каталоге состояния и не публикуется
// никуда: ни в ветку метрик, ни в сводку, ни в донат. В ветку метрик уезжают
// только ЧИСЛА; строка журнала туда не попадает никогда. Здесь лежат путь к
// файлам, текст реплики Влада и вывод инструментов — то же различение, что уже
// сделано в журнале решений, где хранится КЛАСС причины отказа, а не её текст,
// именно потому что он переживает сессию. Читателей у журнала будет больше, чем у
// буфера, поэтому правило записано здесь, а не подразумевается.
import fs from 'node:fs';
import { eachJsonl } from './jsonl.js';
import { unsupported } from './event.js';
import { mutationOf, durableTargets } from './write-targets.js';

export const OPS = Object.freeze({
  READ: 'read',
  WRITE: 'write',
  ERROR: 'error',
  INCIDENT: 'incident',
  // Вопрос «менял ли вызов мир» неразрешим, потому что адаптера нет. Строка всё
  // равно ложится: молчание тут читалось бы как «ничего не делал», а это
  // догадка. Имя недостающего стоит в `unsupported` (решение 8).
  UNKNOWN: 'unknown',
});

// Сигнальные операции: по ним работает инстинкт-контур. Прежде их копил
// отдельный эфемерный буфер; теперь это обычные строки журнала, и читатель
// отличает их по `op`, а не по тому, в каком файле они лежат.
export const SIGNAL_OPS = Object.freeze([OPS.ERROR, OPS.INCIDENT]);

// Голова текста в БАЙТАХ, без обрыва посреди символа и без хвостовых переводов
// строки: сигнал ложится одной строкой, и длина у него ограничена.
export function head(text, limit) {
  const cut = Buffer.from(`${String(text ?? '')}\n`, 'utf8').subarray(0, limit);
  let end = cut.length;
  while (end > 0 && cut[end - 1] === 0x0a) end -= 1;
  return cut.subarray(0, end).toString('utf8').replace(/\n/g, ' ');
}

// Строка журнала: общая часть у всех операций одна, остальное дописывается
// вызывающим. Время приходит числом, чтобы одно событие давало одну метку у
// всех своих строк.
export function fact({
  op, tool = '', callId = '', at = Date.now(),
}, extra = {}) {
  return {
    ts: new Date(at).toISOString(),
    op: String(op || ''),
    tool: String(tool || ''),
    call_id: String(callId || ''),
    ...extra,
  };
}

// Возвращает, ЛЕГЛА ли строка: производителю это безразлично (журнал не
// пополнился, ход цел), а кейсу — нет.
export function appendFact(file, record) {
  if (!file) return false;
  try {
    fs.appendFileSync(file, `${JSON.stringify(record)}\n`);
    return true;
  } catch { return false; }
}

// Что за операция и над чем — по СОСТОЯВШЕМУСЯ вызову.
//
//   scope — область вызова от адаптера харнеса: {reads}|{session}|{};
//   call  — форма вызова оттуда же:
//     {kind:'read', paths}     — чтение НАЗВАННЫХ файлов;
//     {kind:'read-nothing'}    — читающий вызов, у которого читать нечего;
//     {kind:'edit', path}      — правка содержимого по пути;
//     {kind:'note', ref}       — запись в базу заметок по её адресу;
//     {kind:'command', text}   — команда интерпретатора;
//     {}                       — форма неизвестна;
//   adapters — commandWrites(текст) → {mutates, targets}; commandReads(текст) →
//     {reads, targets}; ignored(путь).
//
// Пустой `op` значит «строки нет»: вызов, правящий ход САМОЙ сессии (план,
// вопрос, список работы, расписание пробуждения), ни чтением, ни записью мира не
// является, и запись про него была бы не фактом, а шумом.
//
// Поле `unsupported` рядом с операцией значит: операция установлена, а что-то
// СВЕРХ неё — нет, и это названо именем (решение 8). Пустой список целей без
// такого имени — утверждение «называть тут нечего», а не «назвать не смогли»:
// читателю эти два случая различать обязательно, иначе гвард чтения не отличит
// вызов, который ничего не читал, от вызова, чьё чтение мы не разобрали.
export function factOf(scope = {}, call = {}, adapters = {}) {
  if (scope.session === true) return { op: '' };
  if (scope.reads === true) {
    if (call.kind === 'read') {
      const named = Array.isArray(call.paths) ? call.paths : [];
      return { op: OPS.READ, targets: named.filter(Boolean).map(String) };
    }
    // Адаптер говорит: читать этому вызову нечего по его природе (список работы,
    // перечисление, поиск в сети). Пустой список тут — факт.
    if (call.kind === 'read-nothing') return { op: OPS.READ, targets: [] };
    // Формы нет: чтение было, а назвать прочитанное нечем. Это НЕ то же самое,
    // и молчаливый пустой список читался бы гвардом как «ничего не читал».
    return { op: OPS.READ, targets: [], unsupported: 'read-targets' };
  }
  // Запись в базу заметок: её адрес — не путь файла, и эфемерности у него нет.
  // Адреса нет — запись всё равно ЕСТЬ, и молчать про неё нельзя: пропав, она
  // унесла бы с собой ровно то изменение, ради сборки которого журнал и заведён.
  if (call.kind === 'note') {
    const ref = String(call.ref || '');
    return ref
      ? { op: OPS.WRITE, targets: [ref] }
      : { op: OPS.WRITE, targets: [], unsupported: 'note-write-target' };
  }
  const mutation = mutationOf(scope, call, adapters);
  if (mutation.status !== 'ok') return { op: OPS.UNKNOWN, unsupported: mutation.capability };
  if (mutation.mutates) {
    const fact = { op: OPS.WRITE, targets: durableTargets(call, adapters) };
    // Формы у вызова не было вовсе (сторонний сервер, подагент): «менял мир» тут
    // — консервативное умолчание гейта, а не установленный факт, и журнал обязан
    // сказать это вслух. Целей он при этом не даёт, так что сборка изменений
    // ничего лишнего не насчитает.
    if (!call.kind) fact.unsupported = 'call-shape';
    return fact;
  }
  // Не запись — но, может быть, ДОКАЗАННОЕ чтение. Про команду это знает адаптер
  // интерпретатора; синтаксиса общая часть не разбирает. Адаптера нет — вопрос
  // остался без ответа, и это имя, а не молчание.
  if (call.kind === 'command') {
    if (typeof adapters.commandReads !== 'function') {
      return { op: OPS.UNKNOWN, unsupported: 'read-targets' };
    }
    const answer = adapters.commandReads(String(call.text || '')) || {};
    if (answer.reads) return { op: OPS.READ, targets: answer.targets || [] };
    // Адаптер РАЗОБРАЛ команду и говорит: это не чтение. Тогда пустой `op`
    // означает «события мира не было» — факт. А вот «не доказано» им означать
    // нельзя: команда, про которую разбор ничего не понял, могла переписать
    // пол-репозитория, и молчание выдало бы неизвестность за спокойствие.
    if (answer.proven !== true) return { op: OPS.UNKNOWN, unsupported: 'command-effect' };
  }
  return { op: '' };
}

// Сигнальные строки журнала ПОСЛЕ отметки и текущий размер журнала. Отметка —
// байтовое смещение: журнал только дописывается, поэтому смещение и есть
// «досюда уже разбирали».
//
// Отметка БОЛЬШЕ файла означает, что журнал начался заново (другая сессия, файл
// подмели): читаем с начала. Иначе новые сигналы молча считались бы разобранными
// — то есть контур замолчал бы ровно там, где обязан говорить.
//
// Журнала ЕЩЁ НЕТ — это факт: сессия пока ничего не делала, сигналов не было.
// Журнал ЕСТЬ, но не читается (права, полный диск) — это НЕ «сигналов не было», а
// отсутствие ответа, и оно называется именем. Без этого различения молчаливый
// отказ чтения выглядел бы как спокойная сессия — то есть менял бы знак.
export function readSignals(file, from = 0) {
  const empty = { status: 'ok', records: [], size: 0, from: 0, end: 0 };
  if (!file) return empty;
  let size = 0;
  let start = 0;
  let text = '';
  try {
    size = fs.statSync(file).size;
    // Отметка больше файла — журнал начался заново; читаем с начала. Начало
    // возвращается ВЫЗЫВАЮЩЕМУ: он держит отметку и двигает её только вперёд, и
    // молчаливая подмена здесь оставила бы его с отметкой из прошлой жизни
    // журнала — то есть заклинила бы его навсегда на одних и тех же строках.
    start = Number.isFinite(from) && from > 0 && from <= size ? from : 0;
    const fd = fs.openSync(file, 'r');
    try {
      const buf = Buffer.alloc(size - start);
      if (buf.length) fs.readSync(fd, buf, 0, buf.length, start);
      text = buf.toString('utf8');
    } finally {
      fs.closeSync(fd);
    }
  } catch (error) {
    if (error && error.code === 'ENOENT') return empty;
    return { ...unsupported('journal-read'), records: [], size: 0, from: 0, end: 0 };
  }

  const records = [];
  eachJsonl(text, (entry) => {
    if (SIGNAL_OPS.includes(entry.op)) records.push(entry);
  });
  // Конец ПОСЛЕДНЕЙ ПОЛНОЙ строки, а не размер файла. Производитель дописывает
  // журнал на каждом вызове, и конец хода приходит сразу за одним из них: размер,
  // снятый посреди строки, отметил бы её разобранной, а разбор её молча пропустил
  // как битую — сигнал исчез бы навсегда.
  // Длина считается в БАЙТАХ, а не в символах: смещения журнала байтовые, и на
  // первом же не-ASCII тексте (а их тут большинство) символьная длина увела бы
  // горизонт назад, в середину уже разобранной строки.
  const cut = text.lastIndexOf('\n');
  const end = cut < 0 ? start : start + Buffer.byteLength(text.slice(0, cut + 1), 'utf8');
  return {
    status: 'ok', records, size, from: start, end,
  };
}
