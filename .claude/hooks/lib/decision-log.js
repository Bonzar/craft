// Журнал решений хуков одного события: КАНАЛ между хуками цепочки.
//
// Пишет тот, кто решает, и строка ложится ДО печати и до выхода из процесса:
// упавший следом хук своего решения не теряет, и видит его любой процесс, а не
// только тот, кого позвали следом. ЧИТАТЕЛЬ один — наблюдатель (хук метрик): он
// переносит новые строки в свой журнал на следующем событии. Диспетчер журнал не
// читает вовсе: обрыв цепочки — признак в памяти процесса (lib/decided.js), и от
// диска он зависеть не имеет права.
//
// Строка: {ts, sid, call_id, event, hook, outcome, reason_class}. Текста причины
// в журнале НЕТ — только класс: журнал переживает сессию, а причина отказа
// содержит куски работы Влада.
import fs from 'node:fs';
import path from 'node:path';
import { decisionLog } from './paths.js';
import { eachJsonl } from './jsonl.js';
import { sha256 } from './hash.js';
import { sweepOld } from './sweep.js';

// Путь журнала: сессия и КАТАЛОГ СОСТОЯНИЯ берутся из самого события — оба поля
// ядра. Своей копии формулы каталога здесь нет.
function logOf(event) {
  return decisionLog(event && event.session_id, event && event.state_dir);
}

// Журнал переживает сессию, а его никто не снимает за собой: процесс, дописавший
// последнюю строку, о конце сессии не знает. Файл, которого не касались дольше
// срока, принадлежит кончившейся сессии — читают из журнала только строки ТЕКУЩЕГО
// события, поэтому терять в нём нечего. Уборщик общий с метками уступки.
const JOURNAL_PREFIX = 'decisions.';
const SWEEP_STAMP = 'decisions.sweep';
const JOURNAL_TTL_MS = 60 * 60 * 1000;
const SWEEP_EVERY_MS = 10 * 60 * 1000;

// Сколько байт начала журнала читается ради отпечатка «тот ли это файл».
const HEAD_BYTES = 256;

// Одна запись на все три вида строк: собрать общую часть, дописать, назвать
// неудачу. Три копии этого тела уже разъезжались бы по составу полей.
function appendRecord(event, kind, extra) {
  const file = logOf(event);
  if (!file) return false;
  // Ключ строки — ПОЯВЛЕНИЕ события: его номер, имя и идентификатор вызова. По
  // нему наблюдатель сшивает решение с записью события, а сессия в ключе нужна
  // потому, что при пустом идентификаторе путь журнала общий
  // (`decisions.default.jsonl`) — без неё решение одной сессии читалось бы как
  // решение другой. Номер появления даёт обёртка: он свой у каждого прочтения
  // события (event-claude.js), и без него у событий без вызова (реплика, конец
  // хода) ключ был бы один на всю сессию.
  const record = {
    kind,
    ts: new Date().toISOString(),
    occurrence: (event && event.occurrence) || '',
    sid: (event && event.session_id) || '',
    call_id: (event && event.call_id) || '',
    event: (event && event.event) || '',
    ...extra,
  };
  try {
    fs.appendFileSync(file, `${JSON.stringify(record)}\n`);
    sweepOld(path.dirname(file), {
      prefix: JOURNAL_PREFIX, stamp: SWEEP_STAMP, ttlMs: JOURNAL_TTL_MS, everyMs: SWEEP_EVERY_MS,
    });
    return true;
  } catch {
    // Журнал не пополнился. Ход это не рвёт — решение уже напечатано, — но строка
    // потеряна, и вызывающему об этом говорится «нет», а не тишиной: сорвавшуюся
    // запись видно исходом, а не догадкой по пустоте.
    return false;
  }
}

export function appendDecision(event, {
  outcome, hook = '', reasonClass = '', h = '', tool = '',
}) {
  return appendRecord(event, 'decision', {
    hook,
    outcome,
    class: reasonClass,
    // Хеш вызова: по нему сводка узнаёт «тот же вызов, прошедший после отказа».
    // Без него отказ и последующий проход не сшить — у отказанного вызова записи
    // метрик нет вовсе, цепочка обрывается на решении.
    h,
    tool,
  });
}

// Признак, замеченный одним хуком цепочки для другого (сегодня — «в реплике есть
// инцидент»). Тот же канал, что и решение: пишет заметивший, читает наблюдатель.
export function appendFlag(event, flag) {
  return appendRecord(event, 'flag', { flag });
}

// Замеры времени хуков цепочки: одна строка на событие, пишет диспетчер перед
// последним хуком. Одна, а не по строке на хук: цепочка стоит в ходе, и лишние
// записи на диск в ней платит Влад ожиданием.
export function appendTimings(event, hooks) {
  return appendRecord(event, 'timing', { hooks });
}

// Перенос новых строк наблюдателю. Читает журнал ОТ СМЕЩЕНИЯ, которое читающий
// помнит между событиями, и отдаёт разобранные строки, новое смещение и отпечаток
// начала журнала.
//
// Почему переносом, а не чтением по месту. Решение по событию пишется ПОСЛЕ того,
// как наблюдатель записал само событие: он зовётся первым, иначе отказ обрывал бы
// цепочку до него. Значит решение этого события он видит на следующем — и тогда же
// кладёт его в СВОЙ журнал, который переживает сессию. Журнал решений живёт час
// после последней записи (см. уборку выше), и считать по нему сводку задним числом
// было бы счётом по тому, что вот-вот подметут.
//
// Почему не одно смещение. Уборщик СНОСИТ журнал, и сессия, вернувшаяся после
// перерыва, заводит новый — своей длины, которая запросто окажется больше
// запомненного смещения. По одному смещению такой журнал читался бы с середины, а
// строки начала пропадали бы молча. Поэтому рядом со смещением помнится ОТПЕЧАТОК
// НАЧАЛА журнала: не сошёлся — журнал другой, читаем сначала. Номер файла (inode)
// для этого не годится: система выдаёт его снова сразу после сноса, и новый журнал
// получает номер снесённого.
//
export function readSince(event, { offset = 0, head = '' } = {}) {
  const file = logOf(event);
  const empty = { records: [], offset: 0, head: '' };
  if (!file) return { ...empty, status: 'unsupported' };
  let size = 0;
  try {
    size = fs.statSync(file).size;
  } catch (error) {
    // Журнала НЕТ — законная пустота: пока никто не решал, строк и не должно быть.
    if (!error || error.code !== 'ENOENT') return { ...empty, offset, head, status: 'error' };
    return { ...empty, status: 'ok' };
  }
  let fd;
  try {
    fd = fs.openSync(file, 'r');
    const top = Buffer.alloc(Math.min(HEAD_BYTES, size));
    fs.readSync(fd, top, 0, top.length, 0);
    // Отпечаток берётся по ПЕРВОЙ СТРОКЕ, а не по первым байтам файла: строки
    // дописываются целиком, поэтому первая больше не меняется, а окно «первые N
    // байт» у короткого файла росло бы вместе с ним — и отпечаток менялся бы на
    // каждой записи, заставляя перечитывать журнал целиком.
    const stamp = sha256(top.toString('utf8').split('\n')[0]).slice(0, 12);
    const from = stamp === head && offset <= size ? offset : 0;
    if (from === size) return { records: [], offset: size, head: stamp, status: 'ok' };
    const buf = Buffer.alloc(size - from);
    fs.readSync(fd, buf, 0, buf.length, from);
    const records = [];
    eachJsonl(buf.toString('utf8'), (rec) => records.push(rec));
    return { records, offset: size, head: stamp, status: 'ok' };
  } catch {
    return { ...empty, offset, head, status: 'error' };
  } finally {
    if (fd !== undefined) fs.closeSync(fd);
  }
}
