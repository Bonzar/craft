// Вызов классификатора план-гейта — LLM-проверки, которую регулярка дать не
// может. Здесь только СЧЁТ и УЧЁТ: чем запускать классификатор и как передать ему
// материал, знает адаптер (classify-bash.js) — он приходит параметром с края.
//
// Таймаут, обрыв и нераспознанный ответ дают UNAVAILABLE: решение о судьбе правки
// принимает гейт, а не помощник. Адаптера нет вовсе — ответ UNSUPPORTED: это не
// «модель промолчала», а «возможности classify в этой сборке нет» (решение 8).
import { recordModelCall, verdictClass } from './metrics.js';

// Срок и число проходов приёма материала. Живут здесь, а не по месту, потому что
// их два и они обязаны быть согласованы: приём тратит бюджет на КАЖДОМ проходе, а
// хук одобрения убивает его снаружи одним числом. Разъехавшись, они давали
// молчаливую пропажу: приём успевал записать часть и погибал.
export const INGEST_BUDGET_SEC = 1500;
// Проход один: второй, «дозаводящий пропущенное», удваивал вызовы модели на
// каждой реплике и плодил переформулированные дубли вместо того, чтобы сходиться.
// Пропуск задачи разбором — повод для отдельного разрешения, а не для второго
// вызова.
export const INGEST_PASSES = 1;

// Потолок хода, за которым приём резать уже не нам: столько отмерено хуку в
// настройках, и на столько же протухает метка разбора, которую ждёт сверка.
// Дедлайн приёма обязан помещаться внутрь — иначе хук убьют раньше, чем он успеет
// записать след, и получится ровно та молчаливая пропажа, ради которой след и
// заводился.
const HOOK_CAP_SEC = 3600;

// Сколько ждать приём снаружи: все его проходы плюс запас на чтение реестра,
// запись и запуск процесса. Меньше — значит резать собственную работу; больше
// потолка хода — значит не резать вовсе, и тогда режет кто-то другой и молча.
export function ingestDeadlineMs() {
  const wanted = INGEST_BUDGET_SEC * INGEST_PASSES + 60;
  return Math.min(wanted, HOOK_CAP_SEC - 60) * 1000;
}

// classify(адаптер, bin, mode, args, материал) → строка вердикта.
//
// Каждый вызов — событие метрик: режим, длительность и класс ответа. Это
// единственное место, откуда хуки зовут модель, поэтому счёт вызовов живёт здесь,
// а не в хуке метрик, — приём реестра идёт в отдельном фоновом процессе, и хуку
// его не видно.
export function classify(adapter, bin, mode, args, description, { timeoutSec } = {}) {
  if (!adapter || typeof adapter.run !== 'function') return 'UNSUPPORTED';
  if (!adapter.available(bin)) return 'UNAVAILABLE';
  const started = Date.now();
  const verdict = adapter.run(bin, mode, args, description, { timeoutSec }) || 'UNAVAILABLE';
  // С аварийным выключателем классификатор отвечает сам и модель не зовёт — такой
  // вызов в счётчик вызовов модели не идёт. Исход `unavailable` остаётся общим для
  // настоящего неответа и прочих ранних выходов классификатора (нечитаемый
  // материал, нет реестра): снаружи они неразличимы.
  if (!adapter.offSwitchOn()) {
    recordModelCall({ mode, ms: Date.now() - started, outcome: verdictClass(verdict) });
  }
  return verdict;
}
