// Якорь сессии: у каждой сессии есть своя задача в базе — место, куда ложится
// «надо сделать», итог работы и ссылки на всё, что сессия создала. Правило живёт
// в базе, подстраницей роутера; здесь только его машинная часть.
//
// Правило НЕ разбирает ни команд, ни путей: что считать записью, уже сказал
// инструмент признаков записи, и это определение на весь контур одно. Раньше у
// якоря был свой отдельный гвард со своим определением — одна и та же команда у
// него была записью, а у гейта нет.
//
// Молчит там, где спрашивать некого: автономные рутины и замеры (CRAFT_AUTONOMOUS,
// CRAFT_EVAL), вложенный вызов подагента (CRAFT_NESTED_CALL) и пустой
// идентификатор сессии — у последнего файла состояния нет вовсе, и отказ запер бы
// сессию насмерть. Fail open во всех этих случаях сознателен: якорь страхует
// дисциплину, а не безопасность. Своих выходов гейт при этом не приобретает:
// молчит ПРАВИЛО, а сверка с реестром идёт дальше наравне со всеми.
import fs from 'node:fs';
import { sessionAnchor } from '../paths.js';

export const name = 'anchor';

// Заголовок якорного вопроса: директива старта диктует его дословно, приём тапа
// узнаёт по нему свой вопрос. Метка нашего контура, а не догадка по тексту.
export const ANCHOR_HEADER = 'Якорь сессии';

// Выбран ли якорь этой сессии. null означает «спрашивать негде»: идентификатора
// сессии нет, файла состояния не существует в принципе.
export function anchorChosen() {
  const state = sessionAnchor();
  if (!state) return null;
  try {
    return fs.existsSync(state) && fs.readFileSync(state, 'utf8').trim() !== '';
  } catch {
    return false;
  }
}

export function run(ctx) {
  if (process.env.CRAFT_AUTONOMOUS || process.env.CRAFT_EVAL || process.env.CRAFT_NESTED_CALL) {
    return { decision: 'next' };
  }
  const chosen = anchorChosen();
  if (chosen === null || chosen === true) return { decision: 'next' };

  return {
    decision: 'deny',
    reason: `Заблокировано якорем сессии: ${ctx.intent.why} без задачи-якоря. Спроси Влада кнопками, какая задача базы будет якорем этой сессии (вопрос с заголовком «${ANCHOR_HEADER}»: найденные по теме задачи и «завести новую»), и продолжай после ответа. Автономному прогону — CRAFT_AUTONOMOUS=1.`,
  };
}
