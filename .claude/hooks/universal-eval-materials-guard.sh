#!/usr/bin/env bash
# PreToolUse(Read|Grep|Glob) guard: в евал-прогоне закрывает материалы самого
# замера — кейсы, раннер с грейдером и сохранённые прогоны.
#
# ЗАЧЕМ. Кейсы лежат в том же репозитории, где работает измеряемый агент, и
# рядом с промптом в них стоят ОЖИДАЕМЫЕ подстроки ассертов. В замере 30.07.2026
# агент прочитал файл кейсов в 10 прогонах из 12 — то есть видел ответы к тесту,
# и ни один вердикт, включая зелёные, ничего не доказывал.
#
# Что закрыто: evals/cases, evals/lib, evals/runs, раннеры evals/run-*.sh и
# самотест. Что НАМЕРЕННО открыто: весь остальной репозиторий — правила, скиллы,
# хуки и код агент читать обязан, иначе исчезает измеряемое поведение. README
# евалов тоже открыт: он описывает контур, но ответов кейсов не содержит.
#
# Действует ТОЛЬКО при CRAFT_EVAL=1 — в обычной сессии агент работает с евалами
# как с обычным кодом. Fail open на всём неожиданном.
set -u

# Project-уровень уступает user-уровню (install.sh) — не гейтим дважды.
if [[ -n "${CLAUDE_PROJECT_DIR:-}" && "$0" == "$CLAUDE_PROJECT_DIR"/* \
      && -e "$HOME/.claude/hooks/$(basename "$0")" ]]; then
  exit 0
fi

[[ -n "${CRAFT_EVAL:-}" ]] || exit 0

input="$(cat)"
# Путь может прийти в любом из трёх полей: file_path (Read), path (Grep) или
# самим шаблоном (Glob) — проверяем все, иначе обход тривиален.
target="$(jq -r '[.tool_input.file_path // "", .tool_input.path // "",
                 .tool_input.pattern // ""] | join(" ")' <<<"$input" 2>/dev/null)" || exit 0
[[ -z "${target//[[:space:]]/}" ]] && exit 0

closed='evals/cases|evals/lib|evals/runs|evals/run-[a-z-]*\.sh|evals/selftest\.sh'
if grep -qE "$closed" <<<"$target"; then
  jq -n '{
    hookSpecificOutput: {
      hookEventName: "PreToolUse",
      permissionDecision: "deny",
      permissionDecisionReason: "Это материалы замера, в котором ты сейчас участвуешь: кейсы, раннер и сохранённые прогоны. В них лежат ожидаемые ответы, и чтение обесценивает измерение. Решай задачу по существу — правила, скиллы и остальной код читать можно."
    }
  }'
fi
exit 0
