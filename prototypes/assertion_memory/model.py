def persisted_model_error_code(error):
    """Recognize only the exact constant generated by the trusted worker."""
    if error == f"{ModelProviderUnavailable.__name__}: {ModelProviderUnavailable.message}":
        return ModelProviderUnavailable.code
    return None


_CODEX_UNAVAILABLE_CODES = frozenset({
    "authentication_error", "invalid_api_key", "unauthorized", "token_expired",
    "unsupported_country_region_territory", "unsupported_region",
    "server_overloaded", "service_unavailable", "connection_error", "connection_failed",
    "stream_disconnected", "response_stream_connection_error", "response_stream_disconnected",
    "response_stream_max_retries_exceeded", "http_connection_failed", "http_connection_error",
    "response_timeout", "bad_gateway", "gateway_timeout",
})
_CODEX_UNAVAILABLE_RE = re.compile(
    r"^(?:(?:error:\s*)?(?:not logged in\b|authentication required\b|"
    r"your refresh token (?:has expired|was already used)\b|"
    r"stream disconnected before completion\b|"
    r"unexpected status (?:401|502|503|504)\b|"
    r"(?:country, region, or territory not supported|unsupported country, region, or territory)\b|"
    r"(?:error sending request for url|failed to connect to|connection refused|network is unreachable)\b))",
    re.IGNORECASE,
)


def _codex_unavailable(stdout, stderr):
    # Trust only CLI error/failed event fields; never classify generation text,
    # record bodies, repair text, or generic validation/usage errors.
    for line in stdout.splitlines():
        try:
            event = json.loads(line)
        except (ValueError, TypeError):
            continue
        if not isinstance(event, dict) or event.get("type") not in ("error", "turn.failed"):
            continue
        error = event.get("error", event)
        if not isinstance(error, dict):
            continue
        for field in ("code", "type", "codex_error_info"):
            value = error.get(field)
            if isinstance(value, dict):
                names = list(value)
            else:
                names = [value] if isinstance(value, str) else []
            for name in names:
                normalized = re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
                if normalized in _CODEX_UNAVAILABLE_CODES:
                    return True
        if isinstance(error.get("message"), str) and _CODEX_UNAVAILABLE_RE.match(error["message"].strip()):
            return True
    return any(_CODEX_UNAVAILABLE_RE.match(line.strip()) for line in stderr.splitlines())


class ModelContextExceeded(ModelError):
    """The provider explicitly reported its actual context capacity, not a local quota."""


def _context_error(output):
    codes = {'context_length_exceeded','model_context_window_exceeded','context_window_exceeded',
             'ContextWindowExceeded'}
    for line in output.splitlines():
        try:event = json.loads(line)
        except (ValueError,TypeError):continue
        if not isinstance(event,dict) or event.get('type') not in ('error','turn.failed'):
            continue
        error = event.get('error',event)
        if isinstance(error,dict) and any(isinstance(error.get(key),str) and error[key] in codes
                                          for key in ('code','type','codex_error_info')):
            return True
    return False


def _codex_has_completed_turn(stdout):
    for line in stdout.splitlines():
        try:
            event = json.loads(line)
        except (ValueError, TypeError):
            continue
        if isinstance(event, dict) and event.get("type") == "turn.completed":
            return True
    return False


