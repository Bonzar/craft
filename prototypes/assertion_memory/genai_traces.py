"""Optional, payload-free OTLP/HTTP JSON spans for the private memory-query service.

The application's only destination is its lane's loopback trace collector. It
does not read cloud credentials or any generic OTEL endpoint/export settings.
"""
from contextvars import ContextVar
from dataclasses import dataclass, field
from http.client import HTTPConnection
import json
import os
from queue import Empty, Full, Queue
import re
from threading import Lock, Thread
from time import monotonic, monotonic_ns, time_ns
from uuid import uuid4

ENABLE = 'ASSERTION_MEMORY_MONIUM_TRACE_ENV'
_PORTS = {'test': 14318, 'prod': 24318}
_MODEL = re.compile(r'(?:gpt-[a-z0-9][a-z0-9.-]{0,75}|o[1-9][a-z0-9.-]{0,75}|codex-[a-z0-9][a-z0-9.-]{0,73})\Z')
_USAGE = {
    'input_tokens': 'gen_ai.usage.input_tokens',
    'output_tokens': 'gen_ai.usage.output_tokens',
    'cached_input_tokens': 'gen_ai.usage.cache_read.input_tokens',
    'reasoning_output_tokens': 'gen_ai.usage.reasoning.output_tokens',
}
_ERROR_STATUSES = ('failed', 'timeout', 'unavailable', 'interrupted')
_STAGE_STATUS = frozenset((*_ERROR_STATUSES, 'ok', 'partial', 'miss', 'ready', 'queued', 'reused'))
_TRACE_ID = re.compile(r'[0-9a-f]{32}\Z')
_span = ContextVar('memory_query_otlp_span', default=None)
_exporter = None
_init = Lock()


def _attribute(key, value):
    if type(value) is int:
        return {'key': key, 'value': {'intValue': str(value)}}
    return {'key': key, 'value': {'stringValue': value}}


class _Exporter:
    QUEUE_SIZE = 512
    BATCH_SIZE = 64

    def __init__(self, lane):
        self.lane = lane
        self._queue = Queue(maxsize=self.QUEUE_SIZE)
        self._thread = Thread(target=self._background, name='memory-otlp-export', daemon=True)
        self._thread.start()

    def put(self, record):
        try:
            self._queue.put_nowait(record)
        except Full:
            # This lane must never block a query or build an unbounded backlog.
            pass

    def _background(self):
        while True:
            batch = [self._queue.get()]
            wait_until = monotonic() + .075
            while len(batch) < self.BATCH_SIZE:
                try:
                    batch.append(self._queue.get(timeout=max(0, wait_until - monotonic())))
                except Empty:
                    break
            try:
                self._send(batch)
            except Exception:
                # Drop this batch on collector outage; query latency and the
                # independent journal trace do not depend on OTLP delivery.
                pass

    def _send(self, batch):
        resource = {'attributes': [_attribute('service.name', 'assertion-memory-' + self.lane),
                                    _attribute('deployment.environment.name', self.lane)]}
        data = {'resourceSpans': [{'resource': resource,
                'scopeSpans': [{'scope': {'name': 'assertion_memory.query_timing'}, 'spans': batch}]}]}
        wire = json.dumps(data, separators=(',', ':'), ensure_ascii=True).encode('ascii')
        conn = HTTPConnection('127.0.0.1', _PORTS[self.lane], timeout=1)
        try:
            conn.request('POST', '/v1/traces', wire, {'Content-Type': 'application/json'})
            with conn.getresponse() as response:
                # No redirects, proxy, retry or unbounded collector response.
                # Closing this one-shot connection frees any unread bytes.
                response.read(4096)
        finally:
            conn.close()


def configure(lane):
    """Called at hosted Base startup, never from the model/query path."""
    global _exporter
    if lane not in _PORTS or os.environ.get(ENABLE) != lane:
        return
    with _init:
        if _exporter is None:
            try:
                _exporter = _Exporter(lane)
            except Exception:
                pass


@dataclass
class _Span:
    stage: str
    trace_id: str
    span_id: str
    began_ns: int
    clock_ns: int
    parent_id: str | None
    exporter: _Exporter
    attributes: dict = field(default_factory=dict)
    semantic_outcome: str | None = None
    genai: bool = False


def begin(stage, ids, *, queue_wait_ms=None, backdate_ms=0):
    exporter = _exporter
    if exporter is None:
        return None
    try:
        trace_id = ids['trace_id'].replace('-', '')
        if not _TRACE_ID.fullmatch(trace_id) or trace_id == '0'*32:
            return None
        parent = _span.get()
        same_trace = parent is not None and parent.trace_id == trace_id
        backdate_ns = min(backdate_ms * 1_000_000, time_ns())
        span = _Span(stage, trace_id, uuid4().hex[:16], time_ns() - backdate_ns, monotonic_ns() - backdate_ns,
                     parent.span_id if same_trace else None, exporter)
        if type(queue_wait_ms) is int and 0 <= queue_wait_ms < 2**53:
            span.attributes['memory.queue_wait_ms'] = queue_wait_ms
        # Opaque IDs are generated by the trusted pipeline, not request attributes.
        for key in ('run_id', 'call_id', 'model_phase'):
            if key in ids:
                span.attributes['memory.' + key] = ids[key]
        return span, _span.set(span)
    except Exception:
        return None


def measured(stage, ids, status, duration_ms, *, retry_count=None):
    """Export an already completed local measurement on the same trace."""
    if status not in _STAGE_STATUS or type(duration_ms) is not int or not 0 <= duration_ms < 2**53:
        return
    handle = begin(stage, ids, backdate_ms=duration_ms)
    if handle and type(retry_count) is int and 0 < retry_count < 2**31:
        handle[0].attributes['memory.retry_count'] = retry_count
    end(handle, status)


def outcome(status):
    span = _span.get()
    if span is not None and span.stage == 'query_total' and status in _STAGE_STATUS:
        span.semantic_outcome = status


def mark_codex(requested_model):
    span = _span.get()
    if span is None or span.stage != 'provider_attempt':
        return
    span.genai = True
    span.attributes.update({'gen_ai.operation.name': 'chat', 'gen_ai.provider.name': 'openai',
                            'gen_ai.system': 'openai'})
    if isinstance(requested_model, str) and _MODEL.fullmatch(requested_model):
        span.attributes['gen_ai.request.model'] = requested_model


def observe_usage(usage):
    span = _span.get()
    if span is None or not span.genai:
        return
    model = usage.get('actual_model')
    if isinstance(model, str) and _MODEL.fullmatch(model):
        span.attributes['gen_ai.response.model'] = model
    tokens = usage.get('tokens')
    if isinstance(tokens, dict):
        for name, attribute in _USAGE.items():
            count = tokens.get(name)
            if type(count) is int and 0 <= count <= 2**63-1:
                span.attributes[attribute] = count


def provider_signal(status, count):
    span = _span.get()
    if span is None or not span.genai:
        return
    if status == 'connection_signal':
        span.attributes['memory.provider_connection_signal'] = 1
    elif status == 'retry_signal' and type(count) is int and 0 < count < 2**31:
        span.attributes['memory.provider_retry_signals'] = count


def end(handle, status):
    if handle is None:
        return
    span, token = handle
    try:
        _span.reset(token)
        if span.semantic_outcome is not None and status == 'ok':
            status = span.semantic_outcome
        attributes = {**span.attributes, 'memory.stage': span.stage, 'memory.outcome': status}
        elapsed = max(0, monotonic_ns() - span.clock_ns)
        span.exporter.put({
            'traceId': span.trace_id, 'spanId': span.span_id,
            **({'parentSpanId': span.parent_id} if span.parent_id is not None else {}),
            'name': 'openai.chat' if span.genai else 'memory_query.' + span.stage,
            'kind': 3 if span.genai else 1,
            'startTimeUnixNano': str(span.began_ns), 'endTimeUnixNano': str(span.began_ns + elapsed),
            'status': {'code': 2 if status in _ERROR_STATUSES else 1},
            'attributes': [_attribute(key, value) for key, value in attributes.items()],
        })
    except Exception:
        pass
