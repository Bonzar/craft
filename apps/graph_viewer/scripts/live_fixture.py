"""Publish or remove a named live probe in a MARKED synthetic fixture only.

No server is launched. These intentional fixture writes are separate from the
viewer-read-only audit and must be reported as test stimuli. Cleanup restores
semantic contents but advances source revision so live consumers can reset.
"""
from __future__ import annotations
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import sqlite3
import time
import uuid


def connect(manifest):
    database = Path(manifest['database']).resolve()
    if manifest.get('synthetic') is not True or manifest.get('writable_live_probes') is not True or database.name != 'source.sqlite3' or not (database.parent/'.viewer-qa-owned').is_file():
        raise ValueError('Refusing any source that is not an explicitly writable marked synthetic fixture')
    return sqlite3.connect(database)


def publish(manifest, *, supersede=False):
    key='qa-live-'+str(uuid.uuid4())
    edge=key+'-edge'
    stamp=datetime.now(timezone.utc).isoformat(timespec='microseconds')
    metadata={'fixture':'graph-viewer-qa-v1','probe':key}
    # Preserve source kind semantics: the target long assertion is an assertion,
    # not a proposal/decision. No text content is generated by a model.
    with connect(manifest) as db:
        db.execute('PRAGMA foreign_keys=ON')
        db.execute('INSERT INTO memory_assertions VALUES(?,?,?,?,?,?,?,?,?)', (key,'LIVE СИНТЕТИЧЕСКОЕ УТОЧНЕНИЕ '+key,'synthetic-vlad','synthetic-fixture','qa-session','2026-01-01T00:00:00.000000+00:00',stamp,'viewer-qa-synthetic',json.dumps(metadata)))
        db.execute('INSERT INTO memory_edges VALUES(?,?,?,?,?,?)', (edge,key,manifest['first_id'],'supersedes' if supersede else 'supports',stamp,'{}'))
    return {'synthetic':True,'id':key,'edge_id':edge,'source_ready_epoch_ms':time.time_ns()/1_000_000,'source_ready_monotonic_ns':time.monotonic_ns(),'recorded_at':stamp,'supersede':supersede}


def cleanup(manifest, probe):
    if probe.get('synthetic') is not True or not probe['id'].startswith('qa-live-') or probe['edge_id'] != probe['id']+'-edge':
        raise ValueError('Invalid synthetic probe identity')
    with connect(manifest) as db:
        db.execute('PRAGMA foreign_keys=ON')
        node=db.execute('SELECT metadata FROM memory_assertions WHERE assertion_id=?',(probe['id'],)).fetchone()
        if node is not None and json.loads(node[0]).get('probe') != probe['id']:
            raise ValueError('Probe ownership mismatch')
        db.execute('DELETE FROM memory_edges WHERE edge_id=? AND from_id=?',(probe['edge_id'],probe['id']))
        # The source fixture FTS is external-content; remove its index entry before
        # deleting the row, preserving parity with append-only source semantics.
        row=db.execute('SELECT rowid,text FROM memory_assertions WHERE assertion_id=?',(probe['id'],)).fetchone()
        if row:
            db.execute("INSERT INTO memory_fts(memory_fts,rowid,text) VALUES('delete',?,?)",row)
        db.execute('DELETE FROM memory_assertions WHERE assertion_id=?',(probe['id'],))
        db.execute('UPDATE memory_state SET version=version+1 WHERE singleton=1')
    return {'restored_semantic_objects':True,'source_revision_advanced':True,'synthetic':True}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fixture-manifest',type=Path,required=True)
    parser.add_argument('--action',choices=['append','supersede','cleanup'],required=True)
    parser.add_argument('--probe-file',type=Path,required=True)
    args=parser.parse_args()
    manifest=json.loads(args.fixture_manifest.read_text())
    if args.action=='cleanup':
        result=cleanup(manifest,json.loads(args.probe_file.read_text()))
    else:
        if args.probe_file.exists():
            parser.error('Refusing to overwrite an existing probe evidence file')
        result=publish(manifest,supersede=args.action=='supersede')
        args.probe_file.write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps(result))


if __name__=='__main__':
    main()
