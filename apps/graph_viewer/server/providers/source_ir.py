"""Viewer-owned compatibility IR, never an assertion-memory engine database.

Legacy memory_* names are a documented SQL compatibility interface to the existing
projection, not a claim that the source was generated by the memory engine.
"""
import errno
import hashlib
import json
import os
import shutil
import sqlite3
import tempfile
from pathlib import Path
from ..common import timestamp

SCHEMA = '''
CREATE TABLE viewer_source_info(schema_version INTEGER,provider_id TEXT,input_sha256 TEXT,source_revision TEXT,supplied_source_revision TEXT,adapter_format TEXT,kind_policy TEXT);
CREATE TABLE memory_state(singleton INTEGER PRIMARY KEY,version INTEGER);
CREATE TABLE memory_assertions(assertion_id TEXT PRIMARY KEY,text TEXT,actor TEXT,source TEXT,episode TEXT,valid_at TEXT,recorded_at TEXT,scope TEXT,metadata TEXT);
CREATE TABLE memory_edges(edge_id TEXT PRIMARY KEY,from_id TEXT,to_id TEXT,kind TEXT,recorded_at TEXT,metadata TEXT);
CREATE TABLE memory_raw_events(id TEXT PRIMARY KEY,session_id TEXT,turn_id TEXT,prompt TEXT,actor TEXT,source TEXT,scope TEXT,recorded_at TEXT,metadata TEXT);
CREATE TABLE memory_event_positions(event_id TEXT PRIMARY KEY,position INTEGER);
CREATE TABLE memory_views(id TEXT PRIMARY KEY,definition TEXT,current_id INTEGER,checked_version INTEGER,error TEXT,current_check_id INTEGER);
CREATE TABLE memory_view_versions(id INTEGER PRIMARY KEY,view_id TEXT,snapshot TEXT,created_at TEXT);
CREATE TABLE memory_historical_checks(view_id TEXT,version_id INTEGER,valid_cutoff TEXT,recorded_cutoff TEXT,source_version INTEGER);
CREATE TABLE viewer_topic_links(id TEXT PRIMARY KEY,parent_id TEXT,child_id TEXT,relation TEXT,recorded_at TEXT,provenance TEXT);
'''


def encoded(value):
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'), allow_nan=False)


def populate(connection, doc, fingerprint):
    connection.executescript(SCHEMA)
    connection.execute('INSERT INTO viewer_source_info VALUES(?,?,?,?,?,?,?)',
                       (1, doc['provider_id'], fingerprint, 'sha256:' + fingerprint,
                        doc['source_revision'], doc['schema'], 'source_only'))
    connection.execute('INSERT INTO memory_state VALUES(1,1)')
    provenance = {'provider_id': doc['provider_id'], 'source_revision': doc['source_revision']}
    for node in doc['nodes']:
        meta = {'kind': node.get('kind'), 'temporal_precision': node.get('valid_precision', 'unknown'),
                'source_provenance': dict(provenance, record_id=node['id']),
                'context_truncated': node.get('context_truncated'),
                'context_episode_ids': node.get('context_episode_ids', []),
                'evidence_refs': [dict(event_id=r['episode_id'], start=r['start'], end=r['end'])
                                  for r in node.get('evidence_refs', [])]}
        if doc['schema'] == 'canonical-thought-graph/v1':
            meta['canonical_thought'] = {key: node.get(key) for key in (
                'entity_type', 'thought_ref', 'thought', 'questions', 'origin', 'bases',
                'is_current', 'session_ids', 'session_membership', 'label', 'full_title')}
        if node.get('episode_id') is not None:
            meta['event_id'] = node['episode_id']
        for key in ['source_recorded_at', 'source_available_at']:
            if node.get(key) is not None:
                meta[key] = node[key]
        if node.get('interpreted_at') is not None:
            # Only an explicit source timestamp; never model_verified or an inferred kind.
            meta['interpretation'] = {'interpreted_at': node['interpreted_at']}
        if 'published_status' in node:
            meta['viewer_status'] = node['published_status']
        connection.execute('INSERT INTO memory_assertions VALUES(?,?,?,?,?,?,?,?,?)',
                           (node['id'], node['text'], node.get('actor'), node.get('source'),
                            node.get('episode_id'), node.get('valid_at'), node['recorded_at'],
                            node.get('scope'), encoded(meta)))
    for edge in doc['edges']:
        meta = {key: edge[key] for key in ['source_quote', 'target_quote', 'condition', 'basis', 'effective_at'] if key in edge}
        if doc['schema'] == 'canonical-thought-graph/v1':
            meta.update({key: edge.get(key) for key in ('relation_type', 'source_ref', 'target_ref',
                'source_span', 'target_span', 'provenance')})
        meta['source_provenance'] = dict(provenance, record_id=edge['id'])
        connection.execute('INSERT INTO memory_edges VALUES(?,?,?,?,?,?)',
                           (edge['id'], edge['from_id'], edge['to_id'], edge['kind'], edge['recorded_at'], encoded(meta)))
    for episode in doc['episodes']:
        meta = {'context_truncated': episode.get('context_truncated'),
                'viewer_context_episode_ids': episode.get('context_episode_ids', []),
                'source_provenance': dict(provenance, record_id=episode['id'])}
        if episode.get('source_available_at') is not None:
            meta['source_available_at'] = episode['source_available_at']
        connection.execute('INSERT INTO memory_raw_events VALUES(?,?,?,?,?,?,?,?,?)',
                           (episode['id'], episode.get('session_id'), None, episode['text'],
                            episode.get('actor'), episode.get('source'), episode.get('scope'),
                            episode['recorded_at'], encoded(meta)))
        if episode.get('position') is not None:
            connection.execute('INSERT INTO memory_event_positions VALUES(?,?)', (episode['id'], episode['position']))
    version_key = 0
    for overview in doc['overviews']:
        definition = {'id': overview['id'], 'title': overview['title'], 'scopes': overview.get('scopes', []),
                      'source_provenance': dict(provenance, record_id=overview['id'])}
        if overview.get('question') is not None:
            definition['query'] = overview['question']
        current = None
        for version in sorted(overview['versions'], key=lambda v: timestamp(v['published_at'])):
            version_key += 1
            if version['version_id'] == overview['current_version_id']:
                current = version_key
            snapshot = {'created_at': version['published_at'], 'source_version_id': version['version_id'],
                        'evidence': [{'id': id} for id in version['member_ids']]}
            if isinstance(version.get('summary'), str):
                snapshot['summary'] = version['summary']
            connection.execute('INSERT INTO memory_view_versions VALUES(?,?,?,?)',
                               (version_key, overview['id'], encoded(snapshot), version['published_at']))
            if version.get('valid_cutoff') is not None:
                connection.execute('INSERT INTO memory_historical_checks VALUES(?,?,?,?,?)',
                                   (overview['id'], version_key, timestamp(version['valid_cutoff']),
                                    timestamp(version['recorded_cutoff']) if version.get('recorded_cutoff') else '', 1))
        connection.execute('INSERT INTO memory_views VALUES(?,?,?,?,?,?)',
                           (overview['id'], encoded(definition), current, 1, None, None))
    for link in doc.get('topic_links', []):
        connection.execute('INSERT INTO viewer_topic_links VALUES(?,?,?,?,?,?)',
                           (link['id'], link['parent_id'], link['child_id'], link['relation'],
                            link['recorded_at'], encoded(link['provenance'])))
    connection.commit()


def materialize(doc, fingerprint, state_dir, *, epoch=None):
    """Atomically publish a private, complete generation after full validation."""
    state = Path(state_dir).resolve()
    provider_hash = hashlib.sha256(doc['provider_id'].encode('utf-8')).hexdigest()
    provider = state / 'source-ir' / provider_hash
    directories=[state,state/'source-ir',provider]
    if epoch is not None:
        import re
        if not re.fullmatch(r'[a-f0-9]{64}',epoch):
            raise ValueError('Invalid source IR epoch')
        directories.extend([provider/'database-epochs',provider/'database-epochs'/epoch])
        provider=directories[-1]
    for directory in directories:
        directory.mkdir(mode=0o700, parents=True, exist_ok=True)
        if directory.is_symlink() or not directory.is_dir():
            raise ValueError('Unsafe private source IR directory')
        directory.chmod(0o700)
    target = provider / fingerprint
    temporary = Path(tempfile.mkdtemp(prefix='.building-', dir=provider))
    try:
        path = temporary / 'source.sqlite3'
        with sqlite3.connect(path) as connection:
            populate(connection, doc, fingerprint)
        path.chmod(0o600)
        try:
            os.rename(temporary, target)
        except OSError as error:
            if error.errno not in {errno.EEXIST, errno.ENOTEMPTY}:
                raise
            # Identical bytes in one namespace have an identical immutable IR.
            # Never replace a generation already opened by a reader.
        return target / 'source.sqlite3'
    finally:
        if temporary.exists():
            shutil.rmtree(temporary)
