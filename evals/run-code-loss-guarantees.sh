#!/usr/bin/env bash
# Евалы пяти правил про молчаливую потерю данных и про то, чем держится
# гарантия. Все пять живут в ядре «⚙️ Правила кода», все пять выросли из одного
# захода: инструмент, читавший чужие расписания, терял позиции так, что снаружи
# это выглядело как «столько на источнике и было».
#
# ЗАДАЧИ НАБОРА (поле task):
#   count-from-source      — счёт начинается от ответа источника, а не от уже
#                            разобранных данных: каждая единица ответа обязана
#                            быть объяснена.
#   parse-loses-silently   — резка повторяющихся блоков выражением с закрывающим
#                            маркером теряет каждый второй, а сопоставление с
#                            частью значения выдаёт префикс за целое.
#   guarantee-not-memory   — обязательная проверка ставится на общий вход и
#                            держится перебором реестра, а не памятью автора.
#   signal-reaches-status  — заведённый признак неполноты обязан менять исход:
#                            поле с вечным нулём выглядит как успех.
#   snapshot-not-source    — сохранённый ответ это снимок одного случая; зелёные
#                            тесты на фикстурах не означают, что разбор работает.
#
# ЧТО ИМЕННО МЕРИТСЯ. Промптовый слой: держатся ли правила сами. Машинной
# подпорки у них нет — судить прозу хуком нечем, поэтому этот прогон и есть
# приёмка уроков.
#
# Улика доставки — строка инжекта ядра «Правил кода». До того как хук стал
# отдавать ядро файлом, её не было вовсе, и такой прогон давал ERROR, а не
# ложный зелёный: улика доказывает подготовку правила для сессии, не факт его
# прочтения моделью.
#
# Уровней два, нейтральный и встречный: так же сделаны соседние наборы.
#
# ИМЕНА КЕЙСОВ различаются ЛАТИНСКОЙ частью. eval__slug вырезает кириллицу и
# режет до 40 символов — два кейса с одинаковой латинской частью дали бы один
# слаг, затёрли бы результаты друг друга, и набор упал бы «неполным замером».
#
# Usage: run-code-loss-guarantees.sh [model ...]     (default: claude-sonnet-5)
#        EVAL_RUNS=3 run-code-loss-guarantees.sh …   — N прогонов каждого кейса
#
# Дисциплина прогонов и порог устойчивости — evals/README.md.
set -u
cd "$(dirname "$0")/.." || exit 1
source evals/lib/runner.sh

eval_run evals/cases/behavioral/code-loss-guarantees.jsonl "$@"
