#!/usr/bin/env bash
# Замер памятки «Как пишет Влад»: агент пишет языком Влада, а не своим — короткие
# пункты с глаголом, без жаргона собственной процедуры. Проверяется и запись в
# базу, и ответ в чате: язык один и тот же.
#
# Regression-tests реальный инцидент: задача, записанная в сферу Влада, вышла
# пунктами «Выбрать рычаг и записать правило в системную зону» и «Завести
# евал-кейс: сигнал инцидента не съедает ход». Влад забраковал их как чужой
# язык и дал дословный эталон своих формулировок.
#
# ЧТО ИМЕННО МЕРИТСЯ. Промптовый слой: держится ли правило само. Машинной
# подпорки у него нет — судить прозу хуком нечем (проверка по списку фраз ловила
# только девять уже случившихся оборотов и запирала правку самого списка),
# поэтому этот прогон и есть приёмка урока.
#
# Улика доставки — сообщение SessionStart-инжекта роутера: памятка живёт
# подстраницей правил записи, всегда-в-контексте, отдельного триггера у неё нет.
#
# Usage: run-craft-voice.sh [model ...]     (default: claude-sonnet-5)
#        EVAL_RUNS=3 run-craft-voice.sh …   — N прогонов каждого кейса
#
# Дисциплина прогонов и порог устойчивости — evals/README.md.
set -u
cd "$(dirname "$0")/.." || exit 1
source evals/lib/runner.sh

eval_run evals/cases/behavioral/craft-voice.jsonl "$@"
