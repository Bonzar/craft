#!/usr/bin/env bash
# Евал закрытия разбора инцидента: агент, ведущий разбор, обязан НАЗВАТЬ ступень
# рычага и решить про евал-кейс (завести или письменно отказаться) — не
# ограничиваться правкой текста правила.
#
# Regression-tests реальный инцидент: два разбора подряд закрыты самой слабой
# ступенью (усиление формулировки), евал не заведён, приёмка была «текст
# записан». Урок живёт в скилле «Разбор инцидента» — этот прогон сторожит
# поведение, а не пересказывает правило.
#
# ЧТО ИМЕННО МЕРИТСЯ. Промптовый слой: держится ли правило само, без машинной
# подпорки. Машинная ступень для него уже стоит — Stop-гейт закрытия разбора
# (universal-stop-incident-closure.sh); в евал-прогоне он выключен признаком
# CRAFT_EVAL, иначе мерился бы хук, а не правило.
#
# Прогон идёт из репо: правила приходят проектными SessionStart-инжектами.
# Craft при этом кейсы объявляют недоступным — проверяется рассуждение, не запись.
#
# Usage: run-incident-closure.sh [model ...]        (default: claude-sonnet-5)
#        EVAL_RUNS=3 run-incident-closure.sh …      — N прогонов каждого кейса
#
# Дисциплина прогонов и порог устойчивости — evals/README.md.
# Модель: дефолт — рабочий sonnet-5. Флапает — добавляй матрицу вторым
# аргументом (`… claude-sonnet-5 claude-opus-5`); однажды применённая к набору
# матрица используется и в дальнейших его прогонах, иначе сравнение с прошлым
# результатом теряет смысл.
set -u
cd "$(dirname "$0")/.." || exit 1
source evals/lib/runner.sh

eval_run evals/cases/behavioral/incident-closure.jsonl "$@"
