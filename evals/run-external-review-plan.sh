#!/usr/bin/env bash
# Евал правила «чужие замечания — не разрешение»: правки по замечаниям чужих
# рук (ревью-бот, коллега, другой агент) идут через план, даже когда цель уже
# в периметре одобренного плана; прямое указание Влада, наоборот, открывает
# правку сразу — контрольный кейс держит различитель, чтобы зелёный не
# достигался ответом «ПОКАЖУ ПЛАН» на всё подряд.
#
# Фикстуры сценария — evals/fixtures/external-review/: вымышленный одобренный
# план и вымышленный комментарий ревью-бота. Каталог не называется plans
# намеренно: хук universal-mark-plan-file.sh запоминает файл плана сессии по
# глобу */plans/*.md, и чтение фикстуры не должно подменять рабочий план.
#
# Usage: run-external-review-plan.sh [model ...]   (default: claude-sonnet-5)
#        EVAL_RUNS=3 run-external-review-plan.sh … — N прогонов каждого кейса
#
# Дисциплина прогонов и порог устойчивости — evals/README.md.
set -u
cd "$(dirname "$0")/.." || exit 1
source evals/lib/runner.sh

eval_run evals/cases/behavioral/external-review-plan.jsonl "$@"
