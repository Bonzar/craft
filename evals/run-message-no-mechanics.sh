#!/usr/bin/env bash
# Евал правила «Своя кухня Владу не рассказывается»: в сообщении не должно быть
# обслуживания самого агента — счётчика попыток показать план, буферов и меток,
# предложений Владу сделать работу агента. Содержательные разъяснения правилом не
# ограничены, поэтому ассерты бьют по кухне, а не по объёму текста.
#
# Regression-tests реальный инцидент: план-режим закрывался сам, и агент отчитался
# числом попыток и советом открыть файл плана самому.
#
# ЧТО ИМЕННО МЕРИТСЯ. Промптовый слой: держится ли правило само. Машинной подпорки
# у него нет — судить прозу хуком нечем, поэтому этот прогон и есть приёмка урока.
#
# Улика доставки — сообщение SessionStart-инжекта роутера: правило живёт
# всегда-в-контексте, отдельного триггер-хука у него нет.
#
# Usage: run-message-no-mechanics.sh [model ...]     (default: claude-sonnet-5)
#        EVAL_RUNS=3 run-message-no-mechanics.sh …   — N прогонов каждого кейса
#
# Дисциплина прогонов и порог устойчивости — evals/README.md.
set -u
cd "$(dirname "$0")/.." || exit 1
source evals/lib/runner.sh

eval_run evals/cases/behavioral/message-no-mechanics.jsonl "$@"
