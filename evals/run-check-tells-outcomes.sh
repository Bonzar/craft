#!/usr/bin/env bash
# Евал правила «Признак проверки обязан различать исходы»: проверка, у которой успех и
# отказ выглядят одинаково, проверкой не является. Агент обязан это назвать и предложить
# признак, который одно от другого отличает, а не отчитаться о пройденной проверке.
#
# Regression-tests реальный инцидент: агент выдал человеку разовую ссылку пульта капчи и
# отчитался, что она «отвечает 200». Кодом 200 отвечали и живая страница, и погасшая, и
# ключ, неизвестный пульту. Человек открыл ссылку и увидел «Проверка пройдена» на ссылке,
# которая просто не пережила перезапуск службы. Тем же корнем росли ещё два случая:
# проверка канала кодом 200 от сайта и «успех = процесс запустился» вместо смены адреса.
#
# ЧТО ИМЕННО МЕРИТСЯ. Промптовый слой: держится ли правило само. Машинной подпорки у него
# нет — судить прозу хуком нечем, поэтому этот прогон и есть приёмка урока.
#
# Улика доставки — сообщение SessionStart-инжекта роутера: правило живёт в его подстранице
# «Принципы работы», всегда-в-контексте.
#
# Уровней два, нейтральный и встречный: поддерживающий не заводим — так же сделаны пять из
# шести соседних наборов, и решение оставить два принято явно.
#
# КРАСНАЯ ФАЗА БЫЛА. До записи правила оба кейса падали, после записи — 6/6 на трёх
# прогонах каждого. Первые две редакции кейсов проходили и БЕЗ правила: сценарий с кодом
# 200 уже покрыт правилом в CLAUDE.md, а условие с прямой подсказкой ответ выдавало само.
#
# Ассерты калиброваны на живых ответах — той самой опасностью, о которой предупреждает
# evals/README.md: словарь отказа набирался по тому, как модель формулирует, а не заранее.
# Поэтому смысловая нагрузка лежит на ВТОРОЙ группе: она требует назвать различающий
# признак (кейс, который заведомо падал бы), а не просто отказаться.
#
# Usage: run-check-tells-outcomes.sh [model ...]     (default: claude-sonnet-5)
#        EVAL_RUNS=3 run-check-tells-outcomes.sh …   — N прогонов каждого кейса
#
# Дисциплина прогонов и порог устойчивости — evals/README.md.
set -u
cd "$(dirname "$0")/.." || exit 1
source evals/lib/runner.sh

eval_run evals/cases/behavioral/check-tells-outcomes.jsonl "$@"
