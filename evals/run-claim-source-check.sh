#!/usr/bin/env bash
# Евал правила «Факт против догадки»: вывод из косвенного источника не подаётся как факт.
# Обосновывая правку утверждением об устройстве репозитория или о поведении внешней
# системы, агент обязан сослаться на первоисточник — сам установщик, сам скрипт, сам
# поиск, — а не на соседний документ, который про это лишь упоминает.
#
# Regression-tests реальные инциденты одной сессии, три штуки подряд:
#   1. «S7 не летает из Москвы» — по странице «Куда мы летаем», где перечислены только
#      прямые рейсы; на деле рейс с пересадкой продаётся, Влад опроверг скриншотом.
#   2. «файл без префикса не читается ни как локальный, ни как универсальный» — по README,
#      без сверки с install.sh, который симлинкает и беспрефиксный _load-env.sh.
#   3. «установщик симлинкает только universal-*» — там же три шаблона, а не один.
# Первые два поймал критик планов, третий — он же следующим заходом; правило было записано
# и не удержало, поэтому рычаг поднят на ступень машинной проверки.
#
# ЧТО ИМЕННО МЕРИТСЯ. Промптовый слой: держится ли правило само. Машинной подпорки у него
# нет — universal-fact-gate.sh покрывает только деструктивные операции (rm -rf, git, arc,
# blocks delete/move), а ошибка возникает при обычной правке. Судить прозу хуком нечем,
# поэтому этот прогон и есть приёмка урока.
#
# Улика доставки — сообщение SessionStart-инжекта роутера: правило живёт в системной зоне
# памяти, всегда-в-контексте, отдельного триггер-хука у него нет.
#
# Usage: run-claim-source-check.sh [model ...]     (default: claude-sonnet-5)
#        EVAL_RUNS=3 run-claim-source-check.sh …   — N прогонов каждого кейса
#
# Дисциплина прогонов и порог устойчивости — evals/README.md.
set -u
cd "$(dirname "$0")/.." || exit 1
source evals/lib/runner.sh

eval_run evals/cases/behavioral/claim-source-check.jsonl "$@"
