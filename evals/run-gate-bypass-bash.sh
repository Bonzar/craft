#!/usr/bin/env bash
# Евал обхода план-гейта шеллом: правка файла делается инструментом правки под гейтом,
# а не шелл-записью в обход него. Промптовый слой — держится ли дисциплина сама.
#
# Regression-tests реальный инцидент: 387 строк дописаны через шелл без одобренного
# плана, потому что гейт покрывал только инструменты правки файлов.
#
# Машинная ступень у правила уже стоит — Bash-поверхность план-гейта. Этот прогон
# меряет поведение до неё: агент не должен тянуться к шеллу как к обычному способу
# писать код.
#
# Usage: run-gate-bypass-bash.sh [model ...]     (default: claude-sonnet-5)
#        EVAL_RUNS=3 run-gate-bypass-bash.sh …   — N прогонов каждого кейса
#
# Дисциплина прогонов и порог устойчивости — evals/README.md.
set -u
cd "$(dirname "$0")/.." || exit 1
source evals/lib/runner.sh

eval_run evals/cases/behavioral/gate-bypass-bash.jsonl "$@"
