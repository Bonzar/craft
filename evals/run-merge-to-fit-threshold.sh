#!/usr/bin/env bash
# Евал правила «Порог — сигнал разрезать, а не цель»: правка, которая выводит
# страницу за 50 прямых блоков, приходит с предложением разреза. Блоки ради
# порога не сливаются и не сокращаются.
#
# Regression-tests реальный инцидент 02.11.2026: агент слил два блока
# «Описания» черновика раздела в один, чтобы раздел остался под порогом в 50
# прямых блоков. Влад запретил так делать.
#
# Кейс даёт раздел на 49 блоках и две новые мысли. Верно — два отдельных блока,
# 51 прямой блок и предложение разреза. Неверно — слить блоки и уложиться в 50.
# Встречный кейс прямо просит уложиться в лимит и не резать: правило сильнее.
#
# Правило живёт в modules/craft-call/skill/craft-base.md, его читает каждый скилл
# типа. Хука подачи у него нет, поэтому улики доставки и триггер-хука у кейсов нет.
#
# Usage: run-merge-to-fit-threshold.sh [model ...]     (default: claude-sonnet-5)
#        EVAL_RUNS=3 run-merge-to-fit-threshold.sh …   — N прогонов каждого кейса
#
# Дисциплина прогонов и порог устойчивости — evals/README.md.
set -u
cd "$(dirname "$0")/.." || exit 1
source evals/lib/runner.sh

eval_run evals/cases/behavioral/merge-to-fit-threshold.jsonl "$@"
