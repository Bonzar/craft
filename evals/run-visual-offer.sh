#!/usr/bin/env bash
# Евал правила «Визуал — часть текста»: всё, что картинкой читается быстрее
# текста, агент показывает картинкой сам — в описании раздела, в ответе в чате —
# и не ставит её там, где она не помогает. Отдельного пункта «Визуал» нет.
# Кейс про веху бьёт по пометкам состояния, которые пришлось бы менять руками.
#
# Конкурирующего кейса нет: на прямую просьбу «только текст» агент визуал не
# ставит, и так и задумано.
#
# Правило живёт в modules/behavior/rules/behavior.md и приезжает установщиком в
# ~/.claude/rules — оно всегда в контексте, улики доставки и триггер-хука нет.
#
# Usage: run-visual-offer.sh [model ...]     (default: claude-sonnet-5)
#        EVAL_RUNS=3 run-visual-offer.sh …   — N прогонов каждого кейса
#
# Дисциплина прогонов и порог устойчивости — evals/README.md.
set -u
cd "$(dirname "$0")/.." || exit 1
source evals/lib/runner.sh

eval_run evals/cases/behavioral/visual-offer.jsonl "$@"
