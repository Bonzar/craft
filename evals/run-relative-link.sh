#!/usr/bin/env bash
# Евал правила «Ссылка на файл — по адресату»: локальный файл адресуется
# АБСОЛЮТНЫМ путём всегда.
#
# Regression-tests реальный инцидент: отчёт о правках в arc-маунте был собран
# markdown-ссылками с путями относительно /Users/dev/arc-mounts/, тогда как
# рабочая директория сессии — совсем другой репозиторий. Приложение резолвит
# относительный путь от ЕДИНСТВЕННОГО корня сессии, дополнительные рабочие
# директории корнями не являются — ни одна ссылка у Влада не открылась.
#
# ЧТО ИМЕННО МЕРИТСЯ. Промптовый слой: держится ли правило само, до того как
# сработают машинные подпорки. Подпорок две, и обе неполные: Stop-хук
# .claude/hooks/universal-stop-relative-link.sh блокирует завершение хода с
# неразрешимой ссылкой уже ПОСЛЕ показа сообщения (битую ссылку пользователь
# увидит, гейт лишь заставит дать рабочую следом), а PreToolUse-гейт
# .claude/hooks/craft-guard-plan-hygiene.sh ловит относительный путь превентивно,
# но только в файле плана. Всё, что видно в чате, держится на правиле.
#
# Улика доставки — сообщение инжекта ядра «Правил кода»: правило живёт там, а не
# в роутере. Инжект включается вторым рабочим корнем сессии — прогон задаёт его
# через EVAL_ADD_DIR, иначе в craft-репо правило до сессии не доходит и замер
# вышел бы про память модели, а не про соблюдение.
#
# Usage: run-relative-link.sh [model ...]     (default: claude-sonnet-5)
#        EVAL_RUNS=3 run-relative-link.sh …   — N прогонов каждого кейса
#
# Дисциплина прогонов и порог устойчивости — evals/README.md.
set -u
cd "$(dirname "$0")/.." || exit 1
source evals/lib/runner.sh

EVAL_ADD_DIR="${EVAL_ADD_DIR:-$(mktemp -d "${TMPDIR:-/tmp}/eval-second-root.XXXXXX")}"
export EVAL_ADD_DIR

eval_run evals/cases/behavioral/relative-link.jsonl "$@"
