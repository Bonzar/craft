#!/usr/bin/env bash
# Евал правила «Заглушка вместо контента — не отказ доступа»: браузер, дошедший до
# cookie-баннера или пустой страницы, — не тупик. Агент обязан описать снятие
# оверлея (клик согласия) или проверку свежести ссылки, а не объявлять источник
# недоступным и не уходить к другому сайту.
#
# Regression-tests реальный инцидент: страница гарантии miele.ru отдала только
# баннер согласия на cookies, агент принял это за недоступность источника и
# ушёл искать данные у сторонних дилеров, не попробовав ни клика по баннеру,
# ни проверки самого URL.
#
# ЧТО ИМЕННО МЕРИТСЯ. Промптовый слой: держится ли правило само. Машинной
# подпорки у него нет — судить прозу хуком нечем, поэтому этот прогон и есть
# приёмка урока.
#
# Улика доставки — сообщение SessionStart-инжекта роутера: правило живёт в его
# подстранице «Принципы работы», всегда-в-контексте.
#
# Терминальная ветка («не уходи к вторичному источнику, пока не пройдена лестница»)
# этим прогоном НЕ меряется: её содержание — лестница ступеней — живёт в Craft-доке
# скилла «Доступ к сайтам», а прогону Craft недоступен, и на одном запрете правило под
# прямым давлением не удерживается. Появится доставка скилла в прогоны — заводим кейс.
#
# Usage: run-site-stub-persist.sh [model ...]     (default: claude-sonnet-5)
#        EVAL_RUNS=3 run-site-stub-persist.sh …   — N прогонов каждого кейса
#
# Дисциплина прогонов и порог устойчивости — evals/README.md.
set -u
cd "$(dirname "$0")/.." || exit 1
source evals/lib/runner.sh

eval_run evals/cases/behavioral/site-stub-persist.jsonl "$@"
