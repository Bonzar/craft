#!/usr/bin/env bash
# Классификатор план-гейта: LLM-проверка, которую регулярка дать не может.
# Живёт в tools/, а не в .claude/hooks/ намеренно: реверс-smoke тестов требует
# регистрации каждого файла hooks/ в settings, а помощник — не хук.
#
# Режимы (первый аргумент), описание правки — на stdin:
#   match <план>  — соответствует ли правка одобренному плану;
#   throwaway     — очевидная ли это времянка (плана нет или правка мимо него);
#   delta <снапшот> <новый план> — какие юниты нового плана повторяют одобренный;
#   permission <окно> — разрешает ли недавний ответ или указание Влада эту правку;
#   structure <план> — разложить одобренный план на цели и задачи для реестра.
#
# Ответ одной строкой в stdout:
#   MATCH | NOMATCH:<причина> | THROWAWAY | NOTHROWAWAY:<причина>
#   | CLEAN | REPEATS:<заголовки> | PERMIT | NOPERMIT:<причина> | UNAVAILABLE
#
# Исключение — structure: он отдаёт МНОГОСТРОЧНЫЙ JSON, а не вердикт. Разложенный
# план в одну строку не передать, и однострочный контракт для него не годится;
# нераспознанный ответ там так же вырождается в UNAVAILABLE.
# Разбор ответа модели сверяет СНАЧАЛА отрицательную форму: положительная
# («СООТВЕТСТВУЕТ») входит в отрицательную («НЕ СООТВЕТСТВУЕТ») подстрокой.
#
# Вложенный вызов модели: haiku, один ход, без инструментов, из /tmp (вне
# проекта — проектные SessionStart-хуки не поднимаются), env сессии очищен тем
# же набором, что у раннера евалов, CRAFT_AUTONOMOUS=1 глушит гейты обоих
# контуров, CRAFT_NESTED_CALL=1 представляет вызов служебным.
#
# Второй признак обязателен и не выводится из первого: автономный режим гейты
# глушит, но ВКЛЮЧАЕТ стоп-хуки рутин, а их блокировка добавляет ход — вызов
# с --max-turns 1 падает, и классификатор молча вырождается в UNAVAILABLE. Таймаут, обрыв и нераспознанный ответ = UNAVAILABLE — решение о
# судьбе правки принимает гейт, не помощник.
#
# Env: PLAN_CLASSIFIER_CMD — команда модели (тесты подменяют моком);
#      PLAN_CLASSIFIER_TIMEOUT — бюджет секунд; дефолт 20 = медиана трёх
#        холодных замеров в облачном контейнере (6.2/6.8/8.1 с) с двойным
#        запасом, заведомо меньше лимита PreToolUse-хука;
#      PLAN_CLASSIFIER=off — принудительный UNAVAILABLE (аварийный выключатель).
set -u

[[ "${PLAN_CLASSIFIER:-}" == "off" ]] && { echo "UNAVAILABLE"; exit 0; }

mode="${1:-match}"
budget="${PLAN_CLASSIFIER_TIMEOUT:-20}"
turns=1
tools=""
cmd="${PLAN_CLASSIFIER_CMD:-claude}"
change="$(cat)"

prompt=""
sysprompt="Ты — проверка агентского контура. Отвечаешь ровно тем, что просят, без пояснений."

case "$mode" in
  match)
    planfile="${2:-}"
    [[ -n "$planfile" && -r "$planfile" ]] || { echo "UNAVAILABLE"; exit 0; }
    prompt="Ты — проверка соответствия правки одобренному плану. Ниже план целиком и одна правка. Ответь ровно одной строкой: НЕ СООТВЕТСТВУЕТ: ‹причина одним предложением› — либо СООТВЕТСТВУЕТ. Правка соответствует, когда выполняет обещанное планом в этой цели. Изменение, которого план не обещал, — НЕ СООТВЕТСТВУЕТ, даже если оно улучшает код той же цели или предложено в ревью.

=== ПЛАН ===
$(cat "$planfile")

=== ПРАВКА ===
$change"
    ;;
  throwaway)
    prompt="Ты — проверка класса правки. Ниже одна правка без плана. Ответь ровно одной строкой: ВРЕМЯНКА — если это очевидно временное (отладочная печать, временный файл рядом с работой, закомментированный на пробу блок) — либо НЕ ВРЕМЯНКА: ‹причина одним предложением›. Сомневаешься — НЕ ВРЕМЯНКА.

=== ПРАВКА ===
$change"
    ;;
  delta)
    snapfile="${2:-}"; newplan="${3:-}"
    [[ -n "$snapfile" && -r "$snapfile" && -n "$newplan" && -r "$newplan" ]] \
      || { echo "UNAVAILABLE"; exit 0; }
    # Дельта читает ВЕСЬ реестр одобренного и весь новый план — на живой работе
    # это по несколько килобайт с каждой стороны. Общего дефолта в 20 секунд не
    # хватало: сравнение вырождалось в UNAVAILABLE, гвард на этом останавливал
    # показ, и план становился непоказуемым вовсе. Замер: тот же вход отвечает,
    # когда время есть. Своего потолка у проверки нет — число здесь страховка от
    # зависшего вызова, а не бюджет.
    budget="${PLAN_CLASSIFIER_TIMEOUT:-1800}"
    prompt="Ты — проверка дельты планов. Ниже всё, что Влад уже одобрил, и новый план. Ответь одной строкой:

ПОВТОРЯЕТ ВСЁ — если КАЖДЫЙ кусок нового плана уже одобрен. Это перепоказ того же плана, он законен.
ПОВТОРЫ: ‹заголовки через запятую› — если одобрено только ЧАСТЬ кусков; перечисли именно их.
ДЕЛЬТА ЧИСТАЯ — если ни один кусок нового плана не одобрен.

Переформулировка тем же смыслом считается повтором. Кусок с ревизией, новой целью или изменённым дословным текстом повтором не считается. Записи «указание» считаются одобренным только когда прямо велят сделать правку; просьба показать план, вопрос или запрет менять — не одобрение, совпадающие с ними куски повтором не считаются.

=== ОДОБРЕННЫЙ ПЛАН ===
$(cat "$snapfile")

=== НОВЫЙ ПЛАН ===
$(cat "$newplan")"
    ;;
  permission)
    qafile="${2:-}"
    [[ -n "$qafile" && -r "$qafile" ]] || { echo "UNAVAILABLE"; exit 0; }
    prompt="Ты — проверка разрешения правки. Ниже окно недавних записей диалога (вопросы агента с выбранными ответами Влада и прямые реплики-указания Влада) и одна правка. Ответь ровно одной строкой: РАЗРЕШАЕТ — если какая-то запись прямо называет и разрешает именно эту правку (выбранный ответ на вопрос, предметно её описывающий, либо прямое указание её сделать, включая доуточнение к только что сделанной правке) — либо НЕ РАЗРЕШАЕТ: ‹причина одним предложением›. Ответ или указание про другое разрешением не является. Сомневаешься — НЕ РАЗРЕШАЕТ.

=== ОКНО ЗАПИСЕЙ ===
$(cat "$qafile")

=== ПРАВКА ===
$change"
    ;;
  ingest)
    # Единый разбор для всех трёх источников: одобренный план, ответ на
    # кнопочный вопрос, реплика Влада. На входе — что уже лежит в реестре и
    # новый материал; на выходе — что в реестр добавить и что в нём закрыть.
    #
    # Структуру решает разбор, а не форма документа: сколько целей, сколько
    # задач и на каком уровне вложенности — вопрос смысла. Заголовки и отступы
    # для этого не критерий, план каждый раз свёрстан по-своему.
    #
    # Здесь же семантическая дедупликация: материал про уже одобренную цель
    # ложится НОВОЙ ЗАДАЧЕЙ под неё, а не второй целью рядом; то, что уже есть
    # в реестре, не добавляется вовсе. Материал ничего не одобряет («покажи
    # план», «ок») — пустой add, и записи не появится.
    regfile="${2:-}"; material="${3:-}"; source="${4:-}"
    [[ -n "$material" && -r "$material" ]] || { echo "UNAVAILABLE"; exit 0; }
    budget="${PLAN_CLASSIFIER_TIMEOUT:-180}"
    # Закрытия спрашиваются только у ОДОБРЕННОГО ПЛАНА: новый план и есть граница
    # работы. Реплика границей не является — самые частые реплики Влада
    # («продолжай», «работай») значат ровно обратное, работа идёт. Вызывающий код
    # закрытия от прочих источников ещё и выбрасывает: одного промпта тут мало.
    closerules=""
    if [[ "$source" == "plan" ]]; then
      closerules="— В close перечисли адреса задач вида Ц1.2, про которые в строках «сделано:» их цели видно, что работа уже выполнена. Нет таких — пустой массив. Задачи, которые ты добавляешь этим же ответом, в close не попадают никогда.
"
    fi
    prompt="Ниже реестр уже одобренного и новый материал. Верни ТОЛЬКО JSON-объект, без пояснений.

{\"add\":[{\"kind\":\"work или ban\",\"goal\":\"Ц2 — номер цели из реестра, если материал про неё\",\"goal_new\":\"заголовок, если цель новая\",\"tasks\":[{\"title\":\"имя задачи\",\"where\":[\"адреса\"],\"anchor\":\"первая строка текста задачи дословно\"}]}],\"close\":[\"Ц1.2\"],\"lift\":[\"Ц2\"]}

Правила:
— kind — вид записи. \"work\", когда Влад поручает работу: это обычный случай. \"ban\" — РЕДКИЙ: только когда материал не поручает ничего и целиком состоит из запрета впредь («никогда не создавай .ts», «не трогай прод»). Есть в материале работа — вид \"work\", чем бы он ни был обрамлён. Отрицательная форма запретом не делает: «почини дефекты, не надо багов на проде» поручает чинить, «это не ок, поправь» поручает поправить. У записи с kind \"ban\" задач нет, заголовок пиши в goal_new.
— В lift перечисли номера записей-ЗАПРЕТОВ вида Ц2, которые Влад этим материалом отменяет («можно снова .ts», «снимаю запрет на прод», «забудь про то ограничение»). Нет таких — поля не пиши. Запреты, которые ты заводишь этим же ответом, в lift не попадают никогда.
${closerules}— Цель, у которой все задачи закрыты, принимает новые задачи наравне с прочими: работа под ней продолжается — доработка, ответ ревьюеру, обновление описания. Материал про такую цель — это её НОМЕР в goal и новая задача, а не вторая такая же цель.
— Цель — то, ради чего работа; задача — часть работы под ней. Сколько целей и задач и как они вложены, решай по смыслу материала, а не по его заголовкам и отступам.
— Материал относится к цели, которая УЖЕ есть в реестре — укажи её НОМЕР в поле goal (например Ц2) и добавь только новые задачи. Второй такой же цели заводить нельзя. Заголовок в этом случае не пиши.
— Цель новая — заполни goal_new заголовком, а goal оставь пустым.
— Задача, которая уже есть в реестре, не добавляется.
— Адрес — то, что правка меняет: путь к файлу, идентификатор блока Craft, номер тикета, имя команды или настройки. Нет таких — пустой массив.
— anchor — дословная первая строка того куска материала, который описывает задачу; по ней вызывающий код вырежет тело. Материал короткий и целиком про одну задачу — anchor пустая строка.
— Материал ничего не поручает делать (вопрос, благодарность, просьба показать план) — верни пустой add.

=== РЕЕСТР ===
$( [[ -n "$regfile" && -r "$regfile" ]] && cat "$regfile" || echo '(пусто)' )

=== МАТЕРИАЛ ===
$(cat "$material")"
    ;;
  cover)
    # Одна сверка вместо трёх веток: покрыта ли правка реестром одобренного.
    # Прежние режимы спрашивали каждый про своё (план, окно разрешений,
    # времянка), и правка сверялась то с одним, то с другим.
    regfile="${2:-}"
    [[ -n "$regfile" && -r "$regfile" ]] || { echo "UNAVAILABLE"; exit 0; }
    # Сверку ведёт агент, а не однопроходный вопрос: смысл правки часто виден
    # только из файла, куда она ложится, и по куску текста его не прочесть.
    # Инструменты — только читающие, ходов несколько.
    turns=8
    tools="Read,Grep,Glob"
    # Своего потолка у сверки нет: ждём решения, сколько бы оно ни заняло.
    # Число здесь — страховка от зависшего вызова, а не бюджет проверки.
    budget="${PLAN_CLASSIFIER_TIMEOUT:-1800}"
    prompt="Ниже реестр одобренного — цели и задачи, на которые Влад дал ок, — и одна правка. Тебе доступно чтение файлов: если смысл правки без окружения не читается, открой файл, куда она ложится, и посмотри сам. Ответь ровно одной строкой.

ЗАПРЕЩЕНО ‹Ц›: ‹цитата› — если запись, ПОМЕЧЕННАЯ СЛОВОМ ЗАПРЕТ в своей строке, запрещает эту правку и более позднего разрешения именно её в реестре нет. Записи, помеченные словом «работа», запретом не бывают НИКОГДА — ни их заголовок, ни текст, ни тела задач под ними: там лежит материал, из которого работа и выросла, включая недовольные реплики Влада вроде «это не ок, поправь». Такая реплика поручает работу, а не запрещает её.
РАЗРЕШЕНО ПОВЕРХ ‹Ц› — если такой запрет есть, но позже Влад прямо разрешил именно эту правку.
ПОКРЫТА ‹Ц.З›: ‹что сделано одной фразой› — если правка выполняет то, что обещано этой задачей. Правка, делающая ЧАСТЬ задачи, покрыта: задача почти всегда требует нескольких правок, и «не выполняет задачу целиком» причиной отказа НЕ БЫВАЕТ. Покрыты и правки вокруг работы: комментарий, документация, тест, кейс, отладочная печать по ходу этой задачи — часть той же работы, а не «изменение без функциональности». Работа под задачей уже выглядит сделанной, а правка её дополняет — всё равно покрыта: закрывает задачу агент, а не сверка. Кейс или тест, написанный ДО реализации, покрыт: так требует дисциплина работы — проверка заводится красной и только потом чинится код, — и «кейс без реализации» причиной отказа не бывает. Правка, опирающаяся на функцию или файл, которых ещё нет, покрыта по той же причине: ход состоит из нескольких правок, и порядок внутри него сверку не касается. Файл, не названный в адресах задачи, покрытию не мешает — задача вида «во всех местах использования» адресов не перечисляет. Покрытие даёт ЛЮБАЯ открытая задача, а не первая незакрытая: порядок задач в реестре — это порядок показа, а не обязательство. Агент вправе взяться за третью задачу раньше первой, и «предыдущие задачи ещё не закрыты» причиной отказа НЕ БЫВАЕТ.
Задача со словом «закрыта» покрытием НЕ БЫВАЕТ: работа под ней уже кончилась, а текста у неё не осталось. Имя такой задачи совпало со смыслом правки — это НЕ ПОКРЫТА с причиной «работа по этой задаче уже закрыта». Про саму ЦЕЛЬ этого правила нет: цель со всеми закрытыми задачами живая — под ней просто нет открытой работы, и покрытие даёт её открытая задача, когда она появится.

ЧЕРНОВОЕ — отладочная печать, временный файл рядом с работой, закомментированный на пробу блок.
НЕ ПОКРЫТА: ‹причина одним предложением› — во всех прочих случаях.

=== РЕЕСТР ===
$(cat "$regfile")

=== ПРАВКА ===
$change"
    ;;
  *) echo "UNAVAILABLE"; exit 0 ;;
esac

# Один вызов модели. Системный промпт заменяется коротким: по умолчанию
# вложенный вызов тащит весь системный контекст Claude Code — инструменты,
# правила, окружение, — и на разметке плана он раскачивал ответ (замер: одна
# цель, семь целей, ноль целей на одном и том же плане).
ask() {
  cd /tmp && printf '%s' "$prompt" | timeout "$budget" env \
    -u CLAUDE_CODE_SESSION_ID -u CLAUDE_CODE_CHILD_SESSION \
    -u CLAUDE_PID -u CLAUDE_CODE_REMOTE_SESSION_ID \
    CRAFT_AUTONOMOUS=1 CRAFT_NESTED_CALL=1 \
    "$cmd" -p --model claude-haiku-4-5-20251001 \
    --max-turns "$turns" --system-prompt "$sysprompt" \
    ${tools:+--allowedTools "$tools"} \
    --exclude-dynamic-system-prompt-sections 2>/dev/null
}

answer="$(ask)" || { echo "UNAVAILABLE"; exit 0; }

# Разбор материала отдаёт структуру, а не вердикт: печатаем JSON целиком. Модель
# любит обрамлять его забором — снимаем и проверяем разбираемость: невалидный
# ответ должен вырождаться в UNAVAILABLE, а не приезжать в реестр мусором.
if [[ "$mode" == "ingest" ]]; then
  json="$(sed -e '/^[[:space:]]*```/d' <<<"$answer")"
  if printf '%s' "$json" | python3 -c 'import json,sys; d=json.load(sys.stdin); sys.exit(0 if isinstance(d,dict) and isinstance(d.get("add"),list) else 1)' 2>/dev/null; then
    printf '%s\n' "$json"
  else
    echo "UNAVAILABLE"
  fi
  exit 0
fi

# Последняя непустая строка ответа; отрицательные формы сверяются первыми.
last="$(grep -v '^[[:space:]]*$' <<<"$answer" | tail -1)"
case "$mode" in
  match)
    if grep -qF 'НЕ СООТВЕТСТВУЕТ' <<<"$last"; then
      printf 'NOMATCH:%s\n' "${last#*НЕ СООТВЕТСТВУЕТ}" | sed 's/^NOMATCH::*/NOMATCH:/'
    elif grep -qF 'СООТВЕТСТВУЕТ' <<<"$last"; then echo "MATCH"
    else echo "UNAVAILABLE"; fi ;;
  throwaway)
    if grep -qF 'НЕ ВРЕМЯНКА' <<<"$last"; then
      printf 'NOTHROWAWAY:%s\n' "${last#*НЕ ВРЕМЯНКА}" | sed 's/^NOTHROWAWAY::*/NOTHROWAWAY:/'
    elif grep -qF 'ВРЕМЯНКА' <<<"$last"; then echo "THROWAWAY"
    else echo "UNAVAILABLE"; fi ;;
  delta)
    # «Повторяет всё» проверяется ПЕРВЫМ: перепоказ того же плана законен, а
    # частичный повтор — нет, и спутать их значит отбить показ, который правила
    # прямо разрешают.
    if grep -qF 'ПОВТОРЯЕТ ВСЁ' <<<"$last"; then echo "REPEATSALL"
    elif grep -qF 'ПОВТОРЫ:' <<<"$last"; then
      printf 'REPEATS:%s\n' "${last#*ПОВТОРЫ:}"
    elif grep -qF 'ДЕЛЬТА ЧИСТАЯ' <<<"$last"; then echo "CLEAN"
    else echo "UNAVAILABLE"; fi ;;
  permission)
    if grep -qF 'НЕ РАЗРЕШАЕТ' <<<"$last"; then
      printf 'NOPERMIT:%s\n' "${last#*НЕ РАЗРЕШАЕТ}" | sed 's/^NOPERMIT::*/NOPERMIT:/'
    elif grep -qF 'РАЗРЕШАЕТ' <<<"$last"; then echo "PERMIT"
    else echo "UNAVAILABLE"; fi ;;
  cover)
    # Порядок сверки значим: «НЕ ПОКРЫТА» содержит «ПОКРЫТА» подстрокой, а
    # «РАЗРЕШЕНО ПОВЕРХ» — «ЗАПРЕЩЕНО» не содержит, но оба про запрет, и
    # разрешающая форма обязана проверяться раньше запрещающей.
    if grep -qF 'РАЗРЕШЕНО ПОВЕРХ' <<<"$last"; then
      printf 'OVERRIDE:%s\n' "${last#*РАЗРЕШЕНО ПОВЕРХ}"
    elif grep -qF 'ЗАПРЕЩЕНО' <<<"$last"; then
      printf 'FORBIDDEN:%s\n' "${last#*ЗАПРЕЩЕНО}"
    elif grep -qF 'НЕ ПОКРЫТА' <<<"$last"; then
      printf 'UNCOVERED:%s\n' "${last#*НЕ ПОКРЫТА}" | sed 's/^UNCOVERED::*/UNCOVERED:/'
    elif grep -qF 'ПОКРЫТА' <<<"$last"; then
      printf 'COVERED:%s\n' "${last#*ПОКРЫТА}"
    elif grep -qF 'ЧЕРНОВОЕ' <<<"$last"; then echo "DRAFT"
    else echo "UNAVAILABLE"; fi ;;
esac
exit 0
