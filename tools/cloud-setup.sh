#!/usr/bin/env bash
# Тело setup-скрипта облачного окружения «Craft». В настройках окружения от
# скрипта остаётся одна строка вызова (README, «Окружение с нуля»), а всё, что
# он делает, живёт здесь, в репозитории: окружение пересоздаётся без потерь.
#
# Выполняется до старта харнеса, в /home/user при HOME=/root; переменных из
# настроек окружения здесь нет (замер 18.09.2026), поэтому всё, что от них
# зависит, делают модули на старте сессии. Причину каждой неудачи пишем в
# stderr: молчаливый провал оставляет сессию без модулей незаметно.

set -u
repo="$(cd "$(dirname "$(realpath "${BASH_SOURCE[0]}")")/.." && pwd)"
cd "$repo" || exit 1

# Второй агент. В контейнере codex бывал предустановлен (замер 18.09.2026),
# в окружении, созданном 14.10.2026, его не оказалось.
if ! command -v codex >/dev/null 2>&1; then
  npm i -g @openai/codex >&2 || echo "cloud-setup: codex не поставлен" >&2
fi

python3 tools/jarvis-install --harness claude \
  || { echo "cloud-setup: jarvis-install упал, модули не поставлены" >&2; exit 1; }
