SCOPES={
    'base-test': (Path('/srv/assertion-release/test'),768*1024**2),
    'base-prod': (Path('/srv/assertion-release/production'),768*1024**2),
    'visual-test': (Path('/var/lib/assertion-memory-visual/test'),32*1024**2),
    'visual-prod': (Path('/var/lib/assertion-memory-visual/prod'),32*1024**2),
}
CONFIG=Path('/etc/assertion-release-retention')
RUN=Path('/run/assertion-release-retention')
PROD_FENCE=Path('/run/assertion-base-prod-transition/fence.lock')
OK=b'assertion-release-retention-v1 OK\n'
BASE_NAME=re.compile(r'[a-f0-9]{40}-[a-f0-9]{64}\Z')
VISUAL_NAME=re.compile(r'[a-f0-9]{64}\Z')
GEN_PATH={'base':'releases','visual-static':'releases','visual-runtime':'runtime/versions'}
VENV_PY=re.compile(r'python3\.(?:11|12|13|14)\Z')
CERT_NAMES={('pip','_vendor','certifi','cacert.pem'):'pip',('certifi','cacert.pem'):'certifi'}
MAX_PROVENANCE_FILE=2*1024**2
HOLD=('runtime/.runtime-transition','runtime/.visual-runtime-joint-transition','.activation-pending-v1')
LOG=logging.getLogger(__name__)
SAFE_ERRORS=(OSError, ValueError, RuntimeError, TypeError, csv.Error)

@dataclass(frozen=True)
class Store:
    kind: str
    qualified: object  # function: validate exact generated bytes (raises on mismatch)

    def __post_init__(self):
        if self.kind not in GEN_PATH or not callable(self.qualified):
            raise ValueError('retention_store')


def safe_root(path, owner):
    info=path.lstat()
    if (not stat.S_ISDIR(info.st_mode) or info.st_uid!=owner or info.st_mode&0o022
            or path.resolve(strict=True)!=path):
        raise ValueError('retention_path')
    return info


def lock_identity(root, fd, owner):
    locked=root/'deploy.lock'
    actual=locked.lstat()
    if (not stat.S_ISREG(actual.st_mode) or actual.st_uid!=owner or actual.st_nlink!=1
            or actual.st_mode&0o077 or not os.path.samestat(actual,os.fstat(fd))):
        raise ValueError('retention_lock')
    # Test the same open description is actually locked; do not unlock a
    # duplicate. A different description of the same inode must stay blocked.
    with os.fdopen(os.open(locked,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK),'rb') as other:
        if not os.path.samestat(actual,os.fstat(other.fileno())):
            raise ValueError('retention_lock')
        try:
            fcntl.flock(other,fcntl.LOCK_EX|fcntl.LOCK_NB)
        except BlockingIOError:
            pass
        else:
            raise ValueError('retention_lock_required')
        fcntl.flock(fd,fcntl.LOCK_EX|fcntl.LOCK_NB)


def trusted_file(path, owner, size):
    info=path.lstat()
    with os.fdopen(os.open(path,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK),'rb') as file:
        if (not os.path.samestat(info,os.fstat(file.fileno())) or not stat.S_ISREG(info.st_mode)
                or info.st_uid!=owner or info.st_mode&0o022 or info.st_nlink!=1 or info.st_size>size):
            raise ValueError('retention_control_file')
        return file.read(size+1)


def host_proof(scope, lock_fd):
    def proof(kind, active, candidate, meta):
        safe_root(RUN,0)
        endpoint=RUN/(scope+'.sock')
        entry=endpoint.lstat()
        if entry.st_uid!=0 or not stat.S_ISSOCK(entry.st_mode):
            return False
        wire=json.dumps({'version':1,'scope':scope,'store':kind,'active':active.name,
                         'inactive':candidate.name,'dev':meta.st_dev,'ino':meta.st_ino},
                        separators=(',',':')).encode('ascii')+b'\n'
        with socket.socket(socket.AF_UNIX,socket.SOCK_STREAM) as conn:
            conn.settimeout(8)
            conn.connect(str(endpoint))
            _,uid,_=struct.unpack('3i',conn.getsockopt(socket.SOL_SOCKET,socket.SO_PEERCRED,12))
            if uid!=0 or conn.sendmsg([wire],[(socket.SOL_SOCKET,socket.SCM_RIGHTS,struct.pack('i',lock_fd))])!=len(wire):
                return False
            conn.shutdown(socket.SHUT_WR)
            with conn.makefile('rb') as response:
                return response.read(len(OK)+1)==OK
    return proof


def bindings(root, stores, *, ready=None):
    """Only installed normal receivers in four canonical roots can enable this."""
    root=Path(root)
    modes=[s for s,(p,_) in SCOPES.items() if p==root]
    if len(modes)!=1:
        return None
    scope=modes[0]
    marker=CONFIG/(scope+'.enabled')
    if not os.path.lexists(marker):
        return None
    safe_root(CONFIG,0)
    if trusted_file(marker,0,3)!=b'on\n':
        raise ValueError('retention_enable_marker')
    return lambda lock: Retention(root,stores,lock_fd=lock,proof=host_proof(scope,lock),
                                  minimum=SCOPES[scope][1],ready=ready)


def regular_at(directory,name,expected,owner,device):
    fd=os.open(name,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK,dir_fd=directory)
    with os.fdopen(fd,'rb') as source:
        current=os.fstat(source.fileno())
        if (not os.path.samestat(current,expected) or current.st_uid!=owner or current.st_dev!=device
                or not stat.S_ISREG(current.st_mode) or current.st_nlink!=1 or current.st_mode&0o022
                or not 0<current.st_size<=MAX_PROVENANCE_FILE):
            raise ValueError('retention_generated_ca_identity')
        data=source.read(MAX_PROVENANCE_FILE+1)
        if len(data)!=current.st_size:
            raise ValueError('retention_generated_ca_identity')
        return data


def generated_ca(site, parent, name, relative, owner, device, meta):
    """Only real certifi X.509 bundles in the exact installed wheel RECORD."""
    if relative not in CERT_NAMES or site is None:
        raise ValueError('retention_sensitive_member')
    source=regular_at(parent,name,meta,owner,device)
    pkg=CERT_NAMES[relative]
    dist_names=[n for n in os.listdir(site) if re.fullmatch(pkg+r'-[0-9][A-Za-z0-9_.+-]{0,95}\.dist-info',n)]
    if len(dist_names)!=1:
        raise ValueError('retention_generated_ca_record')
    fd=os.open(dist_names[0],os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=site)
    try:
        info=os.stat('RECORD',dir_fd=fd,follow_symlinks=False)
        records=regular_at(fd,'RECORD',info,owner,device)
    finally:
        os.close(fd)
    path='/'.join(relative)
    want='sha256='+base64.urlsafe_b64encode(hashlib.sha256(source).digest()).decode('ascii').rstrip('=')
    got=[row for row in csv.reader(io.StringIO(records.decode('utf-8')),strict=True) if row and row[0]==path]
    if got!=[[path,want,str(len(source))]]:
        raise ValueError('retention_generated_ca_record')
    chunks=[]
    inside=False
    for line in source.splitlines():
        if line==b'-----BEGIN CERTIFICATE-----' and not inside:
            inside=True
        elif line==b'-----END CERTIFICATE-----' and inside:
            inside=False
        elif inside:
            if not re.fullmatch(rb'[A-Za-z0-9+/]{1,76}={0,2}',line):
                raise ValueError('retention_generated_ca_not_certificates')
        elif not (line.strip()==b'' or line.startswith(b'#')):
            raise ValueError('retention_generated_ca_not_certificates')
        else:
            continue
        chunks.append(line)
    if inside or not chunks:
        raise ValueError('retention_generated_ca_not_certificates')
    try:
        ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT).load_verify_locations(cadata=b'\n'.join(chunks).decode('ascii'))
    except (ssl.SSLError,ValueError) as exc:
        raise ValueError('retention_generated_ca_not_certificates') from exc


def eligible_tree(parent_fd, name, root_stat, *, owner, allow_venv):
    # Reject writable/shared files, hard links, irregular devices, secret/DB
    # paths and submounts before deletion. The privileged proof additionally
    # checks same-device bind mounts and references across namespaces.
    limit=100_000
    entries={}
    def inspect(fd, rel, site=None):
        nonlocal limit
        if (allow_venv and len(rel)==4 and rel[:2]==('venv','lib')
                and VENV_PY.fullmatch(rel[2]) and rel[3]=='site-packages'):
            site=fd
        for name in os.listdir(fd):
            limit-=1
            if limit<0:
                raise ValueError('retention_tree_limit')
            item=(*rel,name)
            low=name.lower()
            if ((not rel and low in {'secrets','credentials','wheelhouse','logs','data','state','config','backups'})
                    or low.endswith(('.db','.db-wal','.db-shm','.sqlite','.sqlite-wal','.sqlite-shm',
                        '.sqlite3','.sqlite3-wal','.sqlite3-shm','.key','.env','.log'))):
                raise ValueError('retention_sensitive_member')
            info=os.stat(name,dir_fd=fd,follow_symlinks=False)
            if info.st_dev!=root_stat.st_dev or info.st_uid!=owner:
                raise ValueError('retention_member_owner_or_device')
            if low.endswith('.pem'):
                prefix=item[:4]
                if (not allow_venv or len(prefix)!=4 or prefix[:2]!=('venv','lib')
                        or not VENV_PY.fullmatch(prefix[2]) or prefix[3]!='site-packages'):
                    raise ValueError('retention_sensitive_member')
                generated_ca(site,fd,name,item[4:],owner,root_stat.st_dev,info)
            entries[item]=info
            mode=info.st_mode
            if stat.S_ISLNK(mode):
                if not allow_venv or item not in {('venv','lib64'),('venv','bin','python'),
                        ('venv','bin','python3'),('venv','bin','python3.11'),('venv','bin','python3.12'),
                        ('venv','bin','python3.13'),('venv','bin','python3.14')}:
                    raise ValueError('retention_nested_link')
                continue  # fd-relative rmtree only unlinks; never follows venv links
            if mode&0o022:
                raise ValueError('retention_writable_member')
            if stat.S_ISDIR(mode):
                child=os.open(name,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=fd)
                try:
                    if not os.path.samestat(info,os.fstat(child)):
                        raise ValueError('retention_replaced_member')
                    inspect(child,item,site)
                finally:
                    os.close(child)
            elif not stat.S_ISREG(mode) or info.st_nlink!=1:
                raise ValueError('retention_nonexclusive_member')
    fd=os.open(name,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=parent_fd)
    try:
        if not os.path.samestat(root_stat,os.fstat(fd)):
            raise ValueError('retention_replaced_candidate')
        inspect(fd,())
    finally:
        os.close(fd)
    return entries


def same_inventory(left, right):
    def seal(info):
        return (info.st_dev,info.st_ino,info.st_mode,info.st_uid,info.st_gid,
                info.st_nlink,info.st_size,info.st_mtime_ns,info.st_ctime_ns)
    return left.keys()==right.keys() and all(seal(info)==seal(right[path]) for path,info in left.items())


def unlink_sealed(parent, name, root_stat, inventory):
    """Delete only names in the qualified tree, through inode-bound FDs."""
    children={}
    for path, info in inventory.items():
        children.setdefault(path[:-1],{})[path[-1]]=info
    def entry(fd, label, expected):
        current=os.stat(label,dir_fd=fd,follow_symlinks=False)
        if (not os.path.samestat(current,expected) or current.st_mode!=expected.st_mode
                or current.st_uid!=expected.st_uid or current.st_gid!=expected.st_gid):
            raise ValueError('retention_tree_replaced_after_witness')
        if not stat.S_ISDIR(expected.st_mode) and (current.st_ctime_ns!=expected.st_ctime_ns
                or current.st_mtime_ns!=expected.st_mtime_ns or current.st_nlink!=expected.st_nlink):
            raise ValueError('retention_file_changed_after_witness')
    def descend(parent_fd, label, expected, path):
        fd=os.open(label,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=parent_fd)
        try:
            if not os.path.samestat(os.fstat(fd),expected):
                raise ValueError('retention_tree_replaced_after_witness')
            out=children.get(path,{})
            if set(os.listdir(fd))!=set(out):
                raise ValueError('retention_tree_changed_after_witness')
            for child, info in out.items():
                entry(fd,child,info)
                if stat.S_ISDIR(info.st_mode):
                    descend(fd,child,info,(*path,child))
                else:
                    os.unlink(child,dir_fd=fd)
            entry(parent_fd,label,expected)
            os.rmdir(label,dir_fd=parent_fd)
        finally:
            os.close(fd)
    entry(parent,name,root_stat)
    descend(parent,name,root_stat,())


@contextmanager
def guard_prod_fence(path, owner=0):
    """Hold a shared legacy-transition fence only during proof/unlink.

    The lane lock is already held. Do not wait here: legacy operations may
    take the exclusive fence first and then attempt their lane lock.
    Do not hold this when hooking restart/prepare/smoke.
    """
    safe_root(path.parent,owner)
    with os.fdopen(os.open(path,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK),'rb') as lock:
        actual=path.lstat()
        if (not os.path.samestat(actual,os.fstat(lock.fileno())) or actual.st_uid!=owner
                or not stat.S_ISREG(actual.st_mode) or actual.st_nlink!=1 or actual.st_mode&0o022):
            raise ValueError('retention_prod_fence')
        fcntl.flock(lock,fcntl.LOCK_SH|fcntl.LOCK_NB)
        yield


class Retention:
    def __init__(self, root, stores, *, lock_fd, proof, minimum, ready=None):
        self.root=Path(root)
        self.owner=os.geteuid()
        self.stores=tuple(stores)
        self.lock=lock_fd
        self.proof=proof
        self.minimum=minimum
        self.ready=ready

    def reader_ready(self):
        try:
            return self.ready is None or self.ready() is True
        except SAFE_ERRORS:
            return False

    def settled(self):
        safe_root(self.root,self.owner)
        lock_identity(self.root,self.lock,self.owner)
        if any(os.path.lexists(self.root/x) for x in HOLD):
            raise ValueError('retention_unsettled_transitions')

    def active(self, store):
        root=self.root/'runtime' if store.kind=='visual-runtime' else self.root
        safe_root(root,self.owner)
        directory=self.root/GEN_PATH[store.kind]
        safe_root(directory,self.owner)
        link=root/'current'
        if not os.path.lexists(link):
            return None
        if not link.is_symlink():
            raise ValueError('retention_current_pointer')
        raw=link.readlink()
        active=directory/raw.name
        if raw not in (active,Path(directory.name)/raw.name):
            raise ValueError('retention_current_pointer')
        matcher=BASE_NAME if store.kind=='base' else VISUAL_NAME
        if not matcher.fullmatch(active.name):
            raise ValueError('retention_active_id')
        safe_root(active,self.owner)
        # Existing active Visual runtime from before this policy has no new
        # GC receipt yet. Root authority still qualifies it as current; unlike
        # inactive candidates it is never validated as a deletion target.
        if store.kind!='visual-runtime':
            store.qualified(active)
        return active

    def remove(self, store, inactive, *, dry=False):
        if self.root==SCOPES['base-prod'][0]:
            with guard_prod_fence(PROD_FENCE):
                return self._remove(store,inactive,dry=dry)
        return self._remove(store,inactive,dry=dry)

    def _remove(self, store, inactive, *, dry):
        self.settled()
        if not self.reader_ready():
            return False
        active=self.active(store)
        directory=self.root/GEN_PATH[store.kind]
        matcher=BASE_NAME if store.kind=='base' else VISUAL_NAME
        if (not active or inactive==active or inactive.parent!=directory or not matcher.fullmatch(inactive.name)):
            return False
        meta=safe_root(inactive,self.owner)
        outer=safe_root(directory,self.owner)
        if meta.st_dev!=outer.st_dev or os.path.ismount(inactive):
            return False
        store.qualified(inactive)
        fd=os.open(directory,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW)
        try:
            if not os.path.samestat(outer,os.fstat(fd)):
                return False
            inventory=eligible_tree(fd,inactive.name,meta,owner=self.owner,allow_venv=store.kind=='base')
            if self.proof(store.kind,active,inactive,meta) is not True:
                return False
            self.settled()
            if not self.reader_ready() or self.active(store)!=active or not os.path.samestat(meta,inactive.lstat()):
                return False
            if not os.path.samestat(outer,directory.lstat()):
                return False
            current_inventory=eligible_tree(fd,inactive.name,meta,owner=self.owner,allow_venv=store.kind=='base')
            if not same_inventory(inventory,current_inventory):
                raise ValueError('retention_tree_changed_after_witness')
            if not dry:
                unlink_sealed(fd,inactive.name,meta,inventory)
                os.fsync(fd)
            return True
        finally:
            os.close(fd)

    def sweep(self, phase, *, dry=False):
        deleted=skipped=unknown=0
        self.settled()
        for store in self.stores:
            directory=self.root/GEN_PATH[store.kind]
            safe_root(directory,self.owner)
            active=self.active(store)
            if not active:
                skipped+=sum(1 for _ in directory.iterdir())
                continue
            valid=BASE_NAME if store.kind=='base' else VISUAL_NAME
            for candidate in sorted(directory.iterdir()):
                if candidate==active:
                    continue
                if not valid.fullmatch(candidate.name):
                    unknown+=1
                    continue
                try:
                    ok=self.remove(store,candidate,dry=dry)
                except SAFE_ERRORS:
                    ok=False
                deleted+=ok
                skipped+=not ok
        LOG.warning('release_retention phase=%s %s=%d unproven=%d unknown=%d',phase,
                'would_remove' if dry else 'removed',deleted,skipped,unknown)
        return deleted,skipped,unknown

    def preflight(self):
        self.sweep('before_prepare')
        fs=os.statvfs(self.root)
        if fs.f_bavail*fs.f_frsize<self.minimum or fs.f_favail<1024:
            raise ValueError('release_retention_insufficient_headroom')

    def failed(self, store, candidate):
        # No old directory is discarded on failure. Only a newly supplied
        # exact candidate is considered, and only once rollback is settled.
        try:
            if self.remove(store,candidate):
                LOG.warning('release_retention phase=failed_prepare removed=1')
                return
        except SAFE_ERRORS:
            pass
        LOG.warning('release_retention phase=failed_prepare deferred=1')


def dry_inventory(scope, stores, *, ready=None):
    """Review-only real host proof, no marker needed and no file can be deleted."""
    from contextlib import ExitStack
    if scope not in SCOPES:
        raise ValueError('retention_scope')
    root,minimum=SCOPES[scope]
    if scope.startswith('visual-') and ready is None:
        raise ValueError('retention_visual_reader_proof_required')
    with ExitStack() as guards:
        lock=guards.enter_context(os.fdopen(os.open(root/'deploy.lock',
                     os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK),'rb'))
        fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
        if scope.startswith('visual-'):
            legacy=root/'runtime'/'runtime.lock'
            if os.path.lexists(legacy):
                marker=guards.enter_context(os.fdopen(os.open(legacy,
                            os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK),'rb'))
                entry=os.fstat(marker.fileno())
                if (not stat.S_ISREG(entry.st_mode) or entry.st_uid!=os.geteuid() or entry.st_nlink!=1
                        or entry.st_mode&0o077 or not os.path.samestat(entry,legacy.lstat())):
                    raise ValueError('retention_legacy_lock')
                fcntl.flock(marker,fcntl.LOCK_EX|fcntl.LOCK_NB)
        engine=Retention(root,stores,lock_fd=lock.fileno(),proof=host_proof(scope,lock.fileno()),minimum=minimum,ready=ready)
        return engine.sweep('dry_inventory',dry=True)
