#!/usr/bin/env bash
# Пульт с человекоподобным вводом: склеивает слой траекторий, слой ввода и рабочий
# скрипт в одну программу и шлёт её dev-browser на маке.
#
# Профиль браузера и порт задаются переменными: DB_PORT (по умолчанию рабочий 9333).
# Профиль у сессий ОБЩИЙ — он копит пропуска антиботов и логины; чистые профили заводим
# только под замеры.
#
# Заодно ретранслирует зов о помощи. Сетевого вызова в песочнице нет, поэтому сессия
# кричит строкой «ЗАСТРЯЛА <идентификатор вкладки> <адрес> :: <повод>», а мы заявляем эту
# вкладку в пульт капчи и печатаем готовую ссылку для Влада. Заявку снимает строка
# «ПРОШЛА <идентификатор вкладки> <адрес>».
#
# Usage: bash h.sh script.js [таймаут-сек]
#
# Срока по умолчанию у прогона НЕТ. Он убивал сессию вместе с её ожиданием человека, а у
# ожидания человека срока не бывает: машина не знает, когда человек освободится.
#
# Ноль инструмент прогона не принимает, а его же предельное значение 4294967295 обрывает
# прогон МГНОВЕННО: секунды переводятся в миллисекунды и переполняют таймер. Наибольшее
# работающее — 2147483 секунды, около 24 дней; замерено встречной пробой, 2147484 уже
# рвёт прогон на старте. Это и есть «без срока» на практике.
#
# Явный срок вторым аргументом остаётся для замеров и коротких проб.
set -u
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GC="$DIR/gc.js"
T="${2:-2147483}"
PORT="${DB_PORT:-9333}"
CM="${DB_SSH_CTL:-/tmp/sshcm}"
GATE="${CAPGATE_URL:-http://127.0.0.1:8899}"
mkdir -p "$CM"
OPTS=(-o "ProxyCommand=nc -X 5 -x 127.0.0.1:1055 %h %p"
      -o "ControlMaster=auto" -o "ControlPath=$CM/%r@%h:%p" -o "ControlPersist=10m"
      -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null
      -o LogLevel=ERROR -o ConnectTimeout=25)
# Адрес узла — из окружения: в репозитории его нет, это персональные данные Влада.
_env_helper="$(cd "$DIR/../.." && pwd)/.claude/hooks/_load-env.sh"
[[ -f "$_env_helper" ]] && . "$_env_helper"
[[ -n "${MAC_NODE_ADDR:-}" ]] || { echo "нет MAC_NODE_ADDR в окружении — tailnet-адрес мака кладётся в настройки облачного окружения"; exit 1; }
HOST="agent@$MAC_NODE_ADDR"

[[ -f "$GC" ]] || { echo "нет слоя траекторий: $GC"; exit 1; }

# Метка занятости профиля: уборка не трогает то, с чем сейчас работают. Ставится не
# однажды, а бьётся сердцем всё время прогона — иначе работа дольше окна уборки переставала
# защищать вкладки, и они закрывались прямо под сессией. Сердце живёт на маке рядом с
# прогоном и умирает вместе с ним.
ssh "${OPTS[@]}" "$HOST" "touch /tmp/agchrome-keep.$PORT" >/dev/null 2>&1 || true

# Тело заявки уходит ОТДЕЛЬНЫМ ПОТОКОМ, а не внутри текста команды.
#
# Раньше оно вставлялось в строку удалённой команды между одинарными кавычками, и адрес
# страницы попадал туда как есть. Одинарная кавычка в адресе закрывала кавычку команды, и
# остаток удалённая оболочка исполняла как свои команды — от имени учётки агента, у которой
# общий профиль Chrome со всеми логинами и выходной узел в домашнюю сеть. Ревью безопасности
# нашло это как исполнение команд с недоверенного сайта; воспроизведено тестом
# tools/mac/h-shell-injection.test.sh, который исполняет присланное ровно как это сделал бы мак.
#
# Теперь оболочке на маке разбирать нечего: команда фиксированная, без подстановок, а тело
# приходит на стандартный ввод. Ключ -n снят намеренно — он стоял, чтобы вложенный ssh не
# съедал stdin цикла разбора вывода (из-за этого пропадала вторая заявка прогона). Теперь
# stdin у ssh занят трубой с телом, и до потока цикла он не дотягивается.
gate() {  # $1 — json тела заявки
  printf '%s' "$1" | ssh "${OPTS[@]}" "$HOST" \
    "curl -sS --max-time 12 -X POST -H 'content-type: application/json' --data-binary @- $GATE/register" 2>/dev/null
}

# Сердце метки: фоновый цикл на маке трогает её раз в полминуты и сам умирает, когда
# кончается прогон (kill -0 по родительской оболочке). Продлевать метку из контейнера
# нельзя — каждый удар стоил бы отдельного захода через реле.
#
# Имя переменной латиницей обязательно: кириллическое bash за имя не считает и исполняет
# присваивание как команду. Первая версия этой строки называлась по-русски и не запускалась
# ни разу — прогон работал, а метка не продлевалась. Держится tests/shell-identifiers.sh.
HEARTBEAT="( while kill -0 \$\$ 2>/dev/null; do touch /tmp/agchrome-keep.$PORT; sleep 30; done ) >/dev/null 2>&1 &"

cat "$GC" "$DIR/prelude.js" "$1" \
  | ssh "${OPTS[@]}" "$HOST" \
      "export PATH=\$HOME/.npm-global/bin:\$PATH; $HEARTBEAT dev-browser --connect http://127.0.0.1:$PORT --timeout $T" \
  | while IFS= read -r line; do
      printf '%s\n' "$line"
      case "$line" in
        "ЗАСТРЯЛА "*)
          rest="${line#ЗАСТРЯЛА }"
          tgt="${rest%% *}"          # идентификатор вкладки идёт первым: адрес бывает с пробелами
          rest="${rest#* }"
          url="${rest%% :: *}"
          why="${rest#* :: }"
          # Тело собирает и проверяет отдельный файл: он покрыт тестом, а склейка прямо здесь
          # покрыта не была. Поля не прошли проверку — заявку не шлём: разбирается ЛЮБАЯ строка
          # вывода прогона, и текст со страницы, начинающийся с этого же слова, доехал бы сюда
          # наравне с настоящим зовом о помощи.
          if body="$(bash "$DIR/claim-body.sh" "$tgt" "$url" "$why")"; then
            echo "ЧЕЛОВЕК НУЖЕН: $(gate "$body")"
          else
            echo "заявка не отправлена: строка не похожа на зов о помощи"
          fi
          ;;
        "ПРОШЛА "*)
          rest="${line#ПРОШЛА }"
          tgt="${rest%% *}"
          url="${rest#* }"
          if body="$(bash "$DIR/claim-body.sh" "$tgt" "$url" --снять)"; then
            gate "$body" >/dev/null
            echo "заявка снята"
          else
            echo "снятие не отправлено: строка не похожа на снятие заявки"
          fi
          ;;
      esac
    done
