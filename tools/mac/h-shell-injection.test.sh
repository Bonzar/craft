#!/usr/bin/env bash
# Тест: адрес страницы не может выполнить команду на маке.
#
# Запуск: bash tools/mac/h-shell-injection.test.sh
# Ни мака, ни сети не нужно — ssh подменяется заглушкой.
#
# ЧТО ИМЕННО ВОСПРОИЗВОДИТСЯ. Ревью безопасности нашло в h.sh исполнение команд на маке
# через адрес открытой страницы. Тело заявки вставлялось в ТЕКСТ команды, уходящей по ssh,
# внутрь одинарных кавычек и не экранировалось. Одинарная кавычка в адресе закрывала эту
# кавычку, и остаток строки удалённая оболочка исполняла как свои команды — от имени учётки
# агента, у которой общий профиль Chrome со всеми логинами и выходной узел в домашнюю сеть.
#
# Кавычка в адресе не выдумка: Chromium кодирует её в строке запроса, но не в пути и не во
# фрагменте, и там же выживают «;», «$», «|» и «&». Страница ставит себе такой адрес сама.
#
# Проверка честная — она ИСПОЛНЯЕТ то, что h.sh отдал бы удалённой оболочке, ровно как это
# сделал бы sshd, и смотрит, появился ли файл-улика. Проверять глазами текст команды было бы
# слабее: признак должен различать исходы, а «в строке нет кавычки» и «команда не выполнилась»
# — разные утверждения.
set -u
cd "$(dirname "$0")/../.." || exit 1
export LC_ALL=C.UTF-8

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

STUB="$WORK/stub"
mkdir -p "$STUB"

# Заглушка ssh: ведёт себя как sshd — берёт последний аргумент и исполняет его оболочкой.
# Вызов с прогоном скрипта отличаем по dev-browser: вместо браузера печатаем одну строку
# зова о помощи с враждебным адресом, будто её напечатал скрипт, работающий на живом сайте.
cat > "$STUB/ssh" <<'STUBSSH'
#!/usr/bin/env bash
for arg in "$@"; do cmd="$arg"; done
case "$cmd" in
  *dev-browser*)
    cat >/dev/null                      # проглатываем текст скрипта, как это сделал бы браузер
    printf '%s\n' "ЗАСТРЯЛА $FAKE_TGT $FAKE_URL :: капча"
    ;;
  *)
    printf '%s\n' "$cmd" >> "$WORK/remote-commands.log"
    PATH="$STUB:$PATH" bash -c "$cmd" </dev/stdin
    ;;
esac
STUBSSH
chmod +x "$STUB/ssh"

# Заглушка curl: отвечает как пульт капчи и записывает то, что получил телом.
cat > "$STUB/curl" <<'STUBCURL'
#!/usr/bin/env bash
prev=""
for arg in "$@"; do
  [ "$prev" = "-d" ] && printf '%s\n' "$arg" >> "$WORK/bodies.log"
  [ "$arg" = "@-" ] && cat >> "$WORK/bodies.log"
  prev="$arg"
done
printf '%s\n' '{"ссылка":"https://узел:8443/c/тест"}'
STUBCURL
chmod +x "$STUB/curl"

: > "$WORK/script.js"

прогон() {  # $1 — адрес страницы, который «вернул» браузер
  rm -f "$WORK/ВЗЛОМАНО" "$WORK/bodies.log" "$WORK/remote-commands.log"
  PATH="$STUB:$PATH" WORK="$WORK" STUB="$STUB" \
    FAKE_TGT="AA7F5D77FF440B420D54DB245879373A" FAKE_URL="$1" \
    MAC_NODE_ADDR="127.0.0.1" \
    bash tools/mac/h.sh "$WORK/script.js" >/dev/null 2>&1
}

ok=0
fail=0
проверка() {  # $1 — имя, $2 — «да», если файл-улика должен отсутствовать
  if [ -e "$WORK/ВЗЛОМАНО" ]; then
    echo "FAIL   $1 — команда из адреса ВЫПОЛНИЛАСЬ на удалённой стороне"
    fail=$((fail+1))
  else
    echo "PASS   $1"
    ok=$((ok+1))
  fi
}

# Полезная нагрузка: закрыть кавычку -d '…', выполнить своё, снова открыть кавычку.
прогон "https://evil.example/x#a';touch \$WORK/ВЗЛОМАНО;'b"
проверка "адрес страницы с одинарной кавычкой выполнял команды на маке"

прогон "https://evil.example/x#\$(touch \$WORK/ВЗЛОМАНО)"
проверка "подстановка команды в адресе не исполняется"

прогон "https://evil.example/x#a\`touch \$WORK/ВЗЛОМАНО\`b"
проверка "обратные кавычки в адресе не исполняются"

# Заявка обязана при этом РАБОТАТЬ: проверка, которая просто всё ломает, ничего не доказывает.
прогон "https://www.iana.org/about"
if [ -s "$WORK/bodies.log" ] && grep -q "iana.org" "$WORK/bodies.log"; then
  echo "PASS   обычная заявка по-прежнему доезжает до пульта"
  ok=$((ok+1))
else
  echo "FAIL   обычная заявка не доехала — тело пустое или без адреса"
  fail=$((fail+1))
fi

echo "---------------------------------------------------------------------------"
echo "H-SHELL-INJECTION: $ok/$((ok + fail)) passed; $fail failed"
[ "$fail" -eq 0 ]
