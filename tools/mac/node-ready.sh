#!/usr/bin/env bash
# Готовность узла в сети Tailscale: дождаться мака и назвать его адрес.
#
# Вынесено из tools/mac-tunnel.sh отдельным файлом, чтобы решение можно было проверить
# тестом: раньше оно лежало в середине скрипта канала и проверить его там было нечем.
#
# ТРИ ДЕФЕКТА, КОТОРЫЕ ЭТОТ ФАЙЛ ЗАКРЫВАЕТ. Скрипт канала объявлял «узла нет в сети» на
# полностью исправном контуре, и причин было три, наложенных друг на друга:
#
#  1. Он смотрел список узлов ОДИН раз сразу после входа. Карта сети приходит с задержкой —
#     секундой позже узел на месте. Признак не различал исходы: «нет в списке прямо сейчас»
#     одинаково выглядит и когда ноут выключен, и когда карта ещё не доехала.
#  2. Он искал узел по значению из окружения, а там лежит ПОЛНОЕ доменное имя. В текстовом
#     списке узел значится коротким именем, и поиск не находил его никогда.
#  3. Он передавал то же полное имя как выходной узел, а клиент такое не принимает:
#     «must be IP or unique node name». Вход из-за этого не выполнялся вовсе — и скрипт
#     винил ключ, хотя ключ был рабочий.
#
# Поэтому узел ищется в машинном выводе клиента и по любому из трёх обличий — полное имя,
# короткое имя, адрес, — а наружу отдаётся именно адрес: его клиент принимает без споров.
#
# Usage: node-ready.sh <клиент-tailscale> <узел: имя или адрес>
#   exit 0 — на stdout «готов <адрес-узла>»
#   exit 1 — на stdout слово-причина: «нет-входа» либо «нет-узла»
#
# NODE_READY_LIMIT — предел ожидания в секундах (по умолчанию 45).
set -u

TS="${1-}"
NODE="${2-}"
LIMIT="${NODE_READY_LIMIT:-45}"
STEP=3

# Разбор машинного вывода: печатает адрес узла, если он в сети и годится выходным.
# Слово «вышел» — про то, что клиент вообще не вошёл в сеть.
разобрать() {
  NODE="$NODE" python3 -c '
import json, os, sys
try:
    d = json.load(sys.stdin)
except Exception:
    sys.exit(0)                      # клиент ещё не отвечает машинно — ждём дальше
if d.get("BackendState") in ("NeedsLogin", "NoState"):
    print("вышел"); sys.exit(0)
хотим = os.environ["NODE"].rstrip(".")
for p in (d.get("Peer") or {}).values():
    имя = (p.get("DNSName") or "").rstrip(".")
    обличья = {имя, имя.split(".")[0], p.get("HostName") or ""} | set(p.get("TailscaleIPs") or [])
    if хотим in обличья and p.get("Online"):
        for ip in (p.get("TailscaleIPs") or []):
            if ":" not in ip:        # берём IPv4: его понимают и клиент, и ssh
                print(ip); sys.exit(0)
'
}

started=$(date +%s)
last=""
while :; do
  last="$("$TS" status --json 2>/dev/null | разобрать)"
  case "$last" in
    ""|вышел) ;;                     # ещё не готов — ждём, «вышел» тоже переходное состояние
    *) echo "готов $last"; exit 0 ;;
  esac

  now=$(date +%s)
  [ $(( now - started )) -ge "$LIMIT" ] && break
  sleep "$STEP"  # timed-wait: карта сети приходит асинхронно, событием её не дождаться
done

# Вердикт ставится ТОЛЬКО по исчерпании ожидания. Состояние «не вошёл» держится до конца —
# значит ключ и правда не принят; иначе ноут спит или выключен.
[ "$last" = "вышел" ] && { echo "нет-входа"; exit 1; }
echo "нет-узла"
exit 1
