// Решение по ключу пульта капчи: что отдать на запрос с этим ключом.
//
// Вынесено из capgate.js отдельным файлом, чтобы решение можно было проверить тестом.
// Сам пульт в контейнере не поднять — на старте он тянет playwright маковским путём и
// выходит без адреса фронта, — а здесь нет ни сети, ни браузера, только чистая функция.
//
// Три исхода различаются НАМЕРЕННО и это главное свойство файла: раньше «Проверка
// пройдена» отдавалась и когда проверка пройдена, и когда вкладка закрылась, и когда ключ
// пульту вообще неизвестен. Человек получал зелёный экран успеха на ссылку, которая просто
// не пережила перезапуск службы.
"use strict";

// Ручки, которые у мёртвого ключа не молчат, а называют причину: по ней уже открытая
// страница выбирает свой финальный экран вместо умолчательного.
const РУЧКИ_ПРИЧИНЫ = ["/state", "/watch"];

// Ручки, которые пауза не блокирует. Пауза — это «человек вернул управление агенту»:
// трансляция погашена, но узнать состояние, дождаться события, вернуть себе управление и
// перезагрузить вкладку по-прежнему можно. Блокируется только то, что показывает вкладку
// или двигает её.
const ПАУЗА_ПРОПУСКАЕТ = ["/state", "/watch", "/stop", "/resume", "/reload"];

/**
 * @param {null|{погашен?: string, пауза?: boolean}} запись — состояние ключа; null, если
 *        пульт такого ключа не знает. Поле «погашен» несёт причину: "пройдена" | "закрылась".
 * @param {string} ручка — служебный хвост адреса ("/state", "/frame", …) или "" для самой страницы.
 * @returns {{вид: string, код?: number, экран?: string, причина?: string}}
 *   вид "экран"   — отдать страницу: "пульт" (рабочая) либо финальный экран;
 *   вид "причина" — ответить причиной смерти ключа;
 *   вид "отказ"   — код без тела;
 *   вид "дальше"  — ключ живой, работает обычный обработчик ручки.
 */
function исход(запись, ручка) {
  const служебная = !!ручка;

  // Ключа пульт не знает. Это НЕ успех: так выглядит и ссылка, не пережившая перезапуск
  // службы, и просто очень старая. Причина называется своим словом, а не чужим.
  if (!запись) {
    if (РУЧКИ_ПРИЧИНЫ.indexOf(ручка) !== -1) return { вид: "причина", причина: "не-действует" };
    return служебная ? { вид: "отказ", код: 410 } : { вид: "экран", экран: "не-действует" };
  }
  if (запись.погашен) {
    if (РУЧКИ_ПРИЧИНЫ.indexOf(ручка) !== -1) return { вид: "причина", причина: запись.погашен };
    // Всё остальное у погашенного ключа обрублено: утёкшая ссылка не должна ни показывать
    // чужую вкладку, ни двигать её.
    if (служебная) return { вид: "отказ", код: 410 };
    return { вид: "экран", экран: запись.погашен };
  }
  if (!служебная) return { вид: "экран", экран: "пульт" };
  if (запись.пауза && ПАУЗА_ПРОПУСКАЕТ.indexOf(ручка) === -1) return { вид: "отказ", код: 409 };
  return { вид: "дальше" };
}

module.exports = { исход, РУЧКИ_ПРИЧИНЫ, ПАУЗА_ПРОПУСКАЕТ };
