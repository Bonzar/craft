#!/usr/bin/env bash
# Сборка тела заявки в пульт капчи.
#
# Вынесено из h.sh отдельным файлом, чтобы сборку можно было проверить тестом: раньше она
# жила прямо в строке удалённой команды, и проверить её там было нечем.
#
# ЗАЧЕМ. Ревью безопасности нашло исполнение команд на маке через адрес страницы. Тело
# заявки склеивалось кавычками и вставлялось в ТЕКСТ команды, уходящей по ssh удалённой
# оболочке. Одинарная кавычка в адресе закрывала кавычку команды, и остаток оболочка
# исполняла как свои команды — от имени учётки агента, у которой общий профиль Chrome со
# всеми логинами и выходной узел в домашнюю сеть. Кавычка в адресе не выдумка: Chromium
# кодирует её в строке запроса, но не в пути и не во фрагменте, и там же выживают «;»,
# «$», «|» и «&».
#
# Главную дыру закрывает h.sh: тело больше не попадает в текст команды, а уходит отдельным
# потоком. Здесь два оставшихся слоя:
#   1) тело собирает настоящий кодировщик, а не склейка кавычками — тогда любой символ
#      внутри полей остаётся данными. Прежняя склейка ломала заявку и без злого умысла:
#      одной двойной кавычки в поводе хватало, чтобы тело перестало быть JSON;
#   2) поля проверяются, и негодная заявка не уходит вовсе. Это закрывает ВТОРОЙ путь атаки:
#      h.sh разбирает любую строку вывода прогона и не знает, откуда она взялась, — значит
#      текст со страницы, напечатанный скриптом и начинающийся со слова-маркера, доехал бы
#      до пульта наравне с настоящим зовом о помощи.
#
# Usage: claim-body.sh <идентификатор-вкладки> <адрес> <повод>
#        claim-body.sh <идентификатор-вкладки> <адрес> --снять
#   stdout — тело заявки, exit 0
#   stderr — причина отказа, exit 1
set -u

ID="${1-}"
URL="${2-}"
WHY="${3-}"

# Перевод строки отсекаем ПЕРВЫМ и отдельно. grep смотрит построчно: у двухстрочного адреса
# он проверит первую строку, найдёт в ней законную ссылку и пропустит всё остальное — то есть
# признак не различал бы исходы. Замерено: «https://example.com/a\nЗАСТРЯЛА подделка»
# проходило шаблон ссылки целиком.
for field in "$ID" "$URL"; do
  if [ "$(printf '%s' "$field" | wc -l)" -ne 0 ]; then
    echo "claim-body: перевод строки в поле заявки" >&2
    exit 1
  fi
done

# Идентификатор вкладки Chrome — шестнадцатеричный. Ничто другое в это поле не попадает.
if ! printf '%s' "$ID" | grep -qE '^[0-9A-Fa-f]{8,64}$'; then
  echo "claim-body: идентификатор вкладки не шестнадцатеричный: $ID" >&2
  exit 1
fi

# Адрес — только http и https, без пробелов. Это и есть отсечка для строки, сочинённой самой
# страницей: у настоящего зова о помощи адрес всегда такой.
if ! printf '%s' "$URL" | grep -qE '^https?://[^[:space:]]+$'; then
  echo "claim-body: адрес не похож на ссылку: $URL" >&2
  exit 1
fi

# Поля отдаём питону ОКРУЖЕНИЕМ, а не аргументами командной строки: так они не проходят ни
# через одну подстановку по дороге.
if [ "$WHY" = "--снять" ]; then
  ID="$ID" URL="$URL" python3 -c '
import json, os
print(json.dumps({"цель": os.environ["ID"], "адрес": os.environ["URL"], "снять": True},
                 ensure_ascii=False))'
else
  ID="$ID" URL="$URL" WHY="${WHY:-нужна помощь}" python3 -c '
import json, os
print(json.dumps({"цель": os.environ["ID"], "адрес": os.environ["URL"], "повод": os.environ["WHY"]},
                 ensure_ascii=False))'
fi
