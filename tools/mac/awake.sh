#!/bin/bash
# Сторож круглосуточной доступности мака.
#
# Задача: мак стоит закрытым, с потухшим экраном и запертой сессией, и при этом доступен
# облачным сессиям — через него идёт домашний выход в интернет, на нём живут браузер под
# управлением сессий и пульт капчи.
#
# Правило простое: пока есть сеть И (мак на питании ИЛИ заряд выше порога) — спать
# запрещено. Иначе запрет снимается и мак засыпает штатно.
#
# Почему запрет, а не Amphetamine: тот снимает засыпание ПО ПРОСТОЮ, а мак уходил
# «Maintenance Sleep» — обслуживающим сном системы, на который такая заявка не влияет
# (замерено в журнале pmset: Entering Sleep state due to 'Maintenance Sleep' на зарядке
# при 100% заряда). Запрет сна снимает и его, и засыпание по закрытой крышке.
#
# Почему плановое пробуждение, а не пробуждение по сети: разбудить спящий мак может
# только обращение ИЗ ЛОКАЛЬНОЙ сети через посредника сна (в домашней сети такой есть —
# Apple TV). Облачная сессия приходит из интернета, до посредника не достаёт и разбудить
# мак не может. Поэтому, засыпая из-за пропавшей сети, сторож заранее назначает себе
# пробуждение — мак сам просыпается и проверяет, вернулась ли сеть.
#
# Запускается системным заданием do.craft.awake.plist раз в минуту. От имени root:
# запрет сна и плановое пробуждение — системные настройки.
set -u
PATH=/usr/bin:/bin:/usr/sbin:/sbin:/usr/local/bin:/opt/homebrew/bin
export PATH

ПОРОГ=30            # процент заряда, ниже которого без питания мак спит по-настоящему
ОКНО_СНА=15         # через столько минут просыпаемся проверить, вернулась ли сеть
ПОРТ_ФРОНТА=8443    # внешний порт tailscale serve — с него открываются ссылки пульта
ПОРТ_ПУЛЬТА=8899    # локальный слушатель пульта капчи
МЕТКА=/var/run/craft-awake.wake   # время назначенного нами пробуждения

лог() { echo "$(date '+%F %T') $*"; }

# --- сеть -------------------------------------------------------------------------------
# Маршрут по умолчанию сам по себе ничего не значит: он остаётся и когда Wi-Fi
# ассоциирован, а роутер лежит. Поэтому маршрут плюс живой шлюз.
есть_сеть() {
  local шлюз
  шлюз="$(route -n get default 2>/dev/null | awk '/gateway:/{print $2}')"
  [ -n "$шлюз" ] || return 1
  ping -c 1 -t 3 "$шлюз" >/dev/null 2>&1
}

# --- питание ----------------------------------------------------------------------------
на_питании() { pmset -g batt 2>/dev/null | grep -q "AC Power"; }
заряд() { pmset -g batt 2>/dev/null | grep -o '[0-9]\{1,3\}%' | head -1 | tr -d '%'; }

# --- канал ------------------------------------------------------------------------------
TS="$(command -v tailscale || echo /usr/local/bin/tailscale)"

# Фронт пульта объявлен на ИМЕНИ узла, и переименование его не переносит: после смены
# имени старая запись остаётся жить, а ссылки минтятся с новым именем и ведут в никуда —
# ровно на этом контур и встал. Сверяем объявленное с текущим именем.
чинить_канал() {
  "$TS" status >/dev/null 2>&1 || { "$TS" up >/dev/null 2>&1 && лог "узел поднят заново"; }

  local имя фронт
  # --peers=false обязателен: в полном выводе DNSName есть у каждого соседа, и без него
  # имя пришлось бы угадывать по порядку полей.
  имя="$("$TS" status --self --peers=false --json 2>/dev/null \
        | sed -n 's/.*"DNSName"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)"
  имя="${имя%.}"
  [ -n "$имя" ] || return 0          # имени нет — сеть ещё не поднялась, чинить нечего

  фронт="$("$TS" serve status 2>/dev/null)"
  case "$фронт" in
    *"$имя"*) return 0 ;;
  esac
  # Снимаем всё и объявляем заново: снять точечно нельзя — старую запись демон опознаёт
  # по её собственному имени, которого у узла уже нет, и отказывает.
  "$TS" serve reset >/dev/null 2>&1
  "$TS" serve --bg --https="$ПОРТ_ФРОНТА" "http://127.0.0.1:$ПОРТ_ПУЛЬТА" >/dev/null 2>&1 \
    && лог "фронт пульта переобъявлен под текущим именем узла"
}

# --- плановое пробуждение ---------------------------------------------------------------
# Отменяем ТОЛЬКО своё событие, по записанному времени: cancelall снёс бы и события Влада.
снять_пробуждение() {
  [ -f "$МЕТКА" ] || return 0
  pmset schedule cancel wake "$(cat "$МЕТКА")" >/dev/null 2>&1
  rm -f "$МЕТКА"
}

назначить_пробуждение() {
  [ -f "$МЕТКА" ] && return 0        # уже назначено — второе не нужно
  local когда
  когда="$(date -v "+${ОКНО_СНА}M" '+%m/%d/%y %H:%M:%S')"
  if pmset schedule wake "$когда" >/dev/null 2>&1; then
    echo "$когда" > "$МЕТКА"
    лог "сети нет — просыпаемся проверить её в $когда"
  fi
}

# --- решение ----------------------------------------------------------------------------
з="$(заряд)"; [ -n "$з" ] || з=100   # заряда не видно — считаем, что питание есть

if есть_сеть && { на_питании || [ "$з" -gt "$ПОРОГ" ]; }; then
  pmset -a disablesleep 1 >/dev/null 2>&1
  снять_пробуждение
  чинить_канал
elif на_питании || [ "$з" -gt "$ПОРОГ" ]; then
  # Работать есть на чём, но сети нет: спим и возвращаемся сами.
  pmset -a disablesleep 0 >/dev/null 2>&1
  назначить_пробуждение
else
  # Заряд на исходе и питания нет — единственный случай настоящего сна без возврата:
  # будить себя по будильнику значило бы доедать остаток батареи. Мак проснётся, когда
  # его подключат к питанию.
  pmset -a disablesleep 0 >/dev/null 2>&1
  снять_пробуждение
  лог "заряд $з% без питания — уходим в сон до подключения питания"
fi
