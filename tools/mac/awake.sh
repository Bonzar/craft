#!/bin/bash
# Сторож круглосуточной доступности мака.
#
# Задача: мак стоит закрытым, с потухшим экраном и запертой сессией, и при этом доступен
# облачным сессиям — через него идёт домашний выход в интернет, на нём живут браузер под
# управлением сессий и пульт капчи.
#
# Правило: пока мак доступен — сон запрещён целиком, включая закрытую крышку. Доступности
# нет и мак на питании — тоже не спим, экономить нечего. Доступности нет и мак на батарее —
# отпускаем систему в сон и назначаем себе пробуждение, чтобы вернуться самим.
#
# Что считается доступностью. Не живой шлюз: за формой входа в гостиничный Wi-Fi и на
# раздаче с телефона без мобильного интернета шлюз отвечает, а до нас не дойти. Считаем
# доступностью то, чем сессия и приходит, — виден ли узел контрольному серверу тейлнета.
# ОСТОРОЖНО, не проверено: залипает ли этот признак за формой входа, показывая последнее
# удачное состояние. Пока не замерено — это известная дыра, а не гарантия.
#
# Почему запрет сна, а не Amphetamine: тот снимает засыпание ПО ПРОСТОЮ, а мак уходил
# «Maintenance Sleep» — обслуживающим сном системы, на который такая заявка не влияет
# (в журнале pmset: Entering Sleep state due to 'Maintenance Sleep' на зарядке при 100%
# заряда). Что причина именно в Power Nap — предположение: журнал пишет факт входа, не
# причину. Запрет сна снимает засыпание независимо от того, кто его инициировал.
#
# Почему будильник, а не пробуждение по сети: разбудить спящий мак может только обращение
# ИЗ ЛОКАЛЬНОЙ сети через посредника сна. Облачная сессия приходит из интернета, до
# посредника не достаёт. Будильник же — часы самой машины, сети ему не нужно никакой,
# поэтому возврат работает на любой сети, а не только дома. Не проверено: просыпается ли
# мак по будильнику с закрытой крышкой и на батарее.
#
# Имена в коде латиницей: системный bash на маке — 3.2, кириллические идентификаторы он не
# принимает вовсе («ПОРОГ=30: command not found»). Комментарии и сообщения журнала это не
# трогает.
#
# Запускается системным заданием do.craft.awake.plist раз в минуту. От имени root: запрет
# сна и плановое пробуждение — системные настройки.
set -u
PATH=/usr/bin:/bin:/usr/sbin:/sbin:/usr/local/bin:/opt/homebrew/bin
export PATH

LIMIT=30            # процент заряда, ниже которого без питания мак спит по-настоящему
LOOKAROUND=180      # секунд бодрствования после планового пробуждения: Wi-Fi поднимается
                    # не мгновенно, и одной проверки на подъём не хватило бы
FRONT_PORT=8443     # внешний порт tailscale serve — с него открываются ссылки пульта
PULT_PORT=8899      # локальный слушатель пульта капчи

# Состояние между запусками. /var/run очищается перезагрузкой — это и нужно: после неё
# лесенка начинается заново.
ALARM=/var/run/craft-awake.wake     # время назначенного НАМИ пробуждения: первой строкой в
                                    # виде для pmset, второй — то же в секундах эпохи.
                                    # Сравнивать нужно секундами: строка «08/09/26» лежит
                                    # раньше «12/31/25» по алфавиту, но позже по времени
STEP=/var/run/craft-awake.step      # номер ступени лесенки пауз
UNTIL=/var/run/craft-awake.grace    # до какого момента держим бодрость после подъёма

log() { echo "$(date '+%F %T') $*"; }

# --- доступность ------------------------------------------------------------------------
TS="$(command -v tailscale || echo /usr/local/bin/tailscale)"

visible() {
  local j
  j="$("$TS" status --self --peers=false --json 2>/dev/null)" || return 1
  case "$j" in *'"BackendState": "Running"'*) ;; *) return 1 ;; esac
  case "$j" in *'"Online": true'*) ;; *) return 1 ;; esac
  return 0
}

# Перед вердиктом «доступности нет» — одна попытка поднять узел: сбитая настройка не должна
# выглядеть пропавшей сетью. Предел ожидания обязателен: без него зависшая попытка съела бы
# минутный такт задания целиком. Флагов не передаём — тогда клиент сохраняет текущие
# настройки, включая объявление мака выходным узлом (проверено чтением: AdvertiseRoutes
# держит 0.0.0.0/0 и ::/0).
reachable() {
  visible && return 0
  "$TS" up --timeout=20s >/dev/null 2>&1
  visible
}

# --- питание ----------------------------------------------------------------------------
on_power() { pmset -g batt 2>/dev/null | grep -q "AC Power"; }
charge() { pmset -g batt 2>/dev/null | grep -o '[0-9]\{1,3\}%' | head -1 | tr -d '%'; }

# --- канал ------------------------------------------------------------------------------
# Фронт пульта объявлен на ИМЕНИ узла, и переименование его не переносит: после смены имени
# старая запись остаётся жить, а ссылки минтятся с новым именем и ведут в никуда — ровно на
# этом контур и встал. Сверяем объявленное с текущим именем.
fix_front() {
  local name front
  # --peers=false обязателен: в полном выводе DNSName есть у каждого соседа, и без него имя
  # пришлось бы угадывать по порядку полей.
  name="$("$TS" status --self --peers=false --json 2>/dev/null \
        | sed -n 's/.*"DNSName"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)"
  name="${name%.}"
  [ -n "$name" ] || return 0

  front="$("$TS" serve status 2>/dev/null)"
  case "$front" in
    *"$name"*) return 0 ;;
  esac
  # Снимаем всё и объявляем заново: снять точечно нельзя — старую запись демон опознаёт по
  # её собственному имени, которого у узла уже нет, и отказывает.
  "$TS" serve reset >/dev/null 2>&1
  "$TS" serve --bg --https="$FRONT_PORT" "http://127.0.0.1:$PULT_PORT" >/dev/null 2>&1 \
    && log "фронт пульта переобъявлен под текущим именем узла"
}

# --- лесенка пауз -------------------------------------------------------------------------
# 5, 10, дальше по 15 минут. Смена сети ловится быстро, а долгий простой без сети не съедает
# батарею подъёмами: в устойчивом режиме это три минуты бодрствования на восемнадцать.
step_minutes() {
  case "${1:-1}" in
    1) echo 5 ;;
    2) echo 10 ;;
    *) echo 15 ;;
  esac
}

# Отменяем ТОЛЬКО своё событие, по записанному времени: cancelall снёс бы и события Влада.
drop_alarm() {
  [ -f "$ALARM" ] || return 0
  pmset schedule cancel wake "$(head -1 "$ALARM")" >/dev/null 2>&1
  rm -f "$ALARM"
}

reset_ladder() { rm -f "$STEP" "$UNTIL"; }

set_alarm() {
  local n mins when
  n="$(cat "$STEP" 2>/dev/null || echo 1)"
  mins="$(step_minutes "$n")"
  when="$(date -v "+${mins}M" '+%m/%d/%y %H:%M:%S')"
  if pmset schedule wake "$when" >/dev/null 2>&1; then
    printf '%s\n%s\n' "$when" "$(( $(date +%s) + mins * 60 ))" > "$ALARM"
    log "доступности нет — шаг $n, просыпаемся через $mins мин в $when"
  fi
}

# --- решение ------------------------------------------------------------------------------
pct="$(charge)"; [ -n "$pct" ] || pct=100   # заряда не видно — считаем, что питание есть

if reachable; then
  pmset -a disablesleep 1 >/dev/null 2>&1
  drop_alarm; reset_ladder
  fix_front

elif on_power; then
  # Питание есть — спать незачем даже без доступности: бодрый мак заметит вернувшуюся сеть
  # на ближайшей проверке вместо ожидания будильника. Лесенка сбрасывается, иначе после
  # долгого простоя первое же отключение от розетки стартовало бы сразу с пятнадцати минут.
  pmset -a disablesleep 1 >/dev/null 2>&1
  drop_alarm; reset_ladder

elif [ "$pct" -le "$LIMIT" ]; then
  # Заряд на исходе и питания нет — единственный случай настоящего сна без возврата: будить
  # себя по будильнику значило бы доедать остаток батареи. Мак проснётся, когда его
  # подключат к питанию.
  pmset -a disablesleep 0 >/dev/null 2>&1
  drop_alarm; reset_ladder
  log "заряд $pct% без питания — уходим в сон до подключения питания"

else
  # Батарея, заряда хватает, доступности нет: спим и возвращаемся сами.
  # Если время нашего будильника уже позади — значит мы по нему и проснулись: открываем
  # окно, чтобы Wi-Fi успел подключиться, и двигаем ступень.
  if [ -f "$ALARM" ] && [ "$(date +%s)" -ge "$(sed -n 2p "$ALARM")" ]; then
    rm -f "$ALARM"
    echo "$(( $(cat "$STEP" 2>/dev/null || echo 1) + 1 ))" > "$STEP"
    echo "$(( $(date +%s) + LOOKAROUND ))" > "$UNTIL"
    log "проснулись по будильнику — осматриваемся $((LOOKAROUND / 60)) мин"
  fi

  if [ -f "$UNTIL" ] && [ "$(date +%s)" -lt "$(cat "$UNTIL")" ]; then
    pmset -a disablesleep 1 >/dev/null 2>&1   # окно осмотра: не даём заснуть раньше времени
  else
    rm -f "$UNTIL"
    pmset -a disablesleep 0 >/dev/null 2>&1
    [ -f "$STEP" ] || echo 1 > "$STEP"
    [ -f "$ALARM" ] || set_alarm
  fi
fi
