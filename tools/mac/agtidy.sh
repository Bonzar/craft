#!/bin/bash
# Уборка браузеров агента: вкладки копятся за сессию, а лишние профили остаются висеть
# после опытов. Без уборки мак постепенно забивается окнами и памятью.
#
# Что делает:
#  1. В постоянных профилях оставляет по одной вкладке, остальные закрывает. Страница
#     проверки-капчи неприкосновенна — её как раз и решает Влад с пульта.
#  2. Профили вне постоянного списка гасит целиком.
#
# ЗАКРЫВАЕТСЯ ТОЛЬКО ЗАКОНЧЕННАЯ РАБОТА. Незаконченность видна двумя признаками, и любого
# из них хватает, чтобы вкладку не трогать:
#  — живая заявка в пульте капчи: человек ещё не пришёл её решать. Сколько бы времени ни
#    прошло, это не повод закрывать — работа стоит и ждёт именно его;
#  — свежая метка занятости профиля: прогон сессии жив прямо сейчас. Метку он продлевает,
#    пока работает, поэтому многочасовая работа защищена так же, как минутная.
# Раньше метка ставилась один раз на старте и считалась протухшей через полчаса — работа
# дольше получаса переставала защищать вкладки, а заявленная вкладка с обычным адресом не
# была защищена вовсе.
#
# Вкладками рулим через http-ручки отладки (/json/list, /json/close) — без websocket и
# без сторонних модулей. Процессы гасим ТОЛЬКО по найденному номеру, не по маске.
#
# Имена ПЕРЕМЕННЫХ латиницей: кириллическое имя bash за имя не считает — присваивание
# исполняется как попытка запустить команду («оставить=0: command not found»), а «for перем
# in» падает «not a valid identifier». Имена ФУНКЦИЙ он при этом принимает, и в этом файле
# они русские намеренно. Именно эта разница обманывает: код выглядит однородным, а работает
# только половина. Держится проверкой tests/shell-identifiers.sh — она гоняется в сборке,
# потому что «bash -n» такую ошибку не видит, а сама поломка тихая.
set -u
KEEP_PORTS="9333 9303"
KEEP_DIRS="agprof agprof-pult1"
# Метка теперь бьётся сердцем прогона раз в полминуты, а не ставится однажды на старте.
# Поэтому окно короткое: две минуты означают «прогон жив прямо сейчас», а не «когда-то
# начинался». Долгая работа защищена ровно так же — она метку продлевает.
MARK_AGE_MIN=2
PULT="http://127.0.0.1:8899"

busy() {  # порт → жив ли прогон на этом профиле прямо сейчас
  f="/tmp/agchrome-keep.$1"
  [ -f "$f" ] || return 1
  [ -n "$(find "$f" -mmin -$MARK_AGE_MIN 2>/dev/null)" ]
}

# Вкладки с живыми заявками. Пульт недоступен — список пуст, и тогда единственной защитой
# остаётся метка занятости: молча закрыть заявленную вкладку хуже, чем оставить лишнюю.
заявленные_вкладки() {
  curl -s --max-time 5 "$PULT/pending" 2>/dev/null | /usr/bin/python3 -c '
import json, sys
try:
    print(" ".join(з.get("цель", "") for з in json.load(sys.stdin) if з.get("цель")))
except Exception:
    pass
' 2>/dev/null
}

CLAIMED="$(заявленные_вкладки)"

for port in $KEEP_PORTS; do
  if busy "$port"; then echo "$port: идёт работа, не трогаю"; continue; fi
  # Список вкладок отдаём питону через стандартный ввод: json большой и в аргумент
  # командной строки лезть не должен. Заявленные вкладки идут отдельным аргументом.
  ids="$(curl -s --max-time 5 "http://127.0.0.1:$port/json/list" 2>/dev/null | /usr/bin/python3 -c '
import json, sys
заявлены = set(sys.argv[1].split()) if len(sys.argv) > 1 else set()
try:
    tabs = [t for t in json.load(sys.stdin) if t.get("type") == "page"]
except Exception:
    sys.exit(0)
keep = set()
if tabs:
    keep.add(tabs[0]["id"])
for t in tabs:
    u = t.get("url", "")
    if "xpvnsulc" in u or "captcha" in u:
        keep.add(t["id"])
    # Живая заявка — работа не закончена, вкладка неприкосновенна.
    if t["id"] in заявлены:
        keep.add(t["id"])
print(" ".join(t["id"] for t in tabs if t["id"] not in keep))
' "$CLAIMED" 2>/dev/null)"
  n=0
  for id in $ids; do
    curl -s --max-time 4 "http://127.0.0.1:$port/json/close/$id" >/dev/null 2>&1 && n=$((n+1))
  done
  echo "$port: закрыто лишних вкладок — $n"
done

# Профили вне списка гасим целиком, по номеру процесса. Берём только головной процесс
# Chrome: у него в командной строке есть --user-data-dir и нет --type=.
for pid in $(pgrep -f "user-data-dir=/Users/agent/agprof" 2>/dev/null); do
  cmd="$(ps -o command= -p "$pid" 2>/dev/null)"
  case "$cmd" in *--type=*) continue ;; esac
  dir="$(echo "$cmd" | sed -n 's/.*user-data-dir=\/Users\/agent\/\([^ ]*\).*/\1/p')"
  [ -n "$dir" ] || continue
  keep=0
  for k in $KEEP_DIRS; do
    [ "$dir" = "$k" ] && keep=1
  done
  if [ "$keep" -eq 0 ]; then
    echo "гашу лишний профиль $dir (pid $pid)"
    kill "$pid" 2>/dev/null
  fi
done
echo "уборка закончена"
