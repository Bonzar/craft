// Тест решения по ключу пульта капчи.
//
// Запуск: node tools/mac/capgate-outcome.test.js
// Ни браузера, ни сети не нужно — проверяется чистая функция.
//
// Первый кейс носит имя инцидента, из которого вырос этот файл: разовая ссылка,
// выданная человеку, при первом же открытии показала «Проверка пройдена», хотя проверку
// никто не проходил — пульт перезапустился, реестр ключей потерялся, а неизвестный ключ
// отдавался страницей успеха.
"use strict";
const { исход } = require("./capgate-outcome");

const кейсы = [
  {
    имя: "разовая ссылка соврала, что проверка пройдена",
    запись: null, ручка: "",
    ждём: { вид: "экран", экран: "не-действует" },
  },
  {
    имя: "живой ключ отдаёт рабочую страницу пульта",
    запись: { пауза: false }, ручка: "",
    ждём: { вид: "экран", экран: "пульт" },
  },
  {
    имя: "погашенный пройденной проверкой отдаёт свой экран",
    запись: { погашен: "пройдена" }, ручка: "",
    ждём: { вид: "экран", экран: "пройдена" },
  },
  {
    имя: "погашенный закрытой вкладкой отдаёт свой экран",
    запись: { погашен: "закрылась" }, ручка: "",
    ждём: { вид: "экран", экран: "закрылась" },
  },
  {
    имя: "у погашенного ключа состояние называет причину",
    запись: { погашен: "закрылась" }, ручка: "/state",
    ждём: { вид: "причина", причина: "закрылась" },
  },
  {
    имя: "у погашенного ключа ожидание называет причину",
    запись: { погашен: "пройдена" }, ручка: "/watch",
    ждём: { вид: "причина", причина: "пройдена" },
  },
  {
    имя: "у погашенного ключа показ кадра обрублен",
    запись: { погашен: "пройдена" }, ручка: "/frame",
    ждём: { вид: "отказ", код: 410 },
  },
  {
    имя: "у неизвестного ключа состояние называет причину",
    запись: null, ручка: "/state",
    ждём: { вид: "причина", причина: "не-действует" },
  },
  {
    имя: "у неизвестного ключа показ кадра обрублен",
    запись: null, ручка: "/frame",
    ждём: { вид: "отказ", код: 410 },
  },
  {
    имя: "на паузе показ кадра отклоняется",
    запись: { пауза: true }, ручка: "/frame",
    ждём: { вид: "отказ", код: 409 },
  },
  {
    имя: "на паузе перезагрузка проходит",
    запись: { пауза: true }, ручка: "/reload",
    ждём: { вид: "дальше" },
  },
  {
    имя: "на паузе возврат управления агенту проходит",
    запись: { пауза: true }, ручка: "/resume",
    ждём: { вид: "дальше" },
  },
  {
    имя: "на паузе состояние проходит",
    запись: { пауза: true }, ручка: "/state",
    ждём: { вид: "дальше" },
  },
  {
    имя: "у живого ключа ввод доходит до обработчика",
    запись: { пауза: false }, ручка: "/input",
    ждём: { вид: "дальше" },
  },
];

let упало = 0;
for (const к of кейсы) {
  const было = исход(к.запись, к.ручка);
  const совпало = Object.keys(к.ждём).every((поле) => было[поле] === к.ждём[поле]);
  if (совпало) {
    console.log("PASS   " + к.имя);
  } else {
    упало++;
    console.log("FAIL   " + к.имя);
    console.log("       ждём:  " + JSON.stringify(к.ждём));
    console.log("       вышло: " + JSON.stringify(было));
  }
}
console.log("---------------------------------------------------------------------------");
console.log("TOTAL: " + (кейсы.length - упало) + "/" + кейсы.length + " passed; " + упало + " failed");
process.exit(упало ? 1 : 0);
