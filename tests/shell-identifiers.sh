#!/usr/bin/env bash
# Имена ПЕРЕМЕННЫХ в шелл-скриптах обязаны быть латиницей.
#
# Зачем проверка. Bash не создаёт переменную с не-ASCII именем вообще: строка
# «СЕРДЦЕ=…» исполняется как ПОПЫТКА ЗАПУСТИТЬ КОМАНДУ с таким именем и падает
# «command not found», а «for перем in …» — «not a valid identifier». При этом имена
# ФУНКЦИЙ bash принимает спокойно, и в этом репозитории они намеренно русские. Разница
# незаметная, и на ней я обжёгся трижды за один день: сначала сторож доступности мака,
# потом сердцебиение метки занятости в h.sh и список заявленных вкладок в agtidy.sh.
# Две последние поломки были тихими — скрипт продолжал работать, просто без защиты.
#
# «bash -n» этого не ловит: он разбирает синтаксис, а ошибка возникает при исполнении.
# Отсюда отдельный чек.
#
# Первая версия самого этого файла была написана кириллическими именами и потому не
# запустилась бы — держим правило и здесь.
#
# Usage: bash tests/shell-identifiers.sh
#   exit 0 — все имена переменных латиницей
#   exit 1 — найдено хотя бы одно не-ASCII имя, названы файл, строка и само имя
set -u
cd "$(dirname "$0")/.." || exit 1

# UTF-8-локаль: в ней символ виден символом, а не набором байт.
export LC_ALL=C.UTF-8

# Признак различает исходы: ищем заведомо существующее совпадение, а не отсутствие вывода
# на пустом файле — оно одинаково и при работающем -P, и при неподдерживаемом.
printf 'x\n' | grep -qP 'x' 2>/dev/null || { echo "нужен grep с поддержкой -P"; exit 1; }

# Формы, где bash требует настоящий идентификатор. Присваивание ищем только в позиции
# КОМАНДЫ (начало строки, после ; && || then do {) — иначе ловится любое «слово=» внутри
# строкового литерала.
PATTERNS=(
  '(?:^|;|&&|\|\||\bthen\b|\bdo\b|\{)\s*(?:export|local|declare|readonly|typeset)\s+[^\s=]*[^\x00-\x7F][^\s=]*='
  '(?:^|;|&&|\|\||\bthen\b|\bdo\b|\{)\s*[A-Za-z_]*[^\x00-\x7F][^\s=]*='
  '(?:^|;|&&|\|\||\bthen\b|\bdo\b|\{)\s*for\s+\S*[^\x00-\x7F]\S*\s+in\s'
  '(?:^|;|&&|\|\||\bthen\b|\bdo\b|\{)\s*read\s+(?:-\S+\s+)*\S*[^\x00-\x7F]\S*'
)

found=0
while IFS= read -r file; do
  for pattern in "${PATTERNS[@]}"; do
    while IFS= read -r hit; do
      [ -n "$hit" ] || continue
      # Комментарий не код: в нём кириллица законна и нужна.
      text="${hit#*:}"
      case "$(printf '%s' "${text#*:}" | sed 's/^[[:space:]]*//')" in "#"*) continue ;; esac
      echo "FAIL   $file:$hit"
      found=$((found + 1))
    done < <(grep -nP "$pattern" "$file" 2>/dev/null)
  done
done < <(find . -name '*.sh' -not -path './.git/*' | sort)

echo "---------------------------------------------------------------------------"
if [ "$found" -eq 0 ]; then
  echo "SHELL-IDENTIFIERS: имена переменных латиницей везде"
  exit 0
fi
echo "SHELL-IDENTIFIERS: не-ASCII имён переменных — $found. Bash такие не создаёт:"
echo "  присваивание падает «command not found», for и read — «not a valid identifier»."
echo "  Имена функций переименовывать не нужно, их bash принимает."
exit 1
