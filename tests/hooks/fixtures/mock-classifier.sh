#!/usr/bin/env bash
# Мок команды модели для тестов классификатора: печатает заданный env-ответ.
# MOCK_CLASSIFIER_ANSWER=fail — имитация недоступности (ненулевой выход).
# Каждый вызов оставляет файл-след (MOCK_CLASSIFIER_TRACE) с промптом вызова —
# промпт приходит на СТАНДАРТНЫЙ ВВОД и попадает в след целиком:
# кейсы «модель не зовётся» проверяют ОТСУТСТВИЕ следа, кейсы сериализации
# (MultiEdit, NotebookEdit) — что текст правки дошёл до промпта. Ответ хука
# в этих исходах одинаков, различает их только след.
#
# Вызовы ДОПИСЫВАЮТСЯ, а не перезаписывают друг друга: за одно событие
# классификатор зовут дважды (сперва на разрешение, потом на времянку), и при
# перезаписи в следе оставался бы только последний. Дифференциальной сверке
# версий нужна вся последовательность — иначе две версии, разошедшиеся на первом
# вызове и совпавшие на последнем, читаются как одинаковые.
# Промпт читается со стандартного ввода: аргументом командной строки он не
# пролезает — у одного аргумента в Linux потолок 128 КБ, а реестр одобренного
# на большом плане перерастает его, и вызов падает целиком.
prompt="$(cat)"
[[ -n "${MOCK_CLASSIFIER_TRACE:-}" ]] && printf '%s\n' "$prompt" >> "$MOCK_CLASSIFIER_TRACE" 2>/dev/null
[[ "${MOCK_CLASSIFIER_ANSWER:-}" == "fail" ]] && exit 1

# Задержка ответа: кейсам ожидания нужен разбор, заведомо более медленный, чем
# сверка. Без неё окно, в котором реестр ещё пуст, не успевает открыться, и кейс
# зеленел бы и на коде, который ничего не ждёт.
[[ -n "${MOCK_CLASSIFIER_DELAY:-}" ]] && sleep "$MOCK_CLASSIFIER_DELAY"

# Разбор плана в структуру отвечает не вердиктом, а JSON-ом, и общий дефолт
# «СООТВЕТСТВУЕТ» для него был бы неразборным ответом — то есть кейсы одобрения
# плана молча получали бы пустой разбор. Режим опознаётся по промпту со
# стандартного ввода.
# Приём материала в реестр отвечает не вердиктом, а списком того, что добавить:
# общий дефолт «СООТВЕТСТВУЕТ» для него неразбираем, и кейсы молча получали бы
# пустой реестр.
if printf '%s' "$prompt" | grep -qF 'Верни ТОЛЬКО JSON-объект'; then
  # Новая цель адресуется полем goal_new; существующая — номером в goal («Ц2»).
  # close несёт адреса задач, которые приём закрывает; у реплики и кнопки он
  # выброшен вызывающим кодом, поэтому дефолт пустой.
  default='{"add":[{"goal_new":"# Юнит тестовой цели","tasks":[{"title":"задача","where":["tests/run.sh"],"anchor":""}]}],"close":[]}'
  printf '%s\n' "${MOCK_CLASSIFIER_INGEST:-$default}"
  exit 0
fi

# Сверка правки по реестру отвечает своими формами, а не «СООТВЕТСТВУЕТ»: общий
# дефолт для неё нераспознаваем и вырождался бы в отказ на каждом кейсе.
if printf '%s' "$prompt" | grep -qF 'Ниже реестр одобренного'; then
  # MOCK_CLASSIFIER_ANSWERS — ответы ПО ОЧЕРЕДИ через «|»: ими проверяется, что
  # гейт переспрашивает отказ и решает большинством. Один ответ на все вызовы
  # такой кейс не выразит — он и на прежнем коде, спрашивавшем однажды, зеленел
  # бы. Счётчик живёт рядом со следом вызовов: у каждого прогона он свой.
  if [[ -n "${MOCK_CLASSIFIER_ANSWERS:-}" ]]; then
    turn_file="${MOCK_CLASSIFIER_TRACE:-/tmp/mock-classifier}.turn"
    turn="$(cat "$turn_file" 2>/dev/null || echo 0)"
    printf '%s' "$((turn + 1))" > "$turn_file"
    IFS='|' read -ra answers <<< "$MOCK_CLASSIFIER_ANSWERS"
    idx="$turn"
    (( idx >= ${#answers[@]} )) && idx=$(( ${#answers[@]} - 1 ))
    printf '%s\n' "${answers[$idx]}"
    exit 0
  fi
  printf '%s\n' "${MOCK_CLASSIFIER_ANSWER:-ПОКРЫТА Ц1.1: правка по одобренной задаче}"
  exit 0
fi

printf '%s\n' "${MOCK_CLASSIFIER_ANSWER:-СООТВЕТСТВУЕТ}"
