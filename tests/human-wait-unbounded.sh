#!/usr/bin/env bash
# У ожидания человека не бывает срока.
#
# Зачем проверка. Между зовом о помощи и действием человека стояло ТРИ независимых часов, и
# ни одни из них не были выбраны осознанно — все три достались по умолчанию:
#   1) ожидание человека в слое ввода сдавалось через 15 минут;
#   2) долгое ожидание в пульте отвисало через 10 минут с исходом «ожидание истекло»;
#   3) сам прогон убивался по сроку, который h.sh ставил в две минуты.
# Влад попросил, чтобы времени между зовом и его действием не было ограничено.
#
# Дефект глубже числа: машина не знает, когда человек освободится, а таймер превращает
# «ещё не пришёл» в «отказал» — исход, не различающий два разных события. Это тот же
# корень, что у правила «Признак проверки обязан различать исходы».
#
# Usage: bash tests/human-wait-unbounded.sh
#   exit 0 — ни в одном из трёх мест срока нет
#   exit 1 — срок вернулся, названо место
set -u
cd "$(dirname "$0")/.." || exit 1
export LC_ALL=C.UTF-8

found=0

# Проверки утвердительные: ищем то, что ТАМ ДОЛЖНО СТОЯТЬ. Искать отсутствие числа
# бесполезно — «без срока» само выражается числом ноль, и запрет на цифру ловил бы починку
# вместе с поломкой.

# 1. Ожидание человека в слое ввода: при отсутствии явного аргумента подставляется «без
#    срока», а не число минут.
if ! grep -q 'ms === undefined ? БЕЗ_СРОКА : ms' tools/mac/prelude.js; then
  echo "FAIL   prelude.js: у ожидания человека вернулся срок по умолчанию"
  grep -nE 'ms === undefined' tools/mac/prelude.js
  found=$((found + 1))
fi

# 2. Долгое ожидание в пульте: таймер, отдающий ответ сам по себе, — тот же срок, и исход
#    «ожидание истекло» не отличал «человек не пришёл» от поломки.
# Комментарий не код: в нём эта фраза законна и объясняет, почему срока больше нет.
if grep -nE '^[[:space:]]*[^/[:space:]].*ожидание истекло' tools/mac/capgate.js; then
  echo "FAIL   capgate.js: долгое ожидание снова сдаётся по времени"
  found=$((found + 1))
fi

# 3. Срок прогона: он убивает сессию вместе с её ожиданием. Ноль инструмент прогона не
#    принимает, а его предельное значение рвёт прогон мгновенно — секунды переполняют
#    таймер в миллисекундах. Наибольшее работающее замерено: 2147483 секунды.
if ! grep -q '^T="${2:-2147483}"' tools/mac/h.sh; then
  echo "FAIL   h.sh: срок прогона по умолчанию снова ограничен"
  grep -nE '^T=' tools/mac/h.sh
  found=$((found + 1))
fi

echo "---------------------------------------------------------------------------"
if [ "$found" -eq 0 ]; then
  echo "HUMAN-WAIT: ожидание человека без срока во всех трёх местах"
  exit 0
fi
echo "HUMAN-WAIT: мест со сроком — $found."
echo "  Ожидание человека кончается тем, что он ответил, или тем, что вкладка закрылась."
echo "  Таймер здесь делает «ещё не пришёл» неотличимым от «отказал»."
exit 1
