#!/usr/bin/env node
// PreToolUse на показе плана: не показывать Владу план, трогающий системную
// зону, пока эту его версию не обкатал критик. Правило про обкатку живёт в
// Craft, хук лишь не даёт его пропустить молча.
//
// Перехват именно на ПОКАЗЕ, а не на записи файла плана: критик читает план из
// файла, поэтому гейт на записи заблокировал бы само планирование.
//
// Судит гейт по файлу плана, записанному в этой сессии. Если файла нет,
// несистемный показ можно проверить по canonical plan text; системный план без
// проверяемого артефакта закрыт, потому что его обкатку не к чему привязать.
// Показ несёт и сам текст плана, поэтому расхождение показанного с файлом
// отклоняется отдельно и ДО проверки зоны — иначе подменой одного из двух
// проезжает любой план.
//
// Обхода по автономному режиму здесь нет намеренно: автономный прогон планов не
// показывает, а флаг-лазейка в гейте — приглашение ею воспользоваться.
//
// Неожиданное состояние артефакта закрывает показ: отсутствие доказательства
// обкатки не является разрешением.
import fs from 'node:fs';
import { readEvent } from './lib/event.js';
import { deny } from './lib/decide.js';
import { hookOnce } from './lib/once.js';
import { sha256File } from './lib/hash.js';
import { planFileMarker, planCriticMarker, planCriticRuns } from './lib/paths.js';
import { layoutPattern } from './lib/layout.js';

const { raw, event, route, input } = readEvent();
if (!hookOnce(raw, event, import.meta.url)) process.exit(0);
if (route !== 'plan.submit') process.exit(0);

function planPath() {
  if (process.env.CRAFT_PLAN_FILE) return process.env.CRAFT_PLAN_FILE;
  try {
    return fs.readFileSync(planFileMarker(), 'utf8').trim();
  } catch {
    return '';
  }
}

const plan = planPath();
let text = '';
try {
  text = fs.readFileSync(plan, 'utf8');
} catch { /* ниже используется показанный canonical text */ }

function touchesSystemPlan(value) {
  const fields = value.split('\n').filter((line) => !/^\s*>/.test(line));
  return fields.some((line) => /^\s*#+\s*\[система/i.test(line))
    || fields.some((line) => /^\s*-\s*где:/i.test(line) && layoutPattern('planSystemPattern').test(line));
}

// Показанное против записанного. Хвостовые переводы строки не считаются
// расхождением: их съедала подстановка у bash-версии, и обычный показ проходил.
const shown = input.plan || '';
if (!text) {
  if (!shown) deny('Показ плана заблокирован: нет ни проверяемого артефакта плана, ни canonical текста. Адаптер должен передать одно из них; отсутствие данных остаётся fail-closed.');
  if (touchesSystemPlan(shown)) deny('Системный план нельзя показать без проверяемого артефакта: обкатку plan-critic не к чему криптографически привязать. Адаптер должен сохранить и передать основной артефакт плана.');
  process.exit(0);
}
if (shown && shown.replace(/\n+$/, '') !== text.replace(/\n+$/, '')) {
  deny('Показываемый план не совпадает с файлом плана. Гейт судит по файлу: запиши в него нынешний текст и прогони критика по нему, либо покажи то, что записано.');
}

// Системная зона: core, provider adapters, правила и bootstrap-файлы. Триггер намеренно
// шире источника — точечная правка системной зоны по дословной формулировке
// Влада проходит без критика, а машинного различителя «дословно от Влада»
// против «сочинил агент» нет.
//
// Читаются ПОЛЯ плана — строки, не начатые знаком цитаты: заголовок юнита и
// строка адреса. Дословный текст живёт в цитатном блоке, поэтому его двойники
// полей сюда не попадают. Вырезателя код-блоков нет намеренно: любой разбор
// заборов обманывается вложенностью и глушит гейт молча, а лишний вызов критика
// дёшев.
const touchesSystem = touchesSystemPlan(text);
if (!touchesSystem) process.exit(0);

const markFile = planCriticMarker();
const want = sha256File(plan);
let mark = '';
try {
  mark = fs.readFileSync(markFile, 'utf8').trim();
} catch { /* отметки нет — обкатки не было */ }

// Отметка — «хеш<таб>вердикт»; голая отметка старого вида читается тем же полем.
const [have, verdict] = mark.split('\t');
if (want && want === have) process.exit(0);

// Вердикт «блокеров нет» разрывает самоинвалидацию: критик сказал, что держащих
// показ замечаний нет, значит правка шероховатостей после него круга не стоит —
// показ проходит, хотя хеш разошёлся. Поблажка ОДНОРАЗОВАЯ: вердикт тут же
// снимается, остаётся голый хеш. Иначе один вердикт открывал бы любой
// последующий текст в этом файле.
if (verdict === 'noblockers') {
  try {
    fs.writeFileSync(markFile, `${have}\n`);
  } catch { /* не записалось — в худшем случае поблажка сработает ещё раз */ }
  process.exit(0);
}

// Машинное «плато». Одобрение критика самоинвалидирующееся по устройству:
// отметка стоит на хеше файла, а работа критика — выдать замечания, выполнение
// которых этот хеш меняет. Без условия завершения контур уходит в круг
// «критик → правка → отказ». Три завершённых прогона — потолок.
let runs = '';
try {
  runs = fs.readFileSync(planCriticRuns(), 'utf8').trim();
} catch { /* счётчика нет */ }
if (/^[0-9]+$/.test(runs) && Number(runs) >= 3) process.exit(0);

deny('План трогает системную зону (core, adapter, правило, скилл, хук или bootstrap), а plan-critic эту его версию не обкатывал. Два законных пути: либо отработай замечания и прогони критика ЗАНОВО по новому тексту, либо, если правок не делал, просто прогони критика по нынешнему файлу. Показ идёт сразу после прогона: любая правка плана после него снова обесценивает обкатку. Три прогона по одному разговору — плато: гейт пропустит показ, и план показывается как есть с открытым вопросом о застрявших местах.');
