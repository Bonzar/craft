#!/usr/bin/env node
// Stop hook: детектор несброшенных наблюдений. Сам НИЧЕГО не дистиллирует и не
// пишет в Craft (хук этого не может) — при непустом сигнальном буфере блокирует
// завершение хода директивой агенту: дистиллируй кандидатов и сбрось их в
// «Наблюдения» дока «Инстинкты агента», затем очисти буфер.
//
// Запись кандидатов проходит план-гейт без плана: док в предодобренных зонах
// (gate-exempt-pages.txt), исключение закреплено в «Обслуживании памяти».
// Анти-цикл: stop_hook_active в событии → молчим (не блокируем собственный
// повторный Stop). Fail quiet.
//
// Уступки второму вызову здесь нет намеренно, как и у bash-версии: блок и так
// одноразовый по признаку буфера, а повторный Stop проходит.
import fs from 'node:fs';
import { readEvent } from './lib/event.js';
import { block } from './lib/decide.js';
import { observeBuffer } from './lib/paths.js';

// Headless-евалы исключены признаком CRAFT_EVAL=1, как и у stop-routine-facts:
// в прогоне пишущих инструментов нет, требование «очисти буфер» невыполнимо, и
// агент тратит ходы на обходные пути вместо измеряемой задачи.
// Служебный вложенный вызов (классификатор план-гейта) исключён по той же причине,
// что и евал: у него нет ни рутины, ни диалога с Владом, он живёт один ход и
// возвращает одну строку — лишний ход от блокировки роняет сам вызов.
if (process.env.CRAFT_EVAL || process.env.CRAFT_NESTED_CALL) process.exit(0);

const { event } = readEvent();
if (event.stopActive === true || process.env.CRAFT_STOP_HOOK_ACTIVE === 'true') {
  process.exit(0);
}

const buf = observeBuffer();
let size = 0;
try {
  size = fs.statSync(buf).size;
} catch { /* буфера нет — сбрасывать нечего */ }
if (size === 0) process.exit(0);

const observations = process.env.CRAFT_OBSERVATIONS_PAGE_ID || '11126344-32e1-8c47-81d2-9079eac43f1f';

block(`[stop-hook] В сигнальном буфере сессии есть неразобранные наблюдения (${buf}). Перед завершением хода: 1) прочитай буфер; 2) выдели из него ПОВТОРЯЕМЫЕ паттерны и дистиллируй кандидатов формата «[скоуп] при [сигнале] → [действии]» (скоуп — слаг проекта или global; только дистиллят, без сырых логов; разовые нерепрезентативные ошибки — пропусти); 3) добавь каждого кандидата отдельным блоком в КОНЕЦ страницы «Наблюдения» дока «Инстинкты агента» (Craft, block-ID ${observations}, position end — только append, чужие блоки не трогать); Craft недоступен — просто пропусти шаг записи; 4) очисти буфер (rm файла). Ничего достойного кандидата нет — тоже просто очисти буфер.`);
