=== ПРАВКА ===
$change"
    ;;
  *) echo "UNAVAILABLE"; exit 0 ;;
esac

# Один вызов модели. Системный промпт заменяется коротким, чтобы вложенный
# вызов не наследовал лишний контекст харнесс-сессии и не раскачивал разметку.
ask() {
  if [[ -n "${PLAN_CLASSIFIER_CMD:-}" ]]; then
    cd /tmp && printf '%s' "$prompt" | timeout "$budget" env \
      CRAFT_AUTONOMOUS=1 CRAFT_NESTED_CALL=1 "$PLAN_CLASSIFIER_CMD" 2>/dev/null
    return
  fi
  here="$(cd "$(dirname "$0")" && pwd)"
  cd /tmp && printf '%s' "$prompt" | timeout "$budget" env \
    CRAFT_AUTONOMOUS=1 CRAFT_NESTED_CALL=1 \
    CRAFT_CLASSIFIER_MODE="$mode" \
    CRAFT_CLASSIFIER_TURNS="$turns" CRAFT_CLASSIFIER_TOOLS="$tools" \
    CRAFT_CLASSIFIER_SYSTEM_PROMPT="$sysprompt" PLAN_CLASSIFIER_TIMEOUT="$budget" \
    node "$here/invoke.mjs"
}

answer="$(ask)" || { echo "UNAVAILABLE"; exit 0; }

# Разбор материала отдаёт структуру, а не вердикт: печатаем JSON целиком. Модель
# любит обрамлять его забором — снимаем и проверяем разбираемость: невалидный
# ответ должен вырождаться в UNAVAILABLE, а не приезжать в реестр мусором.
if [[ "$mode" == "ingest" ]]; then
  json="$(sed -e '/^[[:space:]]*```/d' <<<"$answer")"
  here="$(cd "$(dirname "$0")" && pwd)"
  if normalized="$(printf '%s' "$json" | node "$here/validate-ingest.mjs" 2>/dev/null)"; then
    printf '%s\n' "$normalized"
  else
    echo "UNAVAILABLE"
  fi
  exit 0
fi

# Решение обязано занимать ровно одну строку. Выбор «последней подходящей» из
# объяснения превращал многострочный невалидный ответ в разрешение.
if [[ "$answer" == *$'\n'* ]]; then
  echo "UNAVAILABLE"
  exit 0
fi
last="$answer"
case "$mode" in
  preflight)
    case "$last" in
      "ALLOW_READ:"?*) printf '%s\n' "$last" ;;
      "ALLOW_SESSION:"?*) printf '%s\n' "$last" ;;
      "ALLOW_EPHEMERAL:"?*) printf '%s\n' "$last" ;;
      "CHECK_REGISTRY:"?*) printf '%s\n' "$last" ;;
      "DENY:"?*) printf '%s\n' "$last" ;;
      *) echo "UNAVAILABLE" ;;
    esac ;;
  delta)
    # «Повторяет всё» проверяется ПЕРВЫМ: перепоказ того же плана законен, а
    # частичный повтор — нет, и спутать их значит отбить показ, который правила
    # прямо разрешают.
    case "$last" in
      "REPEATSALL"|"CLEAN"|"REPEATS:"?*) printf '%s\n' "$last" ;;
      "ПОВТОРЯЕТ ВСЁ") echo "REPEATSALL" ;;
      "ПОВТОРЫ: "?*) printf 'REPEATS:%s\n' "${last#ПОВТОРЫ: }" ;;
      "ДЕЛЬТА ЧИСТАЯ") echo "CLEAN" ;;
      *) echo "UNAVAILABLE" ;;
    esac ;;
  cover)
    # Порядок сверки значим: «НЕ ПОКРЫТА» содержит «ПОКРЫТА» подстрокой, а
    # «РАЗРЕШЕНО ПОВЕРХ» — «ЗАПРЕЩЕНО» не содержит, но оба про запрет, и
    # разрешающая форма обязана проверяться раньше запрещающей.
    case "$last" in
      "OVERRIDE:"?*|"FORBIDDEN:"?*|"UNCOVERED:"?*|"COVERED:"?*|"DRAFT") printf '%s\n' "$last" ;;
      "РАЗРЕШЕНО ПОВЕРХ "?*) printf 'OVERRIDE:%s\n' "${last#РАЗРЕШЕНО ПОВЕРХ }" ;;
      "ЗАПРЕЩЕНО "?*) printf 'FORBIDDEN:%s\n' "${last#ЗАПРЕЩЕНО }" ;;
      "НЕ ПОКРЫТА: "?*) printf 'UNCOVERED:%s\n' "${last#НЕ ПОКРЫТА: }" ;;
      "ПОКРЫТА "?*) printf 'COVERED:%s\n' "${last#ПОКРЫТА }" ;;
      "ЧЕРНОВОЕ") echo "DRAFT" ;;
      *) echo "UNAVAILABLE" ;;
    esac ;;
esac
exit 0
