    # кнопочный вопрос, реплика Влада. На входе — что уже лежит в реестре и
    # новый материал; на выходе — что в реестр добавить и что в нём закрыть.
    #
    # Структуру решает разбор, а не форма документа: сколько целей, сколько
    # задач и на каком уровне вложенности — вопрос смысла. Заголовки и отступы
    # для этого не критерий, план каждый раз свёрстан по-своему.
    #
    # Здесь же семантическая дедупликация: материал про уже одобренную цель
    # ложится НОВОЙ ЗАДАЧЕЙ под неё, а не второй целью рядом; то, что уже есть
