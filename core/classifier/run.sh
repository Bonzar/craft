#!/usr/bin/env bash
# Классификатор план-гейта: LLM-проверка, которую регулярка дать не может.
# Общие prompts и строгий разбор живут здесь; транспорт, CLI-флаги и модели
# изолированы во внешнем адаптере.
#
# Режимы (первый аргумент), описание правки — на stdin:
#   preflight — классифицировать любой не доказанный как чтение вызов;
#   cover <реестр> — покрыта ли правка одобренным: пять исходов;
#   delta <одобренное> <новый план> — повторяет ли план уже принятое;
#   ingest <реестр> <материал> <источник> — разложить материал в цели и задачи.
#
# Ответ одной строкой в stdout:
#   OVERRIDE:<цель> | FORBIDDEN:<причина> | COVERED:<адрес> | DRAFT
#   | UNCOVERED:<причина> | REPEATSALL | REPEATS:<заголовки> | CLEAN | UNAVAILABLE
#
# Исключение — ingest: он отдаёт JSON, а не вердикт. Разложенный материал в одну
# строку не передать; нераспознанный ответ там так же вырождается в UNAVAILABLE.
# Разбор ответа модели сверяет СНАЧАЛА отрицательную форму: положительная
# («СООТВЕТСТВУЕТ») входит в отрицательную («НЕ СООТВЕТСТВУЕТ») подстрокой.
#
# Вложенный вызов выбирает конфигурация адаптера. Общий слой задаёт только
# контракт, число ходов, набор инструментов и fail-closed разбор.
#
# Второй признак обязателен и не выводится из первого: автономный режим гейты
# глушит, но ВКЛЮЧАЕТ стоп-хуки рутин, а их блокировка добавляет ход — вызов
# с --max-turns 1 падает, и классификатор молча вырождается в UNAVAILABLE. Таймаут, обрыв и нераспознанный ответ = UNAVAILABLE — решение о
# судьбе правки принимает гейт, не помощник.
#
# Env: PLAN_CLASSIFIER_CMD — команда модели (тесты подменяют моком);
#      PLAN_CLASSIFIER_TIMEOUT — страховка от зависшего вызова, секунды. Своего
#        потолка у проверок нет: у каждого режима своё число, и общий дефолт
#        такой же большой — новый режим не должен унаследовать короткий срок
#        молча. Прежние 20 секунд достались от однопроходных режимов, которых
#        больше нет, и на них спотыкались живые проверки;
#      PLAN_CLASSIFIER=off — принудительный UNAVAILABLE (аварийный выключатель).
