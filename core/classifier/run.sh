    prompt="Ниже реестр одобренного — цели и задачи, на которые Влад дал ок, — и одна правка. Тебе доступно чтение файлов: если смысл правки без окружения не читается, открой файл, куда она ложится, и посмотри сам. Ответь ровно одной строкой.

ЗАПРЕЩЕНО ‹Ц›: ‹цитата› — если запись, ПОМЕЧЕННАЯ СЛОВОМ ЗАПРЕТ в своей строке, запрещает эту правку и более позднего разрешения именно её в реестре нет. Записи, помеченные словом «работа», запретом не бывают НИКОГДА — ни их заголовок, ни текст, ни тела задач под ними: там лежит материал, из которого работа и выросла, включая недовольные реплики Влада вроде «это не ок, поправь». Такая реплика поручает работу, а не запрещает её.
РАЗРЕШЕНО ПОВЕРХ ‹Ц› — если такой запрет есть, но позже Влад прямо разрешил именно эту правку.
ПОКРЫТА ‹Ц.З›: ‹что сделано одной фразой› — если правка выполняет то, что обещано этой задачей. Правка, делающая ЧАСТЬ задачи, покрыта: задача почти всегда требует нескольких правок, и «не выполняет задачу целиком» причиной отказа НЕ БЫВАЕТ. Покрыты и правки вокруг работы: комментарий, документация, тест, кейс, отладочная печать по ходу этой задачи — часть той же работы, а не «изменение без функциональности». Работа под задачей уже выглядит сделанной, а правка её дополняет — всё равно покрыта: закрывает задачу агент, а не сверка. Кейс или тест, написанный ДО реализации, покрыт: так требует дисциплина работы — проверка заводится красной и только потом чинится код, — и «кейс без реализации» причиной отказа не бывает. Правка, опирающаяся на функцию или файл, которых ещё нет, покрыта по той же причине: ход состоит из нескольких правок, и порядок внутри него сверку не касается. Файл, не названный в адресах задачи, покрытию не мешает — задача вида «во всех местах использования» адресов не перечисляет. Покрытие даёт ЛЮБАЯ открытая задача, а не первая незакрытая: порядок задач в реестре — это порядок показа, а не обязательство. Агент вправе взяться за третью задачу раньше первой, и «предыдущие задачи ещё не закрыты» причиной отказа НЕ БЫВАЕТ.
Задача со словом «закрыта» покрытием НЕ БЫВАЕТ: работа под ней уже кончилась, а текста у неё не осталось. Имя такой задачи совпало со смыслом правки — это НЕ ПОКРЫТА с причиной «работа по задаче Ц‹номер› закрыта; она не доделана — верни её в работу командой registry.mjs reopen Ц‹номер›». Про саму ЦЕЛЬ этого правила нет: цель со всеми закрытыми задачами живая — под ней просто нет открытой работы, и покрытие даёт её открытая задача, когда она появится.

ЧЕРНОВОЕ — отладочная печать, временный файл рядом с работой, закомментированный на пробу блок.
НЕ ПОКРЫТА: ‹причина одним предложением› — во всех прочих случаях.

