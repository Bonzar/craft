    # времянка), и правка сверялась то с одним, то с другим.
    regfile="${2:-}"
    [[ -n "$regfile" && -r "$regfile" ]] || { echo "UNAVAILABLE"; exit 0; }
    # Сверку ведёт агент, а не однопроходный вопрос: смысл правки часто виден
    # только из файла, куда она ложится, и по куску текста его не прочесть.
    # Инструменты — только читающие, ходов несколько.
    turns=8
    tools="file.read,text.search,file.list"
    # Своего потолка у сверки нет: ждём решения, сколько бы оно ни заняло.
    # Число здесь — страховка от зависшего вызова, а не бюджет проверки.
