    budget="${PLAN_CLASSIFIER_TIMEOUT:-1800}"
    # Закрытия спрашиваются только у ОДОБРЕННОГО ПЛАНА: новый план и есть граница
    # работы. Реплика границей не является — самые частые реплики Влада
    # («продолжай», «работай») значат ровно обратное, работа идёт. Вызывающий код
    # закрытия от прочих источников ещё и выбрасывает: одного промпта тут мало.
    closerules=""
    if [[ "$source" == "plan" ]]; then
      closerules="— В close перечисли адреса задач вида Ц1.2, про которые САМ МАТЕРИАЛ говорит, что работа кончена: новый план помечает кусок сделанным, ревизией или снятым. Строки «сделано:» в логе цели основанием НЕ ЯВЛЯЮТСЯ: лог пишется по каждой правке, а задача почти всегда делается несколькими — по одной записи в логе работа выполненной не становится. Нет таких — пустой массив. Задачи, которые ты добавляешь этим же ответом, в close не попадают никогда.
"
    fi
    prompt="Ниже реестр уже одобренного и новый материал. Верни ТОЛЬКО JSON-объект, без пояснений.

{\"add\":[{\"kind\":\"work или ban\",\"goal\":\"Ц2 — номер цели из реестра, если материал про неё\",\"goal_new\":\"заголовок, если цель новая\",\"tasks\":[{\"title\":\"имя задачи\",\"where\":[\"адреса\"],\"anchor\":\"первая строка текста задачи дословно\"}]}],\"close\":[\"Ц1.2\"],\"lift\":[\"Ц2\"]}

